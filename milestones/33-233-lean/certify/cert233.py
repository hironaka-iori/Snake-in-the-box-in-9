def key_sets(a):
    """new plain keys, h8 keys, share keys, reused keys {key: window module}, chain chunks."""
    chunks, h8, share = chain_keys()
    wins = old_windows()
    plain = [k for ch in chunks for k in ch]
    reused = {k: next(w[k] for w in wins if k in w) for k in plain if any(k in w for w in wins)}
    new = [k for k in plain if k not in reused]
    assert not any(k in w for w in wins for k in h8)
    if a.keys_from:
        s = json.load(open(a.keys_from))
        want = {(tuple(d), tuple(x)) for d, x in s.get('plain', [])}
        new = [k for k in new if k in want]
        h8 = [k for k in h8 if k in {(tuple(d), tuple(x)) for d, x in s.get('h8', [])}]
        share = [k for k in share if k in {(tuple(d), tuple(x), c) for d, x, c in s.get('share', [])}]
        if 'reused' in s:
            want = {(tuple(d), tuple(x)) for d, x in s['reused']}
            reused = {k: w for k, w in reused.items() if k in want}
    return new, h8, share, reused, chunks


