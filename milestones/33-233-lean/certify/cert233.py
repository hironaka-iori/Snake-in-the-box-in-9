def lst(c):
    return '[' + ', '.join(map(str, c)) + ']'


def proof_term(k, pl, core):
    """(term of `Refuted (winOf ds) (boundsOf syms)`, certificate module) of a new key."""
    e = pl[k]
    if e[0] == 'self':
        m = pname(k)
        cert = f'(Tags.refuted_of_sat {m}.sat {m}.unsat)'
        if [tuple(x) for x in e[1]] == [tuple(x) for x in GC.dir_bounds(k[1])]:
            return cert[1:-1], m
        return f'Families.refuted_key_of_wide {cert}\n    (by decide +kernel)', m
    sk, meth, v, s = e
    sm = pname(sk)
    wide = pl[sk][1]
    seed = (None, list(sk[0]), list(sk[1]))
    dv = FK.derivable(seed, [tuple(x) for x in wide], (None, list(k[0]), list(k[1])))
    assert dv is not None, (k, sk)
    if meth == 'L1':
        assert FK.wider_b([tuple(x) for x in wide], FK.bounds_of(k[1]))
    else:
        assert FK.subok(v, s, FK.win_of(sk[0]), [tuple(x) for x in wide], FK.win_of(k[0]), FK.bounds_of(k[1]))
    cert = f'(Tags.refuted_of_sat {sm}.sat {sm}.unsat)'
    if meth == 'L1':
        return f'Families.refuted_key_of_wide {cert}\n    (by decide +kernel)', sm
    return f'Families.refuted_key_sub (mkPerm {lst(v)}) {s}\n    {cert}\n    (by decide +kernel)', sm


