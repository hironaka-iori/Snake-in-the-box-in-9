"""Certificates of the share-weighted six-centre 233 chain (tag B233): the two premises
`AllRefuted6SB233` and `AllRefutedShare6SB233` of `Snake9.Floors233Port.upper_233_of_certs6SB233`.

The key lists are those of `work/final_lean/LocalWindowDirKeys6SB233.lean` (generated by
`milestones/33-233-lean/scripts/gen_lean_automaton6s.py` from
`milestones/31-233-cost/data/keys233_best.json.gz`):

* `dirKeys6SB233` (19 chunks): plain k6 keys `Refuted (winOf ds) (boundsOf syms)`.  The keys that
  are keys of `dirKeysR4b` (237), `dirKeysR4` (236) or `dirKeysK6` (235) are *reused*: proved from
  their window modules (`LocalWindowSat.W`, `LocalWindowUnsat.W`) as `gen_lean_glue7.py reuse` does;
  the others are *new*;
* `h8Keys6SB233`: 262 H8 keys (8 directions, 6 counts, the last interior vertex uncounted), new,
  the same certificate type and the same encoding as the H9 keys of milestones/25-k7-234;
* `shareKeys6SB233`: 490 share thresholds `RefutedShare (winOf ds) (boundsOf syms) 12 K`.

Pipeline (milestones/25-k7-234/certify is the template: gen_k7_core.py, replay_k7.py, families_k7.py):

  cores   per new plain/H8 key (module prefix `S`): the radius-4 CNF (`gen_k7_core.encoding`)
          with the lazy cycle cuts, its core (CaDiCaL `--unsat`, trimmed), the counters the core
          uses and so the widened bounds `wide` (`families_k7.wide_bounds`).  Per share key
          (prefix `T`): the share CNF of `share233.TaggedShare` (cap K, M = 12) with its cuts, and its
          core.  One gzipped JSON per key in --core (default
          milestones/10-window-aggregate/data/lean_core_direction_6s); no CNF or proof is kept.
  plan    the seeds and families (milestone 30, L1 `refuted_key_of_wide`, L2 `refuted_key_sub`):
          a weighted greedy cover of the new plain/H8 keys by the widened cores, every derivation
          checked by the exact mirror `families_k7.derivable`; `data/seeds6SB233.json.gz`.
  cnf     the packed core + clause-soundness module `LocalWindowCnf/<M>.lean` of each seed (Sat v2,
          `gen_lean_cnfsat_packed.emit --sat-v2 --part-lits`, `bounds` = the widened bounds) and of
          each share key (`emit_share`: `TagsSW.checkAllS`, flat tables `TagsW.getF`/`TagsSW.getSF`,
          checked in parts; the core is renumbered compactly).
  replay  `LocalWindowUnsat/<M>.lean` per seed and share key: the checker v3 (`LratV3`,
          `gen_lean_lrat_v3.py`, seg 60k); proofs of 8 seeds x 5 rounds for cores of at least
          --big hints, else 2 seeds x 1 round; `--warm 32` (cache warm-up of `raw` and of earlier
          segments before a check that jumps far into them: else the kernel's stack overflows).
  final   `LocalWindowDirKeysN6SB233` (the new keys in chunks), `LocalWindowDirUnsatN6SB233_<c>`
          (each new key from its seed by L1/L2 or its own certificate; `Elab.async false`),
          `LocalWindowDirKeysR6SB233` / `LocalWindowDirUnsatR6SB233` (the reused keys from their
          window modules), `LocalWindowDirUnsat6SB233` (`allRefuted6SB233 : AllRefuted6SB233`, one
          kernel `mergeOK` per chunk of the chain, `AllRefutedSrcs.flatten`), and
          `LocalWindowShareUnsat6SB233` (`allRefutedShare6SB233 : AllRefutedShare6SB233`, one
          `Tags.refutedShare_of_sat` per share key, in chunk theorems).

  nice -n 10 python3 cert233.py cores [--kinds plain,h8,share] [--shard i/n] [--only NAME ...]
  python3 cert233.py plan
  python3 cert233.py cnf    [--kinds seed,share] [--limit N] [--budget-hints H] [NAME ...]
  nice -n 10 python3 cert233.py replay [--kinds seed,share] [--limit N] [--budget-hints H] [NAME ...]
  python3 cert233.py final [--sample]
  python3 cert233.py status

`--keys-from F` (a JSON {plain: [[ds, syms]...], h8: [...], share: [[ds, syms, K]...]}) restricts
every step to a sample (the end-to-end validation).  Every step resumes: a key whose output exists
is skipped.
"""
