def emit_share(meta, out):
    """`LocalWindowCnf/<T…>.lean`: the renumbered share core, its meanings and tags, and
    `sat : ∀ S E, AxiomsS S E window (centresOf window bounds) 12 cap → ∃ τ, cnfTrue τ cnf = true`
    by `TagsSW.soundS` (checked in parts: counters, totalizers, clause parts)."""
    enc, ren, core, tags, used_c = share_regen(meta)
    name = meta['name']
    rl = lambda x: (1 if x > 0 else -1) * ren[abs(x)]   # noqa: E731
    code = lambda x: GS.code(rl(x))                      # noqa: E731
    raw = [[code(x) for x in c] for c in core]
    nv = len(ren)
    old = {ren[x]: v for x, v in enc.meaning.items() if x in ren}
    new = {ren[x]: v for x, v in enc.smeaning.items() if x in ren}
    ctr_lists = [[CP.kind_code(kind), kk] + [code(l) for l in lits] if ci in used_c else [0, 2]
                 for ci, (lits, kk, kind) in enumerate(enc.ctrs)]
    w = bl(max(x for l in raw + ctr_lists for x in l))
    assert max(len(c) for c in raw) < 256
    # window meanings: the flat table of TagsW.getF (gen_lean_cnfsat_packed.pack_table)
    ms = list(old.values())
    otags = [t[1] for t in tags if t[0] == 'old']
    vw = bl(max([m[1] for m in ms if m[0] in ('p', 'e')] + [0]))
    rs = [m[1:] for m in ms if m[0] == 'r'] + [t[1:] for t in otags if t[0] in ('first', 'zero', 'mono', 'step', 'over')]
    cw = bl(max([r[0] for r in rs] + [0]))
    iw = bl(max([r[1] for r in rs if len(r) == 3] + [t[2] for t in otags if t[0] in ('first', 'over', 'mono', 'step')] + [0]))
    jw = bl(max([r[2] for r in rs if len(r) == 3] + [t[2] for t in otags if t[0] == 'zero'] +
                [t[3] for t in otags if t[0] in ('mono', 'step')] + [0]))
    mtab, mw = CP.pack_table(old, set(old), vw, cw, iw, jw)
    assert CP.unpack_table(mtab, mw, cw, iw, range(nv + 1)) == {x: tuple(v) for x, v in old.items()}
    # share meanings: the flat table of TagsSW.getSF (layout of satv2_convert_share.py)
    X = new
    qw = bl(max([m[1] for m in X.values() if m[0] in ('sq', 'u')] + [0]))
    aw = bl(max([m[2] for m in X.values() if m[0] == 'sq'] + [m[3] for m in X.values() if m[0] == 'sq'] +
                [m[2] for m in X.values() if m[0] == 'u'] + [0]))
    iw2 = bl(max([m[1] for m in X.values() if m[0] == 't'] + [0]))
    hw = bl(max([max(m[2], m[3]) for m in X.values() if m[0] == 't'] + [0]))
    ccw = bl(max([m[4] for m in X.values() if m[0] == 't'] + [0]))
    WX = 2 + max(qw + 2 * aw, qw + aw, iw2 + 2 * hw + ccw)
    TX = 0
    for x, m in X.items():
        if m[0] == 'sq':
            c = 1 | m[1] << 2 | m[2] << (2 + qw) | m[3] << (2 + qw + aw)
        elif m[0] == 'u':
            c = 3 | m[1] << 2 | m[2] << (2 + qw)
        else:
            c = 2 | m[1] << 2 | m[2] << (2 + iw2) | m[3] << (2 + iw2 + hw) | m[4] << (2 + iw2 + 2 * hw)
        assert c < 1 << WX
        TX |= c << (x * WX)
    for x, m in X.items():      # mirror of TagsSW.leafSF / getSF
        f = (TX >> (x * WX)) & ((1 << WX) - 1)
        k_ = f & 3
        if k_ == 1:
            got = ('sq', (f >> 2) & ((1 << qw) - 1), (f >> (2 + qw)) & ((1 << aw) - 1), f >> (2 + qw + aw))
        elif k_ == 3:
            got = ('u', (f >> 2) & ((1 << qw) - 1), f >> (2 + qw))
        else:
            got = ('t', (f >> 2) & ((1 << iw2) - 1), (f >> (2 + iw2)) & ((1 << hw) - 1),
                   (f >> (2 + iw2 + hw)) & ((1 << hw) - 1), f >> (2 + iw2 + 2 * hw))
        assert got == tuple(m), (x, m, got)
    for x in range(nv + 1):
        if x not in X:
            assert (TX >> (x * WX)) & ((1 << WX) - 1) == 0 or x in X
    # tags: 48-bit codes of Tags.tagOfS, chunks of at most 64 (Tags.tagsOfSL)
    OLDK = ['window', 'deg2', 'degPos', 'endSel', 'lowEnd', 'endLow', 'cut', 'first', 'zero', 'mono', 'step', 'over']

    def tcode(t):
        if t[0] == 'old':
            o = t[1]; k_ = OLDK.index(o[0]); c = i = j = 0
            if o[0] == 'lowEnd':
                c = o[1]
            elif o[0] in ('first', 'over'):
                c, i = o[1], o[2]
            elif o[0] == 'zero':
                c, j = o[1], o[2]
            elif o[0] in ('mono', 'step'):
                c, i, j = o[1], o[2], o[3]
        else:
            k_ = {'emptyE': 12, 'totUp': 13, 'totDown': 14, 'shareCl': 15, 'shareCap': 16}[t[0]]
            c = i = j = 0
            if t[0] in ('totUp', 'totDown', 'shareCap'):
                c = t[1]
            elif t[0] == 'shareCl':
                i, j = t[1], t[2]
        assert c < 256 and i < 65536 and j < 65536, t
        return k_ | c << 5 | i << 13 | j << 29

    def tchunks(ts):
        cs = []
        for s in range(0, len(ts), 64):
            g = ts[s:s + 64]
            st = 0
            for n_, t in enumerate(g):
                st |= tcode(t) << (48 * n_)
            cs.append(len(g) | st << 8)
        return cs
    # totalizers: Tot ⟨lits, kind⟩, the literals by Tags.natsOf (24 bits each)

    def tot_txt(lits, kind):
        cl = [code(x) for x in lits]
        assert all(c < 1 << 24 for c in cl)
        st = sum(c << (24 * i) for i, c in enumerate(cl))
        if kind[0] == 'cap':
            kt = '(.cap [%s])' % ', '.join('[%s]' % ', '.join('(%d, %d)' % p for p in cs) for cs in kind[1])
        else:
            kt = '(.%s %d)' % kind
        return '⟨Tags.natsOf %d (nat_lit 0x%x), %s⟩' % (len(cl), st, kt)
    # the cap totalizer grows with the cap; its clauses fill the kernel caches of their declaration
    parts = CP.clause_parts(core, 4000 if meta['cap'] < 24 else SHARE_PART_LITS if meta['cap'] < 60 else SHARE_PART_LITS // 2)
    np_ = len(parts)
    raw_ps = [CP.pack_lists(raw[s:e], 8, w, 4096) for s, e in parts]
    assert sum((CP.unpack_lists(c, 8, w) for c in raw_ps), []) == raw
    ctr_cs = CP.pack_lists(ctr_lists, 16, w, 4096)
    assert CP.unpack_lists(ctr_cs, 16, w) == ctr_lists

    def lits(cs):
        return '[\n' + ',\n'.join('  nat_lit 0x%x' % c for c in cs) + ']'

    def nm(base, i):
        return base if np_ == 1 else '%s_%d' % (base, i)

    def app(base):
        t_ = nm(base, np_ - 1)
        for i in reversed(range(np_ - 1)):
            t_ = '%s ++ (%s)' % (nm(base, i), t_) if i < np_ - 2 else '%s ++ %s' % (nm(base, i), t_)
        return t_
    dirs, syms, cap = meta['dirs'], meta['syms'], meta['cap']
    ns = 'Snake9.LocalWindow.' + name
    L = ['import LocalWindowDirModel', 'import LocalWindowCnfPack', 'import LocalWindowTagsSW',
         'import LocalWindowTagsSharePacked', '',
         '/-! UNSAT core of the share threshold `%s` (generated by `%s`): %d of the %d clauses of the\n'
         'static-cap share CNF (`share233.TaggedShare`, regenerated from\n'
         '`milestones/10-window-aggregate/data/lean_core_direction_6s/%s.json.gz`), in their original\n'
         'order, variables renumbered compactly.  Directions `%s`, lumped counts `%s`, resolution 12, cap %d:\n'
         '`sat` with the replay `unsat` gives `RefutedShare window bounds 12 %d` (`Tags.refutedShare_of_sat`),\n'
         'i.e. the share sum of the five centres is at least %d.  `check` is proved in %d kernel evaluations\n'
         '(`TagsSW.checkAllS_of_parts`, `TagsSW.ckAllS_append`). -/'
         % (name, ME, len(core), meta['full_clauses'], name, dirs, syms, cap, cap, cap + 1, np_ + 2), '',
         'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0', 'set_option Elab.async false', '',
         'namespace ' + ns, '', 'open Snake9.LocalWindow.Tags', '',
         'noncomputable def window : List Nat := winOf %s' % dirs,
         'noncomputable def bounds : List (Nat × Nat) := boundsOf %s' % syms,
         'noncomputable def resolution : Nat := %d' % MRES,
         'noncomputable def cap : Nat := %d' % cap, '']
    for i in range(np_):
        L += ['noncomputable def %s : List (List Nat) := CnfPack.unpackL 8 %d %s' % (nm('raw', i), w, lits(raw_ps[i])), '']
    if np_ > 1:
        L += ['noncomputable def raw : List (List Nat) := %s' % app('raw'), '']
    L += ['noncomputable def cnf : List (List Int) := raw.map (·.map decodeLit)', '',
          'noncomputable def mtab : Nat := nat_lit 0x%x' % mtab,
          'noncomputable def meaning : Nat → MT := TagsW.getF mtab %d %d %d' % (mw, cw, iw), '',
          'noncomputable def stab : Nat := nat_lit 0x%x' % TX,
          'noncomputable def smeaning : Nat → MS := TagsSW.getSF stab %d %d %d %d %d' % (WX, qw, aw, iw2, hw), '',
          'noncomputable def ctrs : List Ctr := CnfPack.ctrsOf (CnfPack.unpackL 16 %d %s)' % (w, lits(ctr_cs)), '',
          'noncomputable def tots : List Tot := [\n  ' + ',\n  '.join(tot_txt(l_, k_) for l_, k_ in enc.tots) + ']', '']
    for i, (s, e) in enumerate(parts):
        L += ['noncomputable def %s : List TagS := Tags.tagsOfSL %s' % (nm('tags', i), lits(tchunks(tags[s:e]))), '']
    if np_ > 1:
        L += ['noncomputable def tags : List TagS := %s' % app('tags'), '']
    L += ['theorem check_ctrs : TagsW.allK (TagsW.ctrOKK meaning (centresK window bounds)) ctrs = true := by decide +kernel', '',
          'theorem check_tots : tots.all (TagsSW.totOK meaning smeaning window (centresK window bounds)) = true := by decide +kernel', '']
    for i, (s, e) in enumerate(parts):
        L += ['/-- Core clauses %d to %d (%d literals). -/' % (s + 1, e, sum(map(len, core[s:e]))),
              'theorem check_%d : TagsSW.ckAllS meaning smeaning resolution ctrs tots window cap %s %s = true := by decide +kernel'
              % (i, nm('tags', i), nm('raw', i)), '']
    term = 'check_%d' % (np_ - 1)
    for i in reversed(range(np_ - 1)):
        term = 'TagsSW.ckAllS_append meaning smeaning resolution ctrs tots window cap %s %s _ _ check_%d\n      (%s)' % (
            nm('tags', i), nm('raw', i), i, term)
    L += ['theorem check : TagsSW.checkAllS meaning smeaning resolution ctrs tots window bounds cap tags raw = true :=',
          '  TagsSW.checkAllS_of_parts check_ctrs check_tots\n    (%s)' % term, '',
          'theorem sat : ∀ S E : Nat → Bool,',
          '    AxiomsS S E window (centresOf window bounds) resolution cap → ∃ τ, cnfTrue τ cnf = true :=',
          '  fun S E h => ⟨TagsSW.tauS S E meaning smeaning resolution ctrs tots,',
          '    TagsSW.soundS meaning smeaning resolution ctrs tots window bounds cap tags raw check S E h⟩', '',
          'end ' + ns, '']
    txt = '\n'.join(L)
    os.makedirs(os.path.join(out, 'LocalWindowCnf'), exist_ok=True)
    open(os.path.join(out, 'LocalWindowCnf', name + '.lean'), 'w').write(txt)
    return dict(name=name, core=len(core), nv=nv, parts=np_, w=w, mw=mw, WX=WX, lean_bytes=len(txt))


