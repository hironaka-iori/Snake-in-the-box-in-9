def plan(a):
    new, h8, share, _, _ = key_sets(a)
    keys = [('k6' if len(k[0]) != len(k[1]) + 2 else 'H', k[0], k[1]) for k in new + h8]
    metas = {kk: load_meta(a.core, pname(kk[1:])) for kk in keys}
    missing = [kk for kk, m in metas.items() if m is None]
    if missing:
        raise SystemExit(f'{len(missing)} keys without a core, e.g. {missing[:3]}')
    hints = {kk: metas[kk]['lrat']['hints'] for kk in keys}
    wide = {kk: [tuple(x) for x in metas[kk]['wide']] for kk in keys}
    t0 = time.time()
    byds = collections.defaultdict(list)
    for k in keys:
        byds[FK.canon(k[1])].append(k)
        byds[FK.canon(k[1][::-1])].append(k)
    cover = {k: {k: ('self', None, None)} for k in keys}
    nchk = collections.Counter()
    for k2 in keys:
        ds2 = k2[1]
        n = len(ds2)
        seen = set()
        for L in range(2, n + 1):
            for i in range(0, n - L + 1):
                for src in byds.get(FK.canon(ds2[i:i + L]), ()):
                    if src == k2 or src in seen:
                        continue
                    seen.add(src)
                    nchk['candidates'] += 1
                    dv = FK.derivable(src, wide[src], k2)
                    if dv:
                        cover[src][k2] = dv
                        nchk[dv[0]] += 1
    unc, chosen = set(keys), []
    cov = {s: set(v) for s, v in cover.items()}
    while unc:
        best = None
        for s, cv in cov.items():
            live = cv & unc
            if not live:
                continue
            rr = (hints[s] + 5e3) / (sum(hints[x] for x in live) + 5e3 * len(live))
            if best is None or rr < best[0] or (rr == best[0] and s < best[1]):
                best = (rr, s)
        s = best[1]
        chosen.append(s)
        unc -= cov[s] & unc
        for t_ in [t_ for t_, cv in cov.items() if not (cv & unc)]:
            del cov[t_]
    sidx = {s: i for i, s in enumerate(chosen)}
    derive = []
    for k in keys:
        opts = [(0 if cover[s][k][0] in ('self', 'L1') else 1, hints[s], sidx[s], s) for s in chosen
                if k in cover[s]] if k not in sidx else [(0, 0, sidx[k], k)]
        _, _, si, s = min(opts)
        m, v, sv = cover[s][k]
        derive.append([si, m, v, sv])
    meth = collections.Counter(x[1] for x in derive)
    summary = dict(keys=len(keys), seeds=len(chosen), derived=len(keys) - len(chosen), methods=dict(meth),
                   implications=dict(nchk), hints_all=sum(hints.values()), hints_seeds=sum(hints[s] for s in chosen),
                   seeds_widened=sum(1 for s in chosen if wide[s] != FK.bounds_of(s[2])),
                   seconds=round(time.time() - t0, 1), sample=bool(a.keys_from))
    out = dict(summary=summary, keys=[[k[0], list(k[1]), list(k[2])] for k in keys],
               seeds=[[keys.index(s), [list(x) for x in wide[s]]] for s in chosen], derive=derive)
    os.makedirs(os.path.dirname(a.plan), exist_ok=True)
    with gzip.GzipFile(a.plan, 'wb', mtime=0) as g:
        g.write(json.dumps(out, separators=(',', ':')).encode())
    print(json.dumps(summary, indent=1))


def load_plan(path):
    """{key: ('self', wide) | (seed key, 'L1' | 'L2', v, s)} for the keys (ds, syms) of the plan."""
    d = json.load(gzip.open(path, 'rt'))
    keys = [(tuple(k[1]), tuple(k[2])) for k in d['keys']]
    seeds = [(keys[i], [tuple(x) for x in b]) for i, b in d['seeds']]
    out = {}
    for k, (si, m, v, s) in zip(keys, d['derive']):
        out[k] = ('self', seeds[si][1]) if m == 'self' else (seeds[si][0], m, v, s)
    return out


