def share_regen(meta):
    """(enc, renaming, core, tags, used counters) of a share core JSON, with the SHA checked."""
    k = (tuple(meta['dirs']), tuple(meta['syms']), meta['cap'])
    enc = share_enc(k, meta['cycle_cuts'])
    data = (f'p cnf {enc.nv} {len(enc.clauses)}\n' + ''.join(' '.join(map(str, c)) + ' 0\n' for c in enc.clauses)).encode()
    assert hashlib.sha256(data).hexdigest() == meta['full_sha256'], meta['name']
    return (enc,) + share_compact(enc, meta['full_core_ids'])


def cores(a):
    os.makedirs(a.core, exist_ok=True)
    new, h8, share, _, _ = key_sets(a)
    kinds = set(a.kinds.split(','))
    todo = ([('p', k) for k in new] if 'plain' in kinds else []) + ([('p', k) for k in h8] if 'h8' in kinds else []) + \
           ([('s', k) for k in share] if 'share' in kinds else [])
    est = hint_est()
    todo.sort(key=lambda t: (est.get(t[1], 1e12), t[1]))
    si, sn = map(int, a.shard.split('/'))
    work = os.path.join(SCR, f'core{si}')
    certs = os.path.join(work, 'certs')
    os.makedirs(certs, exist_ok=True)
    cad = cadical(work)
    log = os.path.join(a.core, f'_progress{si}.jsonl')
    n = 0
    for i, (kind, k) in enumerate(todo):
        if i % sn != si:
            continue
        name = pname(k) if kind == 'p' else sname(k)
        if a.only and name not in a.only:
            continue
        if os.path.exists(core_path(a.core, name)):
            continue
        if disk_free_mb() < a.min_disk_mb:
            print('stop: disk below %d MB' % a.min_disk_mb, flush=True)
            break
        t = time.time()
        try:
            meta = core_plain(k, work, certs, cad) if kind == 'p' else core_share(k, work, certs, cad, a.share_tl)
        except Exception as e:     # noqa: BLE001  (logged; the key is retried by the next run)
            with open(log, 'a') as f:
                f.write(json.dumps({'name': name, 'error': repr(e)[:500], 's': round(time.time() - t, 1)}) + '\n')
            for fn in os.listdir(work):
                if fn.startswith(name):
                    os.remove(os.path.join(work, fn))
            for fn in os.listdir(certs):
                if fn.startswith(name):
                    os.remove(os.path.join(certs, fn))
            continue
        if meta.get('result', 'UNSAT') != 'UNSAT':
            with open(log, 'a') as f:
                f.write(json.dumps({'name': name, 'result': meta['result'], 's': round(time.time() - t, 1)}) + '\n')
            continue
        save_meta(a.core, name, meta)
        rec = {'name': name, 'kind': meta.get('kind'), 'result': meta.get('result', 'UNSAT'),
               'core': len(meta.get('core_ids', [])), 'hints': meta.get('lrat', {}).get('hints'),
               'est': est.get(k), 'wide': meta.get('wide'), 's': round(time.time() - t, 1)}
        with open(log, 'a') as f:
            f.write(json.dumps(rec) + '\n')
        n += 1
        if a.limit and n >= a.limit:
            break
    print(f'cores: {n} computed in shard {si}/{sn}', flush=True)


