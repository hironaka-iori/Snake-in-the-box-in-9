def chain_keys():
    """(plain chunks, h8 keys, share keys) of LocalWindowDirKeys6SB233, in its order."""
    src = open(KEYS_LEAN).read()
    nch = len(re.findall(r'^noncomputable def dirChunk6SB233_\d+ ', src, re.M))
    pat = re.compile(r'\(\[([\d, ]+)\], \[([\d, ]+)\]\)')
    chunks = []
    for ci in range(nch):
        blk = src.split(f'def dirChunk6SB233_{ci} :', 1)[1].split('\n\n', 1)[0]
        chunks.append([(tuple(map(int, d.split(','))), tuple(map(int, s.split(',')))) for d, s in pat.findall(blk)])
    blk = src.split('def h8Keys6SB233 :', 1)[1].split('\n\n', 1)[0]
    h8 = [(tuple(map(int, d.split(','))), tuple(map(int, s.split(',')))) for d, s in pat.findall(blk)]
    blk = src.split('def shareKeys6SB233 :', 1)[1].split('\n\n', 1)[0]
    share = [(tuple(map(int, d.split(','))), tuple(map(int, s.split(','))), int(k))
             for d, s, k in re.findall(r'\(\[([\d, ]+)\], \[([\d, ]+)\], (\d+)\)', blk)]
    return chunks, h8, share


