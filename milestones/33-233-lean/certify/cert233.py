def status(a):
    new, h8, share, reused, _ = key_sets(a)
    have = {f[:-8] for f in os.listdir(a.core) if f.endswith('.json.gz')} if os.path.isdir(a.core) else set()
    lib = os.path.join(LEAN, '.lake/build/lib/lean')

    def built(d, n):
        return os.path.exists(os.path.join(lib, d, n + '.olean'))
    np_ = [pname(k) for k in new + h8]
    ns = [sname(k) for k in share]
    r = dict(new_plain=len(new), h8=len(h8), share=len(share), reused=len(reused),
             cores_plain=sum(n in have for n in np_), cores_share=sum(n in have for n in ns))
    if os.path.exists(a.plan):
        pl = load_plan(a.plan)
        seeds = [pname(k) for k in new + h8 if k in pl and pl[k][0] == 'self']
        r.update(seeds=len(seeds), seed_cnf_built=sum(built('LocalWindowCnf', n) for n in seeds),
                 seed_unsat_built=sum(built('LocalWindowUnsat', n) for n in seeds))
    r.update(share_cnf_built=sum(built('LocalWindowCnf', n) for n in ns),
             share_unsat_built=sum(built('LocalWindowUnsat', n) for n in ns), disk_free_mb=disk_free_mb())
    print(json.dumps(r, indent=1))


