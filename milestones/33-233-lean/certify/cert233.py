def seed_meta(core, k, wide):
    """The core JSON of seed `k` for the generators: `lean_bounds` = its widened bounds when wider."""
    m = load_meta(core, pname(k))
    if [tuple(x) for x in wide] != [tuple(x) for x in GC.dir_bounds(k[1])]:
        m['lean_bounds'] = [list(x) for x in wide]
        m['plan_bounds'] = [list(x) for x in wide]
    return m


def regen_plain(meta, certs):
    enc = K.encoding(meta['dirs'], meta['syms'])
    assert len(enc.clauses) == meta['base_clauses'], meta['name']
    for cyc in meta['cycle_cuts']:
        enc.add_cycle_cut(cyc)
    gz = os.path.join(certs, meta['name'] + '.cnf.gz')
    assert K.write_gz_cnf(enc, gz) == meta['cnf_sha256'], meta['name']
    return gz


def work_items(a, kinds):
    """(kind, key, name) of the seeds and share keys, smallest hint count first."""
    new, h8, share, _, _ = key_sets(a)
    items = []
    if 'seed' in kinds:
        pl = load_plan(a.plan)
        for k in new + h8:
            if pl[k][0] == 'self':
                items.append(('seed', k, pname(k), pl[k][1]))
    if 'share' in kinds:
        for k in share:
            items.append(('share', k, sname(k), None))
    out = []
    for it in items:
        m = load_meta(a.core, it[2])
        if m is None or m.get('result', 'UNSAT') != 'UNSAT':
            continue
        out.append((m['lrat']['hints'], it, m))
    out.sort(key=lambda x: (x[0], x[1][2]))
    if a.names:
        out = [x for x in out if x[1][2] in a.names]
    return out


