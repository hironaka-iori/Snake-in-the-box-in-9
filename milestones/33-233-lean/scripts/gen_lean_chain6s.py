"""Emit the Lean chain of a share-weighted six-centre automaton (gen_lean_automaton6s.py) to its bound.

Reads the summary `milestones/33-233-lean/data/auto6s_<T>.json` and writes:

  DirectionWindowBridge6S<T>.lean   core Lean: the kernel checks
      keysOK6 / Cover6 (cover6_chunks, one declaration per nonzero exclusion row, against its chunk),
      keysOKH8 / CoverH8 (one evaluation), ShareCover (shareCover_rows, one declaration per share
      shape), and `windows6S<T>`, `shareWindows6S<T>`
  AggregateDirection6S<T>.lean      mathlib: `upper_<N>_of_refuted6S<T>` :
      AllRefuted6S<T> → AllRefutedShare6S<T> → Floors233 → ∀ snake, m ≤ N

The arithmetic is `upper_of_refuted6S` (AggregateDirection6SConditional):
(P + 4200 Q) m ≤ 1099800 Q + 7 P + (2^B - 1).  The unconditional module (discharging AllRefuted6S<T>
and AllRefutedShare6S<T> by LRAT replays and Floors233 by main's theorems) is not generated.

  python gen_lean_chain6s.py --tag T [--out-stronger DIR] [--summary FILE] [--check]
"""
import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
STRONGER = os.path.join(ROOT, 'work', 'spectral', 'stronger')
DATA = os.path.join(HERE, '..', 'data')
ME = 'milestones/33-233-lean/scripts/gen_lean_chain6s.py'


def lst(c):
    return '[' + ', '.join(map(str, c)) + ']'


def bridge(T, s):
    rows = s['rows']
    shapes = s['share_shapes']
    nch = s['k_chunks']
    return f'''/-
Generated by {ME}.
The window premises and share window bounds of `tables6S{T}` from its certificate statements
(core Lean; generic argument in `DirectionWindowBridge6S`).
-/
import DirectionWindowBridge6S
import WindowAutomaton6S{T}Data
import LocalWindowDirKeys6S{T}

set_option Elab.async false
set_option maxHeartbeats 0

namespace Snake9.DirectionWindow6S
open Snake9 Snake9.LocalWindow Snake9.WindowAutomaton Snake9.DirectionWindow6 Snake9.DirectionWindow7

''' + ''.join(f'''theorem keysOK6S{T}_{ci} : keysOK6 (dirChunks6S{T}.getD {ci} []) = true := by decide +kernel

''' for ci in range(nch)) + f'''theorem keysOK6S{T} : keysOK6 dirKeys6S{T} = true :=
  keysOK6_flatten (fun i hi => by
    have : i < {nch} := by simpa [dirChunks6S{T}] using hi
    exact AllP.mem (P := fun i => keysOK6 (dirChunks6S{T}.getD i []) = true) (l := List.range {nch})
      ⟨{', '.join(f'keysOK6S{T}_{ci}' for ci in range(nch))}, trivial⟩ i (List.mem_range.2 this))

''' + ''.join(f'''set_option maxRecDepth 100000 in
theorem zero6S{T}_{n} : allRGS {n} 0 (zeroOutside6 tables6S{T}.k6 rows6S{T}) = true := by decide +kernel

''' for n in range(3, 8)) + ''.join(f'''set_option maxRecDepth 100000 in
theorem row6S{T}_{k} : rowOK6 tables6S{T}.k6 (dirChunks6S{T}.getD {ci} []) {lst(c)} {s0} = true := by
  decide +kernel

''' for k, (c, s0, ci) in enumerate(rows)) + f'''set_option maxRecDepth 100000 in
theorem rows6S{T}_lit : AllP (fun r : List Nat × Nat => ∃ i, rowOK6 tables6S{T}.k6 (dirChunks6S{T}.getD i []) r.1 r.2 = true)
    [{', '.join(f'({lst(c)}, {s0})' for c, s0, ci in rows)}] :=
  ⟨{', '.join(f'⟨{ci}, row6S{T}_{k}⟩' for k, (c, s0, ci) in enumerate(rows))}, trivial⟩

theorem rows6S{T}_ok : ∀ r ∈ rows6S{T}, ∃ i, rowOK6 tables6S{T}.k6 (dirChunks6S{T}.getD i []) r.1 r.2 = true := by
  unfold rows6S{T}
  exact AllP.mem rows6S{T}_lit

/-- Every set exclusion bit of a canonical shape of 3 to 7 directions is one of the plain keys. -/
theorem cover6S{T}k6 : Cover6 tables6S{T}.k6 dirKeys6S{T} :=
  cover6_chunks dirChunks6S{T} rows6S{T} zero6S{T}_3 zero6S{T}_4 zero6S{T}_5 zero6S{T}_6 zero6S{T}_7
    rows6S{T}_ok

theorem keysOKH8_6S{T} : keysOKH8 h8Keys6S{T} = true := by decide +kernel

set_option maxRecDepth 100000 in
theorem coverH8_6S{T} : CoverH8 tables6S{T} h8Keys6S{T} := coverH8_of (by decide +kernel)

set_option maxRecDepth 100000 in
theorem zeroS6S{T} : allRGS 6 0 (zeroOutsideS tables6S{T} sshapes6S{T}) = true := by decide +kernel

''' + ''.join(''.join(f'''set_option maxRecDepth 100000 in
theorem srow6S{T}_{k}_{t0} : shareRowOK tables6S{T} shareKeys6S{T} {lst(c)} {t0} = true := by
  decide +kernel

''' for t0 in range(1, 7)) + f'''theorem srow6S{T}_{k} : allSym (shareRowOK tables6S{T} shareKeys6S{T} {lst(c)}) = true :=
  allSym_of6 _ {' '.join(f'srow6S{T}_{k}_{t0}' for t0 in range(1, 7))}

''' for k, c in enumerate(shapes)) + f'''set_option maxRecDepth 100000 in
theorem srows6S{T}_lit : AllP (fun c : List Nat => allSym (shareRowOK tables6S{T} shareKeys6S{T} c) = true)
    [{', '.join(lst(c) for c in shapes)}] :=
  ⟨{', '.join(f'srow6S{T}_{k}' for k in range(len(shapes)))}, trivial⟩

/-- `cover6S`: every share field is backed by a share key or a floor theorem. -/
theorem shareCover6S{T} : ShareCover tables6S{T} shareKeys6S{T} :=
  shareCover_rows sshapes6S{T} zeroS6S{T} (by
    unfold sshapes6S{T}
    exact AllP.mem srows6S{T}_lit)

theorem windows6S{T} (h : AllRefuted6S{T}) {{m : Nat}} (p : Snake m) :
    Windows6S tables6S{T} (pathDir p) (coreAlpha p) m :=
  direction_windows_core6S h.1 keysOK6S{T} cover6S{T}k6 h.2 keysOKH8_6S{T} coverH8_6S{T} p

end Snake9.DirectionWindow6S

#print axioms Snake9.DirectionWindow6S.cover6S{T}k6
#print axioms Snake9.DirectionWindow6S.coverH8_6S{T}
#print axioms Snake9.DirectionWindow6S.shareCover6S{T}
#print axioms Snake9.DirectionWindow6S.windows6S{T}
'''


def aggregate(T, s):
    P, Q, B, N = s['P'], s['Q'], s['bits'], s['bound']
    lhs = f'({P} + 4200 * {Q}) * m ≤ 1099800 * {Q} + 7 * {P} + (2 ^ {B} - 1)'
    what = ('a toy instance (zero potential, lambda = 120/1; the keys are a toy subset)' if s['toy'] else
            f'lambda = {P}/{Q}, {B}-bit potential (range {s["potential_range"]}), {s["plain_keys"]} plain keys, '
            f'{s["h8_keys"]} H8 keys, {s["share_keys"]} share keys, {s["share_on_floors"]} share fields on '
            f'main\'s floors')
    return f'''import AggregateDirection6SConditional
import WindowAutomaton6S{T}Sequence
import DirectionWindowBridge6S{T}

/-!
# The bound {N} from the share-weighted six-centre automaton `{T}`

Generated by `{ME}`: {what}.
`upper_of_refuted6S` gives `{lhs}`, so `m ≤ {N}`.  The hypotheses are the certificate statements
`AllRefuted6S{T}` (plain and H8 keys) and `AllRefutedShare6S{T}` (share thresholds) and the floor
theorems of origin/main (`Floors233`).
-/

namespace Snake9
open WindowAutomaton

theorem upper_{N}_of_refuted6S{T} (h : LocalWindow.AllRefuted6S{T})
    (hs : LocalWindow.AllRefutedShare6S{T}) (hF : DirectionWindow6S.Floors233) {{m : Nat}}
    (p : Snake m) : m ≤ {N} := by
  have := upper_of_refuted6S tables6S{T} LocalWindow.dirKeys6S{T} LocalWindow.h8Keys6S{T}
    LocalWindow.shareKeys6S{T} h.1 h.2 hs hF DirectionWindow6S.keysOK6S{T}
    DirectionWindow6S.cover6S{T}k6 DirectionWindow6S.keysOKH8_6S{T} DirectionWindow6S.coverH8_6S{T}
    DirectionWindow6S.shareCover6S{T} stepOK6S{T} p
  change {lhs} at this
  omega

end Snake9

#print axioms Snake9.upper_{N}_of_refuted6S{T}
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tag', required=True)
    ap.add_argument('--summary')
    ap.add_argument('--out-stronger', default=STRONGER)
    ap.add_argument('--check', action='store_true', help='fail if a module would change')
    a = ap.parse_args()
    s = json.load(open(a.summary or os.path.join(DATA, f'auto6s_{a.tag}.json')))
    T = s['tag']
    P, Q, B, N = s['P'], s['Q'], s['bits'], s['bound']
    R = 2 ** B - 1
    assert (P + 4200 * Q) * N <= 1099800 * Q + 7 * P + R < (P + 4200 * Q) * (N + 1), 'bound does not follow'
    files = {f'DirectionWindowBridge6S{T}.lean': bridge(T, s), f'AggregateDirection6S{T}.lean': aggregate(T, s)}
    changed = False
    for name, text in files.items():
        p = os.path.join(a.out_stronger, name)
        same = os.path.exists(p) and open(p).read() == text
        changed |= not same
        if not same and not a.check:
            open(p, 'w').write(text)
        print(name, 'unchanged' if same else ('DIFFERS' if a.check else 'written'))
    if a.check and changed:
        sys.exit(1)


if __name__ == '__main__':
    main()
