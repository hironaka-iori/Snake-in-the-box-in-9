"""Emit the Lean chain from a seven-centre automaton (gen_lean_automaton7.py) to its bound.

Reads the summary `milestones/25-k7-234/lean/data/auto7_<T>.json` written by
`gen_lean_automaton7.py --tag T` and writes:

  DirectionWindowBridge7<T>.lean   core Lean: the kernel checks `keysOK6 dirKeys7<T>`,
                                   `keysOKH hKeys7<T>`, `CoverH tables7<T> hKeys7<T>` and
                                   `Cover7 tables7<T> dirKeys7<T>` (`cover7_rows`: one declaration
                                   per nonzero exclusion row, against the chunk of keys that
                                   holds that row), and the premises `Windows7` from
                                   `AllRefuted7<T>`
  AggregateDirection7<T>.lean      mathlib side: `upper_<N>_of_refuted7<T>`,
                                   `AllRefuted7<T> → ∀ snake, m ≤ N`

The arithmetic is the generic `upper_of_refuted7` (AggregateDirection7Conditional):
(P + 35 Q) m + 7 Q ≤ 9171 Q + 8 P + (2^B - 1), which must give m ≤ N.  The unconditional
module (discharging `AllRefuted7<T>` by the LRAT replays of the keys) is not generated.

  python gen_lean_chain7.py --tag T [--summary S] [--out-stronger DIR] [--check]
"""
import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
STRONGER = os.path.join(ROOT, 'work', 'spectral', 'stronger')
DATA = os.path.join(HERE, '..', 'data')
ME = 'milestones/25-k7-234/lean/scripts/gen_lean_chain7.py'


def lst(c):
    return '[' + ', '.join(map(str, c)) + ']'


def rgs(n):
    out = []

    def go(m, l):
        if len(l) == n:
            out.append(tuple(l)); return
        for a in range(m + 1):
            go(max(m, a + 1), l + [a])
    go(0, [])
    return out


def bridge(T, s):
    rows = [(tuple(c), s0, ch) for c, s0, ch in s['rows']]
    pres = rgs(4)
    zero = ''.join(f'''set_option maxRecDepth 100000 in
theorem zero7{T}_{n} : allRGS {n} 0 (zeroOutside6 tables7{T}.k6 rows7{T}) = true := by decide +kernel

''' for n in range(3, 8))
    zero += ''.join(f'''set_option maxRecDepth 100000 in
theorem zeroPre7{T}_{j} :
    allRGS 4 (rgsBound {lst(q)} 0) (fun l => zeroOutside6 tables7{T}.k6 rows7{T} ({lst(q)} ++ l)) = true := by
  decide +kernel

''' for j, q in enumerate(pres))
    zero += f'''theorem zero7{T}_8 : allRGS 8 0 (zeroOutside6 tables7{T}.k6 rows7{T}) = true :=
  allRGS_of_prefixes _ {lst(lst(q) for q in pres)} 4 4 8 rfl (by decide +kernel) (by
    intro pre h
    simp only [List.mem_cons, List.not_mem_nil, or_false] at h
    rcases h with {' | '.join(['rfl'] * len(pres))}
{chr(10).join(f'    · exact zeroPre7{T}_{j}' for j in range(len(pres)))})

'''
    rowdecls = ''.join(f'''set_option maxRecDepth 100000 in
theorem row7{T}_{k} : rowOK6 tables7{T}.k6 (dirChunks7{T}.getD {ch} []) {lst(c)} {s0} = true := by
  decide +kernel

''' for k, (c, s0, ch) in enumerate(rows))
    if rows:
        rows_ok = f'''theorem rows7{T}_ok : ∀ r ∈ rows7{T},
    ∃ i, rowOK6 tables7{T}.k6 (dirChunks7{T}.getD i []) r.1 r.2 = true := by
  intro r hr
  simp only [rows7{T}, List.mem_cons, List.not_mem_nil, or_false] at hr
  rcases hr with {' | '.join(['rfl'] * len(rows))}
{chr(10).join(f'  · exact ⟨{ch}, row7{T}_{k}⟩' for k, (c, s0, ch) in enumerate(rows))}
'''
    else:
        rows_ok = f'''theorem rows7{T}_ok : ∀ r ∈ rows7{T},
    ∃ i, rowOK6 tables7{T}.k6 (dirChunks7{T}.getD i []) r.1 r.2 = true := by
  intro r hr
  simp [rows7{T}] at hr
'''
    return f'''/-
Generated by {ME}.
The window premises of the seven-centre automaton `tables7{T}` from the certificate
statements `AllRefuted7{T}` ({s["k6_keys"]} k6/F8 keys, {s["H9"]} H9 keys; core Lean, generic
argument in `DirectionWindowBridge7`).
-/
import DirectionWindowBridge7
import WindowAutomaton7{T}Data
import LocalWindowDirKeys7{T}

set_option Elab.async false

namespace Snake9.DirectionWindow7
open Snake9 Snake9.LocalWindow Snake9.WindowAutomaton Snake9.DirectionWindow6

theorem keysOK7{T} : keysOK6 dirKeys7{T} = true := by decide +kernel

theorem keysOKH7{T} : keysOKH hKeys7{T} = true := by decide +kernel

/-- The H9 tree of `tables7{T}` holds exactly the codes of the H9 keys. -/
theorem coverH7{T} : CoverH tables7{T} hKeys7{T} := by
  unfold CoverH
  decide +kernel

{zero}{rowdecls}{rows_ok}
/-- Every set exclusion bit of a canonical shape of 3 to 8 directions is one of the keys
(the nonzero rows are listed, each is checked against its chunk of keys). -/
theorem cover7{T} : Cover7 tables7{T} dirKeys7{T} :=
  cover7_rows dirChunks7{T} rows7{T} zero7{T}_3 zero7{T}_4 zero7{T}_5 zero7{T}_6 zero7{T}_7
    zero7{T}_8 rows7{T}_ok

theorem windows7{T} (h : AllRefuted7{T}) {{m : Nat}} (p : Snake m) :
    Windows7 tables7{T} (pathDir p) (coreAlpha p) m :=
  direction_windows_core7 h.1 keysOK7{T} cover7{T} h.2 keysOKH7{T} coverH7{T} p

end Snake9.DirectionWindow7

#print axioms Snake9.DirectionWindow7.cover7{T}
#print axioms Snake9.DirectionWindow7.coverH7{T}
#print axioms Snake9.DirectionWindow7.windows7{T}
'''


def aggregate(T, s):
    P, Q, B, N = s['P'], s['Q'], s['bits'], s['bound']
    lhs = f'({P} + 35 * {Q}) * m + 7 * {Q} ≤ 9171 * {Q} + 8 * {P} + {2 ** B - 1}'
    what = ('a toy instance (zero potential, lambda = 1; the keys are not certificates)' if s['toy'] else
            f'lambda = {P}/{Q}, {B}-bit potential, {s["k6_keys"]} k6/F8 keys and {s["H9"]} H9 keys'
            + (' (PROVISIONAL key set: solver answers)' if s['provisional'] else ''))
    return f'''import AggregateDirection7Conditional
import WindowAutomaton7{T}Sequence
import DirectionWindowBridge7{T}

/-!
# The bound {N} from the seven-centre automaton `{T}`

Generated by `{ME}`: {what}.
`upper_of_refuted7` gives `{lhs}`, so `m ≤ {N}`.  The only hypothesis is `AllRefuted7{T}`.
-/

namespace Snake9
open WindowAutomaton

theorem upper_{N}_of_refuted7{T} (h : LocalWindow.AllRefuted7{T}) {{m : Nat}} (p : Snake m) :
    m ≤ {N} := by
  have := upper_of_refuted7 tables7{T} LocalWindow.dirKeys7{T} LocalWindow.hKeys7{T} h.1
    DirectionWindow7.keysOK7{T} DirectionWindow7.cover7{T} h.2 DirectionWindow7.keysOKH7{T}
    DirectionWindow7.coverH7{T} stepOK7{T} p
  change {lhs} at this
  omega

end Snake9

#print axioms Snake9.upper_{N}_of_refuted7{T}
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tag', required=True)
    ap.add_argument('--summary')
    ap.add_argument('--out-stronger', default=STRONGER)
    ap.add_argument('--check', action='store_true', help='fail if a module would change')
    a = ap.parse_args()
    s = json.load(open(a.summary or os.path.join(DATA, f'auto7_{a.tag}.json')))
    T = s['tag']
    P, Q, B, N = s['P'], s['Q'], s['bits'], s['bound']
    assert (P + 35 * Q) * N + 7 * Q <= 9171 * Q + 8 * P + 2 ** B - 1 or N < 8
    assert (P + 35 * Q) * (N + 1) + 7 * Q > 9171 * Q + 8 * P + 2 ** B - 1, 'bound does not follow'
    files = {f'DirectionWindowBridge7{T}.lean': bridge(T, s), f'AggregateDirection7{T}.lean': aggregate(T, s)}
    changed = False
    for name, text in files.items():
        p = os.path.join(a.out_stronger, name)
        same = os.path.exists(p) and open(p).read() == text
        changed |= not same
        if not same and not a.check:
            open(p, 'w').write(text)
        print(name, 'unchanged' if same else ('DIFFERS' if a.check else 'written'))
    if a.check and changed:
        sys.exit(1)


if __name__ == '__main__':
    main()
