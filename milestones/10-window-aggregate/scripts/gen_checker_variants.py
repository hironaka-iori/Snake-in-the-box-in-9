"""Generate the word-width / variable-offset variants of the kernel LRAT checkers.

`work/final_lean/LratCheck.lean` (base: trees, clause semantics, soundness lemmas, the
original checker) and `LratFast.lean` (the faster checker) are written for 13-bit proof
words and the literal offset OFF = 2400 (variable v is bit v, its negation bit v + OFF).
The variants are the same files with those constants replaced:

  LratCheck14 / LratFast14        14-bit words (clause keys up to 16383)
  LratCheckO3k / LratFastO3k      OFF = 3000, for CNFs with more than 2399 variables
  LratFastO3k14, LratFastO3k15    OFF = 3000 with 14- or 15-bit words
  LratCheckO4k, LratFastO4k{,14,15}  OFF = 4000 (radius-4 five-centre CNFs)

A fast variant imports the base variant with the same offset.  Existing files are only
rewritten when their content changes.

  python gen_checker_variants.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.abspath(os.path.join(HERE, '..', '..', '..', 'work', 'final_lean'))


def variant(src, bits, off, base_name, fast_name, base_import):
    s = src
    if off != 2400:
        s = s.replace('2400', str(off))
    if bits != 13:
        s = s.replace('8191', str((1 << bits) - 1)).replace('13', str(bits))
    s = s.replace('import LratCheck\n', 'import %s\n' % base_import)
    s = s.replace('Snake9.LratFast', '@@FAST@@').replace('Snake9.Lrat', 'Snake9.' + base_name)
    s = s.replace('@@FAST@@', 'Snake9.' + fast_name)
    s = re.sub(r'\bLrat\.seqT\b', base_name + '.seqT', s)
    return s


def header(kind, bits, off):
    parts = []
    if bits != 13:
        parts.append('%d-bit words (clause keys up to %d)' % (bits, (1 << bits) - 1))
    if off != 2400:
        parts.append('literal offset OFF = %d (up to %d variables)' % (off, off - 1))
    return ('/-! Variant of `%s` with %s, generated by\n'
            '`milestones/10-window-aggregate/scripts/gen_checker_variants.py`. -/\n\n'
            % (kind, ' and '.join(parts)))


def write(path, text):
    if os.path.exists(path) and open(path).read() == text:
        return False
    open(path, 'w').write(text)
    return True


def main():
    base = open(os.path.join(LEAN, 'LratCheck.lean')).read()
    fast = open(os.path.join(LEAN, 'LratFast.lean')).read()
    assert '4800' not in base and '4800' not in fast
    # (bits, off) -> names
    bases = {2400: ('LratCheck', 'Lrat'), 3000: ('LratCheckO3k', 'LratO3k'), 4000: ('LratCheckO4k', 'LratO4k')}
    todo = [(13, 3000), (14, 2400), (14, 3000), (15, 3000), (13, 4000), (14, 4000), (15, 4000)]
    for off, (mod, ns) in bases.items():
        if off == 2400:
            continue
        text = base.replace('import LocalWindowModel\n', 'import LocalWindowModel\n\n' + header('LratCheck', 13, off), 1)
        text = variant(text, 13, off, ns, 'LratFast', 'LocalWindowModel')
        print(mod, 'written' if write(os.path.join(LEAN, mod + '.lean'), text) else 'unchanged')
    for bits, off in todo:
        bmod, bns = bases[off]
        fmod = 'LratFast' + {2400: '', 3000: 'O3k', 4000: 'O4k'}[off] + (str(bits) if bits != 13 else '')
        fns = fmod
        text = fast.replace('import LratCheck\n', 'import LratCheck\n\n' + header('LratFast', bits, off), 1)
        text = variant(text, bits, off, bns, fns, bmod)
        print(fmod, 'written' if write(os.path.join(LEAN, fmod + '.lean'), text) else 'unchanged')


if __name__ == '__main__':
    main()
