"""Generate the Lean data module for the direction-aware potential argument.

Reads the certified exclusion index and the minimal-set spec, rebuilds the
(L=6, k=4, K=5) automaton, recomputes an integer potential, and writes
`work/spectral/stronger/WindowAutomatonData.lean` containing

  * `shapeIdx6`  : shape code of a canonical induced 6-direction list -> 0..11
  * `wshapeIdx`  : shape code of a canonical window shape (3..5 dirs) -> 0..5
  * `forbMask`   : bitmask over wshapeIdx * 7^4 + symIdx of excluded windows
  * `potMask`    : 4-bit fields over shapeIdx6 * 216 + count index
  * `check`      : the per-shape step test, and the kernel-checked theorem
                   `step_table : allRGS 7 0 check = true`.

Before writing, the script re-implements the Lean `check` in Python on the
same inputs (all 877 restricted growth strings of length 7) and asserts it.

  python gen_lean_automaton.py --index ../data/direction_certificates.json
"""
import argparse, itertools, json, os
from fractions import Fraction as Fr
import numpy as np
from refine import Automaton, canon, prune, howard, exact_check, induced
from direction_bound import Listed

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
OUT = os.path.join(ROOT, 'work', 'spectral', 'stronger', 'WindowAutomatonData.lean')
L, K_, KMAX = 6, 4, 5
P, Q = 10, 3                      # lambda = 10/3


def shape_code(l):
    acc = 1
    for a in l:
        acc = acc * 8 + a
    return acc


def sym_idx(syms):
    acc = 0
    for s in syms:
        acc = acc * 7 + s
    return acc


def rgs(n):
    out = []
    def go(m, l):
        if len(l) == n:
            out.append(tuple(l)); return
        for a in range(m + 1):
            go(max(m, a + 1), l + [a])
    go(0, [])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--index', required=True)
    a = ap.parse_args()
    cases = [c for c in json.load(open(a.index))['cases'] if c['drat_trim_verified']]
    keys = [(tuple(c['dirs']), tuple(tuple(x) for x in c['alpha'])) for c in cases]
    A = Automaton(L, K_, KMAX)
    U, V, W, WIN = A.edges(Listed(keys))
    m = prune(A.n, U, V); idx = np.nonzero(m)[0]
    mu, cyc = howard(A.n, U[idx], V[idx], W[idx]); cyc = [idx[e] for e in cyc]
    lam = Fr(int(W[cyc].sum()), len(cyc))
    assert lam == Fr(P, Q), lam
    pi = exact_check(A.n, U, V, W, P, Q)
    assert pi is not None
    pi = pi - pi.min()
    assert pi.max() <= 15, pi.max()
    # --- tables -------------------------------------------------------------
    shapes6 = A.dstates                              # 12 canonical induced 6-lists
    s6 = {shape_code(c): i for i, c in enumerate(shapes6)}
    wshapes = sorted({k[0] for k in keys}, key=lambda c: (len(c), c))
    ws = {shape_code(c): i for i, c in enumerate(wshapes)}
    forb = 0
    for dirs, alpha in keys:
        syms = [lo if lo == hi else 6 for lo, hi in alpha]
        assert all(1 <= s <= 6 for s in syms)
        forb |= 1 << (ws[shape_code(dirs)] * 2401 + sym_idx(syms))
    pot = 0
    for (c, t), sid in A.sid.items():
        i = s6[shape_code(c)] * 216 + (t[0] - 1) * 36 + (t[1] - 1) * 6 + (t[2] - 1)
        pot |= int(pi[sid]) << (4 * i)

    # --- Python re-implementation of the Lean check ------------------------
    def phi(h, t):
        code = shape_code(tuple(canon(h)))
        if code not in s6:
            return None
        i = s6[code] * 216 + (t[0] - 1) * 36 + (t[1] - 1) * 6 + (t[2] - 1)
        return (pot >> (4 * i)) & 15

    def wforb(ds, syms):
        def one(d, s):
            code = shape_code(tuple(canon(d)))
            return code in ws and (forb >> (ws[code] * 2401 + sym_idx(s))) & 1
        return one(ds, syms) or one(tuple(reversed(ds)), tuple(reversed(syms)))

    checked = 0
    for c in rgs(7):
        if not induced(c):
            continue
        h0, h1 = c[:6], c[1:]
        for t in itertools.product(range(1, 7), repeat=3):
            for s in range(1, 7):
                al = t + (s,)
                if any(wforb(c[7 - (k + 1):], al[3 - (k - 1):]) for k in (2, 3, 4)):
                    continue
                p0, p1 = phi(h0, t), phi(h1, al[1:])
                assert p0 is not None and p1 is not None, (c, t, s)
                assert 3 * s + p0 >= 10 + p1, (c, t, s, p0, p1)
                checked += 1
    print('python re-check passed on', checked, 'allowed transitions')

    def ifchain(name, table, default):
        lines = [f'def {name} (c : Nat) : Nat :=']
        for code, i in sorted(table.items()):
            lines.append(f'  if c = {code} then {i} else')
        lines.append(f'  {default}')
        return '\n'.join(lines)

    src = f'''/-
Generated by milestones/10-window-aggregate/scripts/gen_lean_automaton.py.
Do not edit by hand.  Tables: {len(keys)} certified window exclusions
(source: {os.path.basename(a.index)}), potential for lambda = {P}/{Q} on
{A.n} states, range {int(pi.max())}.
-/
import WindowAutomatonDefs

namespace Snake9.WindowAutomaton

/-- Canonical induced 6-direction shapes. -/
{ifchain('shapeIdx6', s6, 12)}

/-- Canonical window shapes (3 to 5 directions). -/
{ifchain('wshapeIdx', ws, 6)}

def forbMask : Nat := {forb}

def potMask : Nat := {pot}

/-- Base-6 index of a symbol triple (symbols 1..6 become digits 0..5). -/
def cntIdx : List Nat → Nat → Nat
  | [], acc => acc
  | s :: l, acc => cntIdx l (acc * 6 + (s - 1))

/-- Potential of a state: canonical history `h` (6 directions) and three symbols. -/
def pot (h : List Nat) (t : List Nat) : Nat :=
  (potMask >>> (4 * (shapeIdx6 (shapeCode (canon h)) * 216 + cntIdx t 0))) &&& 15

/-- Is the window (directions `ds`, symbols `syms`) excluded, in either orientation? -/
def wforb1 (ds : List Nat) (syms : List Nat) : Bool :=
  (forbMask >>> (wshapeIdx (shapeCode (canon ds)) * 2401 + symIdx syms 0)) &&& 1 == 1

def wforb (ds : List Nat) (syms : List Nat) : Bool :=
  wforb1 ds syms || wforb1 ds.reverse syms.reverse

/-- Step test for one canonical 7-direction window `c`, over all symbol triples
`t` (the three previous centres) and the new symbol `s`. -/
def check (c : List Nat) : Bool :=
  !inducedPattern c ||
  allSym (fun t1 => allSym (fun t2 => allSym (fun t3 => allSym (fun s =>
    wforb (c.drop 4) [t3, s] || wforb (c.drop 3) [t2, t3, s] || wforb (c.drop 2) [t1, t2, t3, s] ||
    decide (10 + pot (c.drop 1) [t2, t3, s] ≤ 3 * s + pot (c.take 6) [t1, t2, t3])))))

set_option maxRecDepth 100000 in
theorem step_table : allRGS 7 0 check = true := by
  decide +kernel

theorem pot_le (h t : List Nat) : pot h t ≤ 15 := by
  unfold pot
  exact Nat.le_of_lt_succ (Nat.and_lt_two_pow _ (by decide : 15 < 2 ^ 4))

end Snake9.WindowAutomaton
'''
    open(OUT, 'w').write(src)
    print('wrote', OUT, 'exclusions', len(keys), 'shapes6', len(shapes6), 'wshapes', len(wshapes),
          'pot range', int(pi.max()))


if __name__ == '__main__':
    main()
