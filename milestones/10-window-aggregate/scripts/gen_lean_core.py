def dir_syms(alpha):
    """Lumped symbols: the range [s, s] is s (1..5), the range [6, 21] is 6."""
    out = []
    for lo, hi in alpha:
        if lo == hi and 1 <= lo <= 5:
            out.append(lo)
        else:
            assert (lo, hi) == (6, 21), alpha
            out.append(6)
    return out


def dir_bounds(syms):
    """Mirror of `boundOf` in LocalWindowDirModel.lean."""
    return [(s, s) if s < 6 else (6, 21) for s in syms]


def dir_module(dirs, syms, prefix='D'):
    return prefix + ''.join(map(str, dirs)) + 'A' + ''.join(map(str, syms))


def window_from_dirs(ds):
    vs = [0]
    for d in ds:
        vs.append(vs[-1] ^ 1 << d)
    return vs


def sha_gz(path):
    with gzip.open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


