def trim_lrat(src, dst, ncl):
    """Keep only the lemmas on which the final empty clause depends (RUP hints only;
    deletion lines are dropped) and write them to `dst` in increasing id order.
    Returns (lemmas, hints, core ids)."""
    off, hints = {}, {}
    last = None
    with open(src, 'rb') as f:
        pos = 0
        for line in f:
            t = line.split()
            if len(t) > 1 and t[1] == b'd':
                pos += len(line)
                continue
            i = int(t[0])
            z = t.index(b'0', 1)
            hs = array.array('i', [int(h) for h in t[z + 1:-1]])
            assert all(h > 0 for h in hs), 'RAT hints are not supported'
            off[i], hints[i] = pos, hs
            if z == 1:
                last = i
            pos += len(line)
    assert last is not None, 'no empty clause in ' + src
    need, stack = set(), [last]
    while stack:
        i = stack.pop()
        if i in need or i <= ncl:
            continue
        need.add(i)
        stack.extend(h for h in hints[i] if h > ncl)
    core = sorted({h for i in need for h in hints[i] if h <= ncl})
    nh = sum(len(hints[i]) for i in need)
    with open(src, 'rb') as f, open(dst, 'wb') as g:
        for i in sorted(need):
            f.seek(off[i])
            g.write(f.readline())
    return len(need), nh, core


def extract_cnf(name, work, certs=DCERTS):
    cnf = os.path.join(work, name + '.cnf')
    if not os.path.exists(cnf):
        with gzip.open(os.path.join(certs, name + '.cnf.gz'), 'rb') as f, open(cnf, 'wb') as g:
            g.write(f.read())
    return cnf


# CaDiCaL configurations tried for every proof (with --no-binary --lrat).  Trimmed hint
# counts vary by up to 25% between them on the same core; seeds only matter without --unsat.
PORTFOLIO = [[], ['--unsat'], ['--chrono=0'], ['--unsat', '--probe=0'], ['--unsat', '--shrink=0'],
             ['--unsat', '--chrono=0'], ['--unsat', '--subsume=0']]
# Rounds of core shrinking: the next round solves only the clauses the best proof so far
# used.  Hint counts are not monotone over rounds, so the best proof of any round is kept
# (on a 400k-hint core: 401k with one default run, 309k with the portfolio, 200k after
# two rounds of shrinking).
ROUNDS = 1


def _cnf_clauses(cnf):
    nv, cl = 0, []
    for line in open(cnf):
        if line.startswith('p'):
            nv = int(line.split()[2])
        elif line[0] != 'c' and line.strip():
            cl.append(line)
    return nv, cl


def best_cadical_proof(cnf, out_prefix, cadical, seeds, portfolio=None, rounds=None):
    """Run cadical --lrat on `cnf` with every configuration of `portfolio` (default
    PORTFOLIO; each seed of `seeds` for configurations without --unsat), trim, and keep the
    proof with the fewest hints; with `rounds` > 1 repeat on the clauses that proof uses.
    Writes `out_prefix.lrat` with the clause ids of `cnf` (lemma ids above its clause
    count).  Returns (lemmas, hints, description of the run, used clause ids)."""
    portfolio = PORTFOLIO if portfolio is None else portfolio
    rounds = ROUNDS if rounds is None else rounds
    nv, clauses = _cnf_clauses(cnf)
    ncl = len(clauses)
    idmap = list(range(1, ncl + 1))   # clause of the current CNF -> clause id of `cnf`
    cur = cnf
    best = None                       # (hints, lemmas, desc, used ids of `cnf`)
    for rnd in range(rounds):
        nloc = len(idmap)
        rb = None                     # best of this round: (hints, lemmas, tmp, used, desc)
        for extra in portfolio:
            for seed in (seeds[:1] if '--unsat' in extra else seeds):
                raw = f'{out_prefix}.raw.lrat'
                r = subprocess.run([cadical, '-q', '--lrat', '--no-binary', f'--seed={seed}', *extra, cur, raw],
                                   capture_output=True, text=True)
                assert 's UNSATISFIABLE' in r.stdout, (cur, seed, extra, r.stdout[-300:], r.stderr[-300:])
                tmp = f'{out_prefix}.cand.lrat'
                nl, nh, used = trim_lrat(raw, tmp, nloc)
                os.remove(raw)
                if rb is None or nh < rb[0]:
                    os.replace(tmp, f'{out_prefix}.round.lrat')
                    desc = ' '.join(['--seed=%d' % seed, *extra]) + (' (core round %d)' % (rnd + 1) if rnd else '')
                    rb = (nh, nl, f'{out_prefix}.round.lrat', used, desc)
                else:
                    os.remove(tmp)
        nh, nl, path, used, desc = rb
        if best is None or nh < best[0]:
            # rewrite the proof with the ids of `cnf`: clause j -> idmap[j-1], lemma j -> j - nloc + ncl
            with open(path) as f, open(out_prefix + '.lrat', 'w') as g:
                for line in f:
                    t = line.split()
                    z = t.index('0', 1)
                    rm = lambda h: idmap[h - 1] if h <= nloc else h - nloc + ncl
                    g.write(' '.join([str(rm(int(t[0])))] + t[1:z + 1] + [str(rm(int(h))) for h in t[z + 1:-1]] + ['0']) + '\n')
            best = (nh, nl, desc, sorted(idmap[u - 1] for u in used))
        os.remove(path)
        if rnd + 1 == rounds or len(used) == nloc:
            break
        # next round: the clauses this round's proof used
        nxt = f'{out_prefix}.r{rnd + 1}.cnf'
        with open(nxt, 'w') as g:
            g.write(f'p cnf {nv} {len(used)}\n')
            for u in used:
                g.write(clauses[idmap[u - 1] - 1])
        if cur != cnf:
            os.remove(cur)
        cur, idmap = nxt, [idmap[u - 1] for u in used]
    if cur != cnf:
        os.remove(cur)
    nh, nl, desc, used = best
    return nl, nh, desc, used


def full_core_ids(name, work, cadical, seeds, certs=DCERTS, rounds=None):
    """Core of the committed CNF: the original clauses a trimmed cadical proof uses."""
    cnf = extract_cnf(name, work, certs)
    nl, nh, seed, used = best_cadical_proof(cnf, os.path.join(work, name + '.full'), cadical, seeds, rounds=rounds)
    os.remove(os.path.join(work, name + '.full.lrat'))
    return used, {'full_lemmas': nl, 'full_hints': nh, 'full_seed': seed}   # seed: description of the run


def core_lrat(name, core_ids, work, cadical, seeds, certs=DCERTS, rounds=None):
    """NAME.lrat in `work`: a cadical proof of the core alone, with clause ids remapped to
    the numbering of the committed CNF (core clause i -> core_ids[i-1], lemma j ->
    ncl + j - ncore), so that gen_lean_lrat.py reads it like a drat-trim proof.  Regenerated
    on any machine; any UNSAT proof of the core is acceptable (the kernel checks it)."""
    lrat = os.path.join(work, name + '.lrat')
    info_path = os.path.join(work, name + '.lrat.json')
    if os.path.exists(lrat) and os.path.exists(info_path):
        return lrat, json.load(open(info_path))
    cnf = extract_cnf(name, work, certs)
    clauses = [line for line in open(cnf) if line[0] not in 'pc' and line.strip()]
    ncl, ncore = len(clauses), len(core_ids)
    core_cnf = os.path.join(work, name + '.core.cnf')
    with open(core_cnf, 'w') as g:
        nv = max(abs(int(x)) for i in core_ids for x in clauses[i - 1].split())
        g.write(f'p cnf {nv} {ncore}\n')
        for i in core_ids:
            g.write(clauses[i - 1])
    nl, nh, seed, used = best_cadical_proof(core_cnf, os.path.join(work, name + '.core'), cadical, seeds,
                                            rounds=rounds)

    def remap(h):
        return core_ids[h - 1] if h <= ncore else ncl + h - ncore
    with open(os.path.join(work, name + '.core.lrat')) as f, open(lrat, 'w') as g:
        for line in f:
            t = line.split()
            z = t.index('0', 1)
            g.write(' '.join([str(remap(int(t[0])))] + t[1:z + 1] + [str(remap(int(h))) for h in t[z + 1:-1]] + ['0']) + '\n')
    os.remove(os.path.join(work, name + '.core.lrat'))
    info = {'producer': f'cadical --lrat --no-binary {seed} on the core CNF, trimmed to the '
                        f'dependencies of the empty clause, ids remapped to the committed CNF',
            'seeds_tried': list(seeds), 'lemmas': nl, 'hints': nh, 'core_clauses_used': len(used),
            'lrat_sha256': hashlib.sha256(open(lrat, 'rb').read()).hexdigest()}
    json.dump(info, open(info_path, 'w'))
    return lrat, info


def dir5_one(arg):
    case, work, cadical, seeds, setname, rounds, drop = arg
    S = CADICAL_SETS[setname]
    name = case['case']
    dirs, alpha = case['dirs'], [tuple(x) for x in case['alpha']]
    syms = dir_syms(alpha)
    assert dir_bounds(syms) == alpha and len(syms) + 1 == len(dirs), name
    assert case.get('radius', 3) == S['radius'], name
    meta_path = os.path.join(S['core'], name + '.json')
    if os.path.exists(meta_path):   # resume: the core was generated earlier
        meta = json.load(open(meta_path))
        if os.path.exists(os.path.join(LEAN, 'LocalWindowCnf', meta['module'].split('.')[-1] + '.lean')):
            return (name, meta['module'].split('.')[-1], dirs, syms, len(meta['core_ids']),
                    meta['cnf_clauses'], 'cadical', meta['lrat'])
    cnf_sha = sha_gz(os.path.join(S['certs'], name + '.cnf.gz'))
    assert cnf_sha == case['cnf_sha256'], name
    ids, finfo = full_core_ids(name, work, cadical, seeds, S['certs'], rounds)
    lrat, info = core_lrat(name, ids, work, cadical, seeds, S['certs'], rounds)
    clauses = read_cnf(extract_cnf(name, work, S['certs']))
    assert len(clauses) == case['clauses'], name
    stats = lrat_stats(lrat)
    if drop:   # run_direction_replays.py gen regenerates it (deterministically) when needed
        for ext in ('.lrat', '.lrat.json', '.core.cnf'):
            if os.path.exists(os.path.join(work, name + ext)):
                os.remove(os.path.join(work, name + ext))
    assert (stats['lemmas'], stats['hints']) == (info['lemmas'], info['hints']), name
    core = [clauses[i - 1] for i in ids]
    module = dir_module(dirs, syms, S['prefix'])
    meta = {'name': name, 'module': 'LocalWindowCnf.' + module, 'dirs': dirs, 'syms': syms,
            'window': window_from_dirs(dirs), 'bounds': dir_bounds(syms), 'radius': S['radius'],
            'cnf_clauses': len(clauses), 'cnf_sha256': cnf_sha, 'hash_source': S['index'],
            'core_producer': f"cadical --lrat {finfo['full_seed']} on the committed CNF, trimmed "
                             f"({finfo['full_lemmas']} lemmas, {finfo['full_hints']} hints)",
            'lrat_producer': 'core_lrat (cadical on the core; regenerated, not committed)',
            'variables': case['variables'], 'lrat': stats, 'core_ids': ids}
    json.dump(meta, open(os.path.join(S['core'], name + '.json'), 'w'))
    body = ',\n  '.join('[' + ', '.join(str(2 * l if l > 0 else -2 * l + 1) for l in c) + ']' for c in core)
    src = DIR_TEMPLATE.format(name=name, ncore=len(core), ncl=len(clauses), dirs=dirs, syms=syms,
                              module=module, body=body)
    src = src.replace('(generated by\n`milestones/10-window-aggregate/scripts/gen_lean_core.py --set direction`)',
                      '(generated by\n`milestones/10-window-aggregate/scripts/gen_lean_core.py --set %s`)' % setname)
    if S['radius'] != 3:
        src = src.replace('UNSAT core of direction certificate', 'UNSAT core of radius-%d direction certificate' % S['radius'])
        # the kernel only unfolds the data: no compiled code (12x smaller .olean, half the time)
        src = src.replace('\ndef ', '\nnoncomputable def ')
    open(os.path.join(LEAN, 'LocalWindowCnf', module + '.lean'), 'w').write(src)
    return name, module, dirs, syms, len(core), len(clauses), 'cadical', stats


def main_direction5(a):
    S = dict(CADICAL_SETS[a.set])
    if a.index:
        S['index'] = os.path.relpath(os.path.abspath(a.index), os.path.abspath(DATA))
    CADICAL_SETS[a.set] = S
    os.makedirs(S['core'], exist_ok=True)
    cases = [c for c in json.load(open(os.path.join(DATA, S['index'])))['cases'] if c['drat_trim_verified']]
    n = len(cases)
    old = {}
    if S['reuse']:
        for c in json.load(open(os.path.join(DATA, S['reuse'])))['cases']:
            old[(tuple(c['dirs']), tuple(map(tuple, c['alpha'])))] = c['case']
    res, jobs = [], []
    for c in cases:
        k = (tuple(c['dirs']), tuple(map(tuple, c['alpha'])))
        if k in old:   # reuse the 239 core and its drat-trim LRAT
            meta = json.load(open(os.path.join(DCORE, old[k] + '.json')))
            assert meta['name'] == old[k] == c['case'], (old[k], c['case'])
            shutil.copy2(os.path.join(DCORE, old[k] + '.json'), os.path.join(S['core'], old[k] + '.json'))
            res.append((meta['name'], meta['module'].split('.')[-1], meta['dirs'], meta['syms'],
                        len(meta['core_ids']), meta['cnf_clauses'], meta['hash_source'], meta['lrat']))
        else:
            jobs.append((c, a.work, a.cadical, list(range(1, a.seeds + 1)), a.set, a.rounds, a.drop_lrat))
    if a.set == 'direction5' and not a.index:
        assert n == 325 and len(res) == 145 and len(jobs) == 180, (n, len(res), len(jobs))
    print(f'{a.set}: {n} cases, {len(res)} reused, {len(jobs)} to core', flush=True)
    with Pool(a.jobs) as p:
        res += list(p.imap_unordered(dir5_one, jobs))
    res.sort(key=lambda r: r[1])
    keys = sorted(((r[2], r[3]) for r in res), key=lambda k: (len(k[0]), k[0], k[1]))
    assert len({(tuple(d), tuple(s)) for d, s in keys}) == n and len({r[1] for r in res}) == n
    tot = {'core_clauses': 0, 'cnf_clauses': 0, 'lemmas': 0, 'hints': 0, 'lemma_literals': 0, 'cadical': 0}
    for name, module, dirs, syms, ncore, ncl, source, st in res:
        tot['core_clauses'] += ncore; tot['cnf_clauses'] += ncl
        tot['lemmas'] += st['lemmas']; tot['hints'] += st['hints']
        tot['lemma_literals'] += st['lemma_literals']; tot['cadical'] += source == 'cadical'
        print(f'{name:28s} {module:18s} core {ncore:5d}/{ncl:5d}  lemmas {st["lemmas"]:7d}  '
              f'hints {st["hints"]:9d}  [{source}]')
    print('total', tot)
    body = ',\n  '.join(f'({d}, {s})' for d, s in keys)
    src = KEYS_TEMPLATE.format(body=body)
    src = (src.replace('# The 145 direction-aware window certificates', '# ' + S['title'].format(n=n))
              .replace('the 145 direction', 'the %d' % n)
              .replace('--set direction`', '--set %s`' % a.set)
              .replace('direction_certificates.json', S['index'])
              .replace('def dirKeys :', 'def %s :' % S['keys'])
              .replace('/-- The 145 certificate statements behind the conditional bound 239. -/\n'
                       'def AllRefuted239 : Prop := AllRefutedList dirKeys',
                       '/-- The %d certificate statements behind the conditional bound %d. -/\n'
                       'def %s : Prop := AllRefutedList %s' % (n, S['bound'], S['premise'], S['keys'])))
    assert S['keys'] in src and S['premise'] in src
    open(os.path.join(LEAN, S['keys_mod'] + '.lean'), 'w').write(src)
    json.dump({'set': a.set, 'cases': len(res), 'totals': tot,
               'per_case': {r[0]: {'module': r[1], 'core_clauses': r[4], 'cnf_clauses': r[5],
                                   'hash_source': r[6], **r[7]} for r in res},
               'note': 'Keys shared with the direction set keep their drat-trim LRAT; the other windows '
                       'have cadical --lrat proofs trimmed to the dependencies of the empty clause '
                       '(producer and SHA256 per case; not committed).'},
              open(os.path.join(S['core'], '_summary.json'), 'w'), indent=1)


def main_direction(a):
    os.makedirs(DCORE, exist_ok=True)
    os.makedirs(os.path.join(LEAN, 'LocalWindowCnf'), exist_ok=True)
    cases = json.load(open(os.path.join(DATA, 'direction_certificates.json')))['cases']
