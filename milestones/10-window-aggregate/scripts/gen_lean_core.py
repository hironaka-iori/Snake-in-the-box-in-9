"""Emit the UNSAT cores of the window certificates as Lean data modules.

Two certificate sets are supported:

* `--set window` (default): the 22 shape-blind certificates of `certificates/`;
* `--set direction`: the 145 direction-aware certificates of
  `certificates/direction/` behind the conditional bound 239 (index
  `data/direction_certificates.json`).  The committed CNF/DRUP pairs are checked
  against the SHA256 values recorded in the index or, failing that, in
  `data/direction_certificates_k5.json`: for the 48 windows with cycle cuts the pairs
  were regenerated by the five-centre run, the hashes in the index are stale, and the
  committed pairs match the k5 record (they are consistent and verify).  The script
  writes `LocalWindowCnf/D<dirs>A<syms>.lean`, JSON in `data/lean_core_direction/`
  (with the hashes used and LRAT statistics), and the key list
  `work/final_lean/LocalWindowDirKeys.lean`.

For each certificate NAME the committed CNF and DRUP proof are trimmed by the
vendored drat-trim into an LRAT proof.  The input clauses referenced by its hints
form the core.  This script writes

  work/final_lean/LocalWindowCnf/<Module>.lean   `cnf : List (List Int)` (stored compactly as `raw`), the core
      clauses in increasing original order, with the original variable numbers;
  milestones/10-window-aggregate/data/lean_core/NAME.json
      the original 1-based clause indices of the core, plus window and bounds.

The LRAT file itself (NAME.lrat in --work) is consumed by the Lean checker
exporter; it is large and not committed.

  python gen_lean_core.py --work /tmp/lrat22      # reuses NAME.lrat if present
  python gen_lean_core.py --set direction --work /tmp/lrat145 --jobs 4
"""
import argparse, gzip, hashlib, json, os, re, subprocess, sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
CERTS = os.path.join(HERE, '..', 'certificates')
DATA = os.path.join(HERE, '..', 'data')
LEAN = os.path.join(ROOT, 'work', 'final_lean')

# name -> (window constant in LocalWindowModel, bounds)
SHAPES = {'distinct': ('winDistinct', [0, 1, 3, 7, 15]), 'repeated': ('winRepeated', [0, 1, 3, 7, 6]),
          's01203': ('winQ01203', [0, 1, 3, 7, 6, 14]), 's01230': ('winQ01230', [0, 1, 3, 7, 15, 14]),
          's01234': ('winQ01234', [0, 1, 3, 7, 15, 31])}
COUNTS = {'223': [2, 2, 3], '224': [2, 2, 4], '232': [2, 3, 2], '323': [3, 2, 3],
          '41c': [4, 1, (4, 6)], '2423': [2, 4, 2, 3]}


def bounds_of(code, orient):
    cs = COUNTS[code]
    if orient == 'rev':
        cs = cs[::-1]
    return [(c, c) if isinstance(c, int) else c for c in cs]


def module_name(name):
    code, orient, shape = name.split('_')
    return 'C' + code + orient.capitalize() + shape.capitalize()


def read_cnf(path):
    out = []
    for line in open(path):
        if line.startswith(('p', 'c')) or not line.strip():
            continue
        lits = [int(x) for x in line.split()]
        assert lits[-1] == 0
        out.append(lits[:-1])
    return out


def ensure_lrat(name, work, drat, certs=CERTS):
    lrat = os.path.join(work, name + '.lrat')
    cnf = os.path.join(work, name + '.cnf')
    if not os.path.exists(cnf):
        with gzip.open(os.path.join(certs, name + '.cnf.gz'), 'rb') as f, open(cnf, 'wb') as g:
            g.write(f.read())
    if not os.path.exists(lrat):
        drup = os.path.join(work, name + '.drup')
        with gzip.open(os.path.join(certs, name + '.drup.gz'), 'rb') as f, open(drup, 'wb') as g:
            g.write(f.read())
        r = subprocess.run([drat, cnf, drup, '-L', lrat, '-t', '4000'], capture_output=True, text=True)
        os.remove(drup)
        assert 's VERIFIED' in r.stdout, r.stdout[-500:]
    return cnf, lrat


def core_ids(lrat, ncl):
    used = set()
    for line in open(lrat):
        t = line.split()
        if len(t) > 1 and t[1] == 'd':
            continue
        z = t.index('0', 1)
        for h in t[z + 1:-1]:
            h = int(h)
            assert h > 0, 'RAT hints are not expected'
            if h <= ncl:
                used.add(h)
    return sorted(used)


def lrat_stats(lrat):
    """Added lemmas, total hint ids, lemma literals and deleted ids of an LRAT file."""
    lemmas = hints = dels = lits = 0
    for line in open(lrat):
        t = line.split()
        if len(t) > 1 and t[1] == 'd':
            dels += len(t) - 3
            continue
        z = t.index('0', 1)
        lemmas += 1
        lits += z - 1
        hints += len(t) - z - 2
    return {'lemmas': lemmas, 'hints': hints, 'lemma_literals': lits, 'deleted_ids': dels}


# ---------------------------------------------------------------------------
# Direction-aware certificates (conditional bound 239)

DCERTS = os.path.join(CERTS, 'direction')
DCORE = os.path.join(DATA, 'lean_core_direction')


def dir_syms(alpha):
    """Lumped symbols: the range [s, s] is s (1..5), the range [6, 21] is 6."""
    out = []
    for lo, hi in alpha:
        if lo == hi and 1 <= lo <= 5:
            out.append(lo)
        else:
            assert (lo, hi) == (6, 21), alpha
            out.append(6)
    return out


def dir_bounds(syms):
    """Mirror of `boundOf` in LocalWindowDirModel.lean."""
    return [(s, s) if s < 6 else (6, 21) for s in syms]


def dir_module(dirs, syms):
    return 'D' + ''.join(map(str, dirs)) + 'A' + ''.join(map(str, syms))


def window_from_dirs(ds):
    vs = [0]
    for d in ds:
        vs.append(vs[-1] ^ 1 << d)
    return vs


def sha_gz(path):
    with gzip.open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


DIR_TEMPLATE = '''import LocalWindowDirModel

/-! UNSAT core of direction certificate `{name}` (generated by
`milestones/10-window-aggregate/scripts/gen_lean_core.py --set direction`): {ncore} of
the {ncl} clauses of the committed CNF, in their original order, with the
original variable numbers.  Directions `{dirs}`, lumped counts `{syms}`. -/

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace Snake9.LocalWindow.{module}

def window : List Nat := winOf {dirs}
def bounds : List (Nat × Nat) := boundsOf {syms}

/-- Literals coded by `decodeLit`. -/
def raw : List (List Nat) := [
  {body}]

def cnf : List (List Int) := raw.map (·.map decodeLit)

end Snake9.LocalWindow.{module}
'''

KEYS_TEMPLATE = '''import LocalWindowDirModel

/-!
# The 145 direction-aware window certificates

Generated by `milestones/10-window-aggregate/scripts/gen_lean_core.py --set direction`.
Each key is a canonical direction list (a restricted growth string) and its lumped
counts (`sym α = min α 6`), one per case of
`milestones/10-window-aggregate/data/direction_certificates.json`.  The certificate of
key `(ds, syms)` is the module `LocalWindowCnf.D<ds>A<syms>`: the local CNF of the
canonical window `winOf ds` with count bounds `boundsOf syms`.
-/

namespace Snake9.LocalWindow

def dirKeys : List (List Nat × List Nat) := [
  {body}]

/-- The 145 certificate statements behind the conditional bound 239. -/
def AllRefuted239 : Prop := AllRefutedList dirKeys

end Snake9.LocalWindow
'''


def dir_one(arg):
    case, k5, work, drat = arg
    name = case['case']
    dirs, alpha = case['dirs'], [tuple(x) for x in case['alpha']]
    syms = dir_syms(alpha)
    assert dir_bounds(syms) == alpha, name
    assert len(syms) + 1 == len(dirs) and (dirs, case['alpha']) == (k5['dirs'], k5['alpha']), name
    cnf_sha = sha_gz(os.path.join(DCERTS, name + '.cnf.gz'))
    drup_sha = sha_gz(os.path.join(DCERTS, name + '.drup.gz'))
    if (cnf_sha, drup_sha) == (case['cnf_sha256'], case['drup_sha256']):
        source = 'direction_certificates.json'
    else:
        assert (cnf_sha, drup_sha) == (k5['cnf_sha256'], k5['drup_sha256']), name
        source = 'direction_certificates_k5.json'
    cnf_path, lrat = ensure_lrat(name, work, drat, DCERTS)
    clauses = read_cnf(cnf_path)
    ids = core_ids(lrat, len(clauses))
    stats = lrat_stats(lrat)
    core = [clauses[i - 1] for i in ids]
    module = dir_module(dirs, syms)
    meta = {'name': name, 'module': 'LocalWindowCnf.' + module, 'dirs': dirs, 'syms': syms,
            'window': window_from_dirs(dirs), 'bounds': dir_bounds(syms),
            'cnf_clauses': len(clauses), 'cnf_sha256': cnf_sha, 'drup_sha256': drup_sha,
            'hash_source': source, 'lrat': stats, 'core_ids': ids}
    json.dump(meta, open(os.path.join(DCORE, name + '.json'), 'w'))
    body = ',\n  '.join('[' + ', '.join(str(2 * l if l > 0 else -2 * l + 1) for l in c) + ']' for c in core)
    src = DIR_TEMPLATE.format(name=name, ncore=len(core), ncl=len(clauses), dirs=dirs, syms=syms,
                              module=module, body=body)
    open(os.path.join(LEAN, 'LocalWindowCnf', module + '.lean'), 'w').write(src)
    return name, module, dirs, syms, len(core), len(clauses), source, stats


def main_direction(a):
    os.makedirs(DCORE, exist_ok=True)
    os.makedirs(os.path.join(LEAN, 'LocalWindowCnf'), exist_ok=True)
    cases = json.load(open(os.path.join(DATA, 'direction_certificates.json')))['cases']
    k5 = {c['case']: c for c in json.load(open(os.path.join(DATA, 'direction_certificates_k5.json')))['cases']}
    assert len(cases) == 145
    jobs = [(c, k5[c['case']], a.work, a.drat) for c in cases]
    with Pool(a.jobs) as p:
        res = sorted(p.imap_unordered(dir_one, jobs), key=lambda r: r[1])
    keys = sorted(((r[2], r[3]) for r in res), key=lambda k: (len(k[0]), k[0], k[1]))
    assert len({(tuple(d), tuple(s)) for d, s in keys}) == 145 and len({r[1] for r in res}) == 145
    tot = {'core_clauses': 0, 'cnf_clauses': 0, 'lemmas': 0, 'hints': 0, 'lemma_literals': 0,
           'from_k5_hashes': 0}
    for name, module, dirs, syms, ncore, ncl, source, st in res:
        tot['core_clauses'] += ncore; tot['cnf_clauses'] += ncl
        tot['lemmas'] += st['lemmas']; tot['hints'] += st['hints']
        tot['lemma_literals'] += st['lemma_literals']; tot['from_k5_hashes'] += source.endswith('k5.json')
        print(f'{name:28s} {module:16s} core {ncore:5d}/{ncl:5d}  lemmas {st["lemmas"]:6d}  '
              f'hints {st["hints"]:8d}  [{source}]')
    print('total', tot)
    body = ',\n  '.join(f'({d}, {s})' for d, s in keys)
    open(os.path.join(LEAN, 'LocalWindowDirKeys.lean'), 'w').write(KEYS_TEMPLATE.format(body=body))
    json.dump({'set': 'direction', 'cases': len(res), 'totals': tot,
               'per_case': {r[0]: {'module': r[1], 'core_clauses': r[4], 'cnf_clauses': r[5],
                                   'hash_source': r[6], **r[7]} for r in res},
               'note': 'LRAT produced by drat-trim -L from the committed CNF/DRUP pairs (not '
                       'committed); hints = number of hint ids over all added lemmas.'},
              open(os.path.join(DCORE, '_summary.json'), 'w'), indent=1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--work', required=True)
    ap.add_argument('--drat', default=os.path.join(HERE, '..', '.build', 'drat-trim'))
    ap.add_argument('--set', choices=['window', 'direction'], default='window')
    ap.add_argument('--jobs', type=int, default=4)
    a = ap.parse_args()
    os.makedirs(a.work, exist_ok=True)
    if a.set == 'direction':
        return main_direction(a)
    os.makedirs(os.path.join(LEAN, 'LocalWindowCnf'), exist_ok=True)
    os.makedirs(os.path.join(DATA, 'lean_core'), exist_ok=True)
    names = sorted(f[:-7] for f in os.listdir(CERTS) if f.endswith('.cnf.gz'))
    assert len(names) == 22, names
    for name in names:
        code, orient, shape = name.split('_')
        cnf_path, lrat = ensure_lrat(name, a.work, a.drat)
        clauses = read_cnf(cnf_path)
        ids = core_ids(lrat, len(clauses))
        core = [clauses[i - 1] for i in ids]
        wconst, window = SHAPES[shape]
        bounds = bounds_of(code, orient)
        json.dump({'name': name, 'module': 'LocalWindowCnf.' + module_name(name), 'window': window,
                   'window_const': wconst, 'bounds': bounds, 'cnf_clauses': len(clauses),
                   'core_ids': ids}, open(os.path.join(DATA, 'lean_core', name + '.json'), 'w'))
        body = ',\n  '.join('[' + ', '.join(str(2 * l if l > 0 else -2 * l + 1) for l in c) + ']' for c in core)
        src = f'''import LocalWindowModel

/-! UNSAT core of certificate `{name}` (generated by
`milestones/10-window-aggregate/scripts/gen_lean_core.py`): {len(core)} of the
{len(clauses)} clauses of the committed CNF, in their original order, with the
original variable numbers.  Window `{wconst}`, count bounds `{bounds}`. -/

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace Snake9.LocalWindow.{module_name(name)}

def window : List Nat := {wconst}
def bounds : List (Nat × Nat) := {[tuple(b) for b in bounds]}

/-- Literals coded by `decodeLit`. -/
def raw : List (List Nat) := [
  {body}]

def cnf : List (List Int) := raw.map (·.map decodeLit)

end Snake9.LocalWindow.{module_name(name)}
'''.replace("[(", "[(").replace("), (", "), (")
        open(os.path.join(LEAN, 'LocalWindowCnf', module_name(name) + '.lean'), 'w').write(src)
        print(name, len(core), 'core clauses')


if __name__ == '__main__':
    main()
