"""Independent exact audit of saved short-cycle disagreement inequalities.

Reads immutable model and rational certificates. No optimizer or search is run.
Odd subsets are generated by combinations, independently of the producer's masks.
"""
from pathlib import Path
from fractions import Fraction
from itertools import combinations
from collections import Counter
import hashlib
import json

H = Path(__file__).resolve().parents[1]
PREVIOUS = H.parent / '219-linear-partner'


def load(path):
    return json.loads(path.read_bytes())


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rational(pair):
    assert len(pair) == 2 and all(type(x) is int for x in pair)
    assert pair[1] > 0
    value = Fraction(*pair)
    assert [value.numerator, value.denominator] == pair
    return value


def encoded(value):
    return [value.numerator, value.denominator]


def dot(terms, values):
    return sum((coefficient * values[index] for index, coefficient in terms), Fraction())


def ordered_cycle(vertices, adjacency):
    selected = set(vertices)
    assert len(vertices) in (4, 6) and len(selected) == len(vertices)
    local = {u: sorted(adjacency[u] & selected) for u in selected}
    assert all(len(neighbours) == 2 for neighbours in local.values())
    first = min(selected)
    order = [first, local[first][0]]
    while len(order) < len(selected):
        choices = [u for u in local[order[-1]] if u != order[-2]]
        assert len(choices) == 1 and choices[0] not in order
        order.append(choices[0])
    assert first in local[order[-1]]
    return order


diagnostic_path = H / 'data/parity-diagnostic.json'
diagnostic = load(diagnostic_path)
producer_path = H / 'scripts/parity_diagnostic.py'
assert diagnostic['source_sha256'] == digest(producer_path)
prior_audit_path = H / 'data/forest-audit.json'
prior_audit = load(prior_audit_path)
assert prior_audit['status'] == 'PASS_EXACT_SUBSET_ROWS_UPPERS_PRIMALS_CYCLES_FLOWS_AND_TARGET94'
assert [(r['root'], r['point']) for r in diagnostic['reports']] == [
    (0, 'primal'), (0, 'target94'), (78, 'primal'), (78, 'target94')]

pins = {str(p.relative_to(H)): digest(p) for p in
        (Path(__file__), diagnostic_path, producer_path, prior_audit_path)}
results = []
for root in (0, 78):
    model_path = H / 'data' / f'forest-{root}' / 'model.json'
    model = load(model_path)
    base_path = PREVIOUS / 'data' / f'edge-{root}' / 'model.json'
    base = load(base_path)
    assert digest(base_path) == model['base_model_sha256']
    for key in ('variables', 'vertices', 'edges', 'cycles', 'root', 'objective'):
        assert model[key] == base[key]
    assert model['rows'][:len(base['rows'])] == base['rows']
    frozen = next(record for record in prior_audit['models'] if record['root'] == root)
    assert frozen['pins'][str(model_path.relative_to(H))] == digest(model_path)
    pins[str(model_path.relative_to(H))] = digest(model_path)
    pins[str(base_path)] = digest(base_path)
    names = model['variables']
    index = {name: i for i, name in enumerate(names)}
    assert len(index) == len(names) == 574
    V = set(model['vertices'])
    edges = {tuple(e) for e in model['edges']}
    assert len(V) == 158 and len(edges) == len(model['edges']) == 337
    adjacency = {v: set() for v in V}
    for u, v in edges:
        assert u < v and u in V and v in V and (u ^ v).bit_count() == 1
        adjacency[u].add(v)
        adjacency[v].add(u)
    assert edges == {(u, v) for u in V for v in V if u < v and (u ^ v).bit_count() == 1}
    cycles = [ordered_cycle(cycle, adjacency) for cycle in model['cycles']]
    assert len({frozenset(cycle) for cycle in cycles}) == len(cycles)
    cycle_sets = {frozenset(cycle) for cycle in cycles}
    for kind in ('primal', 'target94'):
        certificate_path = H / 'data' / f'rational-{root}' / f'{kind}-certificate.json'
        certificate = load(certificate_path)
        reported = next(r for r in diagnostic['reports'] if r['root'] == root and r['point'] == kind)
        assert reported['model_sha256'] == certificate['model_sha256'] == digest(model_path)
        assert reported['primal_sha256'] == digest(certificate_path)
        assert frozen['pins'][str(certificate_path.relative_to(H))] == digest(certificate_path)
        pins[str(certificate_path.relative_to(H))] = digest(certificate_path)
        values = [rational(pair) for pair in certificate['values']]
        assert len(values) == len(names) and all(0 <= x <= 1 for x in values)
        objective = sum((a * x for a, x in zip(model['objective'], values)), Fraction())
        assert objective == rational(certificate['objective'])
        assert objective == 94 if kind == 'target94' else objective > 94
        for row in model['rows']:
            lhs = dot(row['terms'], values)
            assert row['sense'] in ('eq', 'le')
            assert lhs == row['rhs'] if row['sense'] == 'eq' else lhs <= row['rhs']

        violations = {}
        subset_count = Counter()
        violations_by_length = Counter()
        violating_cycles = set()
        for cycle in cycles:
            ordered_edges = [tuple(sorted((cycle[i], cycle[(i + 1) % len(cycle)])))
                             for i in range(len(cycle))]
            disagreements = [values[index[f'x{u}']] + values[index[f'x{v}']] -
                             2 * values[index[f'y{u}_{v}']] for u, v in ordered_edges]
            assert all(0 <= value <= 1 for value in disagreements)
            total_disagreement = sum(disagreements, Fraction())
            for size in range(1, len(cycle), 2):
                for subset in combinations(range(len(cycle)), size):
                    subset_count[len(cycle)] += 1
                    lhs = 2 * sum((disagreements[i] for i in subset), Fraction()) - total_disagreement
                    excess = lhs - (size - 1)
                    if excess > 0:
                        key = (tuple(cycle), tuple(subset))
                        violations[key] = excess
                        violations_by_length[len(cycle)] += 1
                        violating_cycles.add(tuple(cycle))
        assert reported['cycles_checked'] == len(cycles)
        assert reported['odd_subsets_checked'] == sum(subset_count.values())
        assert reported['violations_found'] == len(violations)
        witnesses = reported['largest_witnesses']
        assert len(witnesses) == 10
        checked_witnesses = []
        seen = set()
        for witness in witnesses:
            cycle = witness['cycle']
            assert frozenset(cycle) in cycle_sets
            assert cycle == ordered_cycle(cycle, adjacency)
            ordered_edges = [list(sorted((cycle[i], cycle[(i + 1) % len(cycle)])))
                             for i in range(len(cycle))]
            assert witness['edges'] == ordered_edges
            subset = witness['odd_edge_indices']
            assert subset == sorted(set(subset)) and len(subset) % 2 == 1
            assert all(0 <= i < len(cycle) for i in subset)
            key = (tuple(cycle), tuple(subset))
            assert key not in seen and key in violations
            seen.add(key)
            disagreements = [values[index[f'x{u}']] + values[index[f'x{v}']] -
                             2 * values[index[f'y{u}_{v}']] for u, v in ordered_edges]
            assert [encoded(x) for x in disagreements] == witness['disagreements']
            lhs = sum((d if i in subset else -d for i, d in enumerate(disagreements)), Fraction())
            rhs = len(subset) - 1
            assert rational(witness['lhs']) == lhs and witness['rhs'] == rhs
            assert rational(witness['violation']) == lhs - rhs == violations[key] > 0
            checked_witnesses.append(dict(cycle=cycle, odd_edge_indices=subset,
                                         disagreements=[encoded(d) for d in disagreements],
                                         violation=encoded(lhs-rhs)))
        expected_top = sorted(violations.values(), reverse=True)[:10]
        assert [rational(w['violation']) for w in witnesses] == expected_top
        results.append(dict(root=root, point=kind, exact_cardinality=encoded(objective),
                            model_rows_checked=len(model['rows']), variable_bounds_checked=len(values),
                            cycle_count_by_length=dict(Counter(map(len, cycles))),
                            odd_subsets_checked=sum(subset_count.values()),
                            odd_subsets_by_cycle_length=dict(subset_count),
                            violations_found=len(violations),
                            violations_by_cycle_length=dict(violations_by_length),
                            distinct_violating_cycles=len(violating_cycles),
                            largest_violation=encoded(expected_top[0]),
                            largest_violation_decimal=float(expected_top[0]),
                            ten_worst_witnesses_checked=checked_witnesses))

proof_path = H / 'data/SquareParity220-audit.json'
proof = load(proof_path)
assert proof['status'] == 'PASS' and proof['exit_code'] == 0 and proof['stop_reason'] is None
for path_key, hash_key in (('source', 'source_sha256'), ('object', 'olean_sha256'), ('log', 'log_sha256')):
    assert digest(Path(proof[path_key])) == proof[hash_key]
for path, expected in proof['dependencies'].items():
    assert digest(Path(path)) == expected
assert len(proof['axioms']) == 3
assert all(set(report['axioms']) <= {'propext', 'Classical.choice', 'Quot.sound'} for report in proof['axioms'])
pins[str(proof_path.relative_to(H))] = digest(proof_path)
result = dict(status='PASS_EXACT_SHORT_CYCLE_PARITY_AUDIT', reports=results,
              total_saved_witnesses_verified=40,
              scope='Exact rational audit of every odd subset on the saved 4- and 6-cycles only; no optimizer, software tests, full cycle enumeration, or new LP bound.',
              conclusion='All four round-220 rational assignments violate valid cycle disagreement inequalities, including the target-94 assignments. These inequalities remove the saved points; feasibility of different target-94 points is unresolved.',
              proof=dict(receipt=str(proof_path.relative_to(H)), status='PASS', seconds=proof['seconds'],
                         axioms=proof['axioms'],
                         scope='Std-only Boolean product/disagreement identity and both square inequality forms. General-cycle theorem and rational-array composition are not compiled here.'),
              pins=pins)
output = H / 'data/parity-audit.json'
assert not output.exists()
output.write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
print(json.dumps({k: v for k, v in result.items() if k not in ('reports', 'pins')}, indent=2))
for report in results:
    print(json.dumps({k: v for k, v in report.items() if k != 'ten_worst_witnesses_checked'}))
