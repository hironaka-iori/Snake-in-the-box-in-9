"""Prepare an immutable reconstruction from144; no graph loading or optimization."""
from pathlib import Path
import ast
import hashlib
import json

H = Path(__file__).resolve().parents[1]
R = H.parents[1]
ORIGINAL = R / 'milestones/144-countfree-share18/scripts/evaluate_graph.py'
EXPECTED = '25bb5aab4657577caf2e5941f23b44e18a36f9e4fe8a44bc538ca277306168ba'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    assert sha(ORIGINAL) == EXPECTED
    source = ORIGINAL.read_text(encoding='utf-8')
    first = source.index('rules = read((HERE / args.rules)')
    last = source.index("pool = np.flatnonzero(alg['prune']")
    block = source[first:last]
    nodes = ast.parse(block).body
    removed = []
    lines = block.splitlines(keepends=True)
    for node in nodes:
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            function = node.value.func
            if isinstance(function, ast.Attribute) and function.attr == 'write_text':
                text = ast.get_source_segment(block, node)
                assert ('baseline121-removed-indices.json' in text or "folder/'removed-indices.json'" in text)
                removed.append(text)
                lines[node.lineno-1:node.end_lineno] = ['# Original archival write omitted; all mathematical checks retained.\n']
    assert len(removed) == 2
    adapted = ''.join(lines)
    # Every removed statement occupies one line, so the two substitutions cannot
    # shift later line indices. All mathematical statements remain byte-identical.
    assert all('\n' not in item for item in removed)
    for item in removed:
        block = block.replace(item, '# Original archival write omitted; all mathematical checks retained.', 1)
    assert adapted == block
    proof = next(node for node in ast.parse(source).body
                 if isinstance(node, ast.FunctionDef) and node.name == '_checked_weak_exclusion')
    proof_text = ast.get_source_segment(source, proof)
    generated = '''"""Exact144 reconstruction prefix, with only its two archival writes omitted.
Generated by prepare_sources.py. No original optimizer, Git extraction or CIM.
"""
from pathlib import Path
from fractions import Fraction
from types import SimpleNamespace
import hashlib, json, re, sys, time
H = Path(__file__).resolve().parents[1]
ROOT = H.parents[1]
_home = ROOT / 'milestones/144-countfree-share18'
'''
    generated += proof_text + '\n\n'
    generated += 'RECONSTRUCTION = ' + repr(adapted) + '\n\n'
    generated += '''def reconstruct(np):
    namespace = dict(ROOT=ROOT, HERE=_home, np=np, Path=Path,
        Fraction=Fraction, hashlib=hashlib, json=json, time=time,
        args=SimpleNamespace(rules='../120-nine-transition-window/data/full-rules.json'),
        coefficients=[24,24,24,24,24], pins={},
        DERIVED_SOURCE_SHA256='066b117d63f3d6cf78341073fa7b7a09dd39946a7f4b77961bf71b23114e782f',
        _proof_gate_info=_checked_weak_exclusion())
    setup = """sha = lambda b: hashlib.sha256(b).hexdigest()
def read(rel):
    raw = (ROOT / rel).read_bytes()
    pins[rel] = sha(raw)
    return json.loads(raw)
def canon(word):
    names = {}
    return tuple(names.setdefault(int(x), len(names)) for x in word)
def shape(word):
    return min(canon(word), canon(word[::-1]))
"""
    exec(compile(setup, '<reconstruction-helpers156>', 'exec'), namespace)
    exec(compile(RECONSTRUCTION, '<exact144-prefix156>', 'exec'), namespace)
    return {key: namespace[key] for key in
        ['arrays','meta','ds','mask','shared','completed','pins','digits']}
'''
    ast.parse(generated)
    target = H / 'scripts/reconstruct144.py'
    helper = H / 'scripts/native_resources.py'
    helper_original = R / 'milestones/154-share17-broader-semantics/scripts/native_resources.py'
    assert sha(helper_original) == '2e9e7d499ef7068d10d7ca7e31c9a9dc7ef19abb72b0396d3eab9824376b4413'
    assert not target.exists() and not helper.exists()
    target.write_text(generated, encoding='utf-8', newline='\n')
    helper.write_bytes(helper_original.read_bytes())
    scripts = sorted((H / 'scripts').glob('*.py'))
    for path in scripts:
        compile(ast.parse(path.read_text(encoding='utf-8')), str(path), 'exec')
    plan = R / 'work/after155-potential-plan.json'
    pins = json.loads(plan.read_text(encoding='utf-8'))['input_pins']
    # Paper hashes describe the inspected context. The paper is expected to change
    # after155 completion and is not an executable graph reconstruction dependency.
    pins.pop('paper/snake9_research.tex')
    record = dict(status='SOURCE_PREPARED_NOT_EXECUTED', original_reconstruction_sha256=EXPECTED,
        original_prefix_start_line=source[:first].count('\n')+1,
        original_prefix_end_line=source[:last].count('\n'),
        removed_statements=removed, mathematical_statements_unchanged=True,
        script_pins={p.relative_to(R).as_posix(): sha(p) for p in scripts},
        plan_path=plan.relative_to(R).as_posix(), plan_sha256=sha(plan),
        input_pins=pins, context_only_pin_exclusions=['paper/snake9_research.tex'],
        no_graph_arrays_loaded=True, no_optimizer_started=True, no_Lean_started=True,
        discovery_seconds=600, iteration_limit=1500)
    (H / 'data').mkdir(exist_ok=True)
    output = H / 'data/preparation.json'
    assert not output.exists()
    output.write_text(json.dumps(record, indent=2)+'\n', encoding='utf-8', newline='\n')
    print(json.dumps(dict(status=record['status'], scripts=len(scripts), input_pins=len(pins))))


if __name__ == '__main__':
    main()
