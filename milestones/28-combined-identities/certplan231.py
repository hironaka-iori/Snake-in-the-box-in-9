def level_fit(res, c_fixed=None):
    """Per share kind: log h = log A + b log s + c log(L / T) on the sampled records (s = solver seconds
    of the source call at level T, L = the level re-solved); c is fitted jointly over the three kinds
    (the 5-window sample has almost no record with L < T)."""
    rows = {k: [r for r in res if r['kind'] == k and r.get('status') == 'UNSAT' and r.get('hints')
                and (r.get('seconds') or 0) > 0.05 and r.get('source_T')] for k in ('5', 'c7', 'c8')}
    if c_fixed is None:
        X, y = [], []
        ks = list(rows)
        for ki, k in enumerate(ks):
            for r in rows[k]:
                v = [0.0] * (2 * len(ks) + 1)
                v[2 * ki] = 1.0; v[2 * ki + 1] = math.log(r['seconds']); v[-1] = math.log(r['level'] / r['source_T'])
                X.append(v); y.append(math.log(r['hints']))
        co, *_ = np.linalg.lstsq(np.array(X), np.array(y), rcond=None)
        c_fixed = float(co[-1])
    out = {}
    for k, rs in rows.items():
        s_ = np.array([r['seconds'] for r in rs]); h = np.array([r['hints'] for r in rs], float)
        q = np.array([r['level'] / r['source_T'] for r in rs])
        A = np.vstack([np.ones(len(rs)), np.log(s_)]).T
        co, *_ = np.linalg.lstsq(A, np.log(h) - c_fixed * np.log(q), rcond=None)
        pred = np.exp(A @ co + c_fixed * np.log(q))
        # bias correction: scale so that the sample's total is reproduced
        sc = float(h.sum() / pred.sum())
        out[k] = dict(A=float(np.exp(co[0])) * sc, b=float(co[1]), c=c_fixed, n=len(rs),
                      log_sd=float(np.std(np.log(h) - np.log(pred))), total_scale=sc)
    return out


def apply_calibration(W, cal, res=None):
    """Costs on the calibrated basis: plain keys by measured/model per log10 bin (calib_factors);
    share certificates by the level-aware fit (level_fit) when results are given."""
    W.cbins = {k: {int(b): f for b, f in v['bins'].items()} for k, v in cal.items()}
    if res:
        W.levelfit = level_fit(res)
        L.log(f'level fit: {W.levelfit}')
    for j in range(W.nK):
        if not W.kfree[j]:
            W.khints[j] *= W.calf('plain', W.khints[j])
            W.kcost[j] = W.khints[j] + OVH_CERT


def apply_cap(W, cap):
    """Forbid every certificate above `cap` calibrated hints: plain keys leave the pool (unchosen,
    never re-chosen), share ids get the largest level whose cheapest call costs <= cap."""
    W.cap = cap
    forb = np.flatnonzero(~W.kfree & (W.khints > cap))
    for j in forb:
        if W.chosen[j]:
            W.chosen[j] = False
    W.forbidden = set(int(j) for j in forb)
    W.recount()
    nl = 0; capped = []
    for i in np.flatnonzero(W.lvl > W.sF):
        lv = int(W.lvl[i])
        if W.share_cost(i, lv)[0] <= cap:
            continue
        ok = [T for T, s_ in W.scalls[i] if s_ is not None and T <= lv and W.share_cost(i, T)[0] <= cap]
        new = max(ok + [int(W.sF[i])])
        # the cheapest call >= new must be <= cap: walk down
        while new > W.sF[i] and W.share_cost(i, new)[0] > cap:
            new -= 1
        capped.append((int(i), lv, new)); W.lvl[i] = new; nl += 1
    W.slb_cap = W.lvl.copy()
    return len(forb), capped


def missing_tests(W, tl=300, maxjobs=20000):
    """Solver tests that could restore feasibility under the cap.  For every critical transition that
    is left uncovered (no plain key, every share source below its need T, with the potential of the
    uncapped plan): the 5-window threshold at T (unless a witness shows share < T), the ctx-7 and
    the ctx-8 threshold at T (same rule).  A test that is UNSAT within `tl` seconds is priced near or
    under the cap.  Jobs are deduplicated per window (max T), sorted by the number of transitions."""
    crit, need = W.critical()
    Sx = W.S(np.arange(W.N))
    es = np.flatnonzero(crit & (W.cnt == 0) & (Sx < need))
    X = S7.Ctx()
    O = L.share_records28()
    jobs, cnt = {}, collections.Counter()
    for e in es:
        ds, t, k5, k6 = C.step_windows(int(e), W.Pr)
        T = int(need[e])
        st5 = O.st.get(C.rkey_of(k5))
        if not (st5 and (st5['ub'] < T or st5.get('excl'))):
            jobs[('t', k5)] = max(jobs.get(('t', k5), 0), T); cnt[('t', k5)] += 1
        for ctx in (7, 8):
            c = C.canon(ds[8 - ctx:])
            key = (ctx, c, tuple(t))
            sx = X.st.get(key)
            if sx and (sx['lb'] >= T or sx['ub'] < T):
                continue
            jobs[('c', key)] = max(jobs.get(('c', key), 0), T); cnt[('c', key)] += 1
    out = []
    for k, T in sorted(jobs.items(), key=lambda kv: -cnt[kv[0]]):
        if k[0] == 't':
            out.append(dict(kind='t', key=[list(k[1][0]), list(k[1][1])], T=int(T), tl=tl, transitions=cnt[k]))
        else:
            out.append(dict(kind='c', key=[k[1][0], list(k[1][1]), list(k[1][2])], T=int(T), tl=tl, transitions=cnt[k]))
    return out[:maxjobs], int(len(es))


def cmd_full(a):
    """dual -> derive -> giants -> cap -> dual -> exact, on calibrated costs."""
    from fractions import Fraction as Fr
    lt = Fr(a.lam); P, Q = lt.numerator, lt.denominator
    B = a.bits or bits_of(P, Q)
    W = make_world(P, Q, B)
    res = load_results(a.results) if os.path.exists(a.results or os.path.join(DATA, 'certsample231_results.jsonl.gz')) else []
    cal = calib_factors(res) if res else {}
    apply_calibration(W, cal, res)
    hist_fit = getattr(W, 'levelfit', None)
    L.log(f'calibration bins: { {k: v["bins"] for k, v in cal.items()} }')
    hist = dict(target=TARGET, calibration={k: {x: v[x] for x in ('n', 'pooled', 'bins')} for k, v in cal.items()},
                level_fit=hist_fit)
    if a.tag0:
        s0, miss = load_plan(W, a.tag0)
        hist['loaded'] = a.tag0
    hist['dual0'] = run_dual(W)
    if not hist['dual0']['ok']:
        L.log(f'infeasible at {P}/{Q}/{B}: {hist["dual0"]}'); return
    if True:                                  # feasibility under the cap on the full data, before any pruning
        lv_b, ch_b = W.lvl.copy(), W.chosen.copy()
        nf0, cap0 = apply_cap(W, a.max_cert_hints)
        ok0, _, r0 = W.check()
        hist['cap_full_data'] = dict(ok=bool(ok0), range=r0, plain_forbidden=nf0, share_capped=len(cap0))
        L.log(f'cap on the full data: ok {ok0} range {r0}')
        W.forbidden = set(); W.lvl = lv_b; W.set_chosen(ch_b); W.check()
    if not a.tag0:
        js = np.flatnonzero(W.chosen & ~W.kfree)
        nd, ncand = W.mark_derivable(js)
        hist['derivable'] = dict(derived=nd, checked=len(js))
        run_dual(W)
    # giants: every kept plain key above a third of the cap
    a.min = a.max_cert_hints / 3; a.budget = a.giants_s
    hist['giants'] = giants_step(W, a)
    ok, it, rng = W.check(); assert ok
    pi0 = W.pi.copy()
    # the cap acts on the full data: every pool key chosen again, every share id at its proved level
    W.chosen[:] = True; W.recount(); W.lvl = np.maximum(W.lvl0, W.sF)
    nforb, capped = apply_cap(W, a.max_cert_hints)
    ok, it, rng = W.check()
    hist['cap'] = dict(cap=a.max_cert_hints, plain_forbidden=nforb, share_capped=len(capped), ok=bool(ok), range=rng)
    L.log(f'cap {a.max_cert_hints:.3g}: {nforb} plain keys forbidden, {len(capped)} share ids capped; ok {ok} range {rng}')
    if not ok:
        W.pi = pi0
        jobs, nunc = missing_tests(W)
        hist['cap']['uncovered_transitions'] = nunc; hist['cap']['missing_jobs'] = len(jobs)
        p = os.path.join(DATA, f'split231_jobs_{a.tag}.jsonl.gz')
        with gzip.GzipFile(p, 'wb', mtime=0) as g:
            g.write(''.join(json.dumps(j) + '\n' for j in jobs).encode())
        L.log(f'infeasible under the cap: {nunc} uncovered critical transitions, {len(jobs)} missing ctx tests -> {p}')
        # keep the capped levels for the report, restore feasibility without the cap for the rest
        save_plan(W, a.tag + '_capfail', dict(steps=hist))
        return
    hist['dual1'] = run_dual(W)
    if a.exact_s > 0:
        hist['exact'] = exact_pass(W, a.exact_s)
        ok, it, rng = W.check(); assert ok
        hist['dual2'] = run_dual(W)
    s = save_plan(W, a.tag, dict(steps=hist))
    L.log(json.dumps(s))


