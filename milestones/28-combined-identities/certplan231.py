def bits_of(P, Q):
    g = 225 * P - 125400 * Q
    return None if g < 2 else g.bit_length() - 1 if 2 ** (g.bit_length() - 1) <= g else None


def bound231(P, Q, B):
    return int(C.bound_m(P, Q, 2 ** B - 1, 1, 0, 0))


