def run_dual(W, passes=6, log=True):
    ok, it, rng = W.check()
    if not ok:
        return dict(ok=False, range=rng, rounds=it)
    hist = []
    for p in range(passes):
        dk, ds, nc = W.dual()
        ok, it, rng = W.check()
        assert ok, 'dual pass broke the potential'
        hist.append(dict(dropped=dk, lowered=ds, critical=nc, range=rng, rounds=it))
        if log:
            L.log(f'  dual pass {p}: {hist[-1]}')
        if dk == 0 and ds == 0:
            break
    return dict(ok=True, passes=hist)


def save_plan(W, tag, extra=None):
    s = W.summary()
    if extra:
        s.update(extra)
    plain, share = W.rows()
    path = os.path.join(DATA, f'certplan231_{tag}.json.gz')
    with gzip.GzipFile(path, 'wb', mtime=0) as g:
        g.write(json.dumps(dict(summary=s, plain=plain, share=share,
                                format=dict(plain='kind plain: key [dirs, lumped syms]; free = Lean-replayed or derivable',
                                            share='kind 5 / c7 / c8: key [dirs, t] (5: lumped 5-window key; c7/c8: '
                                                  'canonical ctx dirs, 6 lumped counts of vertices n+2..n+7); level = '
                                                  'share >= level needed; proved = best UNSAT level; source = the '
                                                  'cheapest UNSAT call at a level >= level')),
                           separators=(',', ':')).encode())
    json.dump(s, open(os.path.join(DATA, f'certplan231_{tag}_summary.json'), 'w'), indent=1)
