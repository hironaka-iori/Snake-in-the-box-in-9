def free233():
    """(plain keys, H8 keys, {k5: level}, seeds [(kind, ds, syms), wide]) of milestone 33's chain."""
    d = json.load(gzip.open(os.path.join(M31, 'data', 'keys233_best.json.gz'), 'rt'))
    plain = {L.lk_of(ds, sy) for ds, sy, b, h in d['plain']}
    h8 = [(tuple(ds), tuple(sy)) for ds, sy, h in d['h8']]
    share = {}
    for ds, sy, T, lb, b, h in d['share']:
        if b != 'lean_floor':
            k = L.lk_of(ds, sy)
            share[k] = max(share.get(k, 0), int(T))
    s = json.load(gzip.open(os.path.join(M33, 'certify', 'data', 'seeds6SB233.json.gz'), 'rt'))
    keys = [(k[0], tuple(k[1]), tuple(k[2])) for k in s['keys']]
    seeds = [(keys[i], [tuple(x) for x in w]) for i, w in s['seeds']]
    return plain, h8, share, seeds


def derivable_from_seeds(cands, seeds):
    """The lumped keys of `cands` that some widened 233 seed implies by L1 or L2 (families_k7 mirror of
    LocalWindowFamilies; the derived key is one `refuted_key_of_wide` / `refuted_key_sub` term)."""
    sys.path.insert(0, os.path.join(MS, '25-k7-234', 'certify'))
    import families_k7 as FK
    byds = collections.defaultdict(list)
    for sd, w in seeds:
        byds[FK.canon(sd[1])].append((sd, w))
        byds[FK.canon(sd[1][::-1])].append((sd, w))
    out = {}
    n = 0
    for k in cands:
        ds2, sy2 = list(k[0]), list(k[1])
        key = ('k6', ds2, sy2)
        hit = None
        for Lw in range(2, len(ds2) + 1):
            for i in range(0, len(ds2) - Lw + 1):
                for sd, w in byds.get(FK.canon(ds2[i:i + Lw]), ()):
                    n += 1
                    dv = FK.derivable(sd, w, key)
                    if dv:
                        hit = (sd, dv[0]); break
                if hit:
                    break
            if hit:
                break
        if hit:
            out[k] = hit
    return out, n


# ------------------------------------------------------------------ the world
class World231(E.World):
    """eng233.World with the context share sources and the 233 chain's free certificates."""

    def __init__(self, P, Q, B, pool=None, verbose=True, no_c8=False):
        self.ctx_loaded = False
        self.no_c8 = no_c8
        super().__init__(P, Q, B, pool=pool, verbose=verbose)
        self.add_ctx(verbose)
        self.add_free233(verbose)
        self.lvl0 = self.lvl.copy()

    # ---- share sources: ids [0, nS) 5-window, [o7, o8) ctx 7, [o8, Z) ctx 8, Z = zero sentinel
    def add_ctx(self, verbose):
        t0 = time.time()
        X = S7.Ctx()
        I = S7.ctx_index(self.Pr, C.canon)
        rows = {7: [], 8: []}
        for (ctx, c, t), s in X.st.items():
            if s['lb'] > 0 and not (ctx == 8 and self.no_c8):
                rows[ctx].append(((ctx, c, t), s['lb']))
        calls = collections.defaultdict(list)
        for r in S7.records():
            if r.get('kind') == 'thr_ctx' and r['result'] == 'UNSAT':
                calls[(r['ctx'], tuple(r['dirs']), tuple(r['t']))].append((int(r['T']), float(r['seconds'])))
        nS = self.nS
        self.o7 = nS; self.o8 = nS + len(rows[7]); self.Z = self.o8 + len(rows[8])
        self.xkeys = [None] * nS + [k for k, _ in rows[7]] + [k for k, _ in rows[8]]
        tot = self.Z + 1
        slb = np.zeros(tot, np.int64); slb[:nS] = self.slb
        sF = np.zeros(tot, np.int64); sF[:nS] = self.sF
        self.x7 = np.full(self.N, self.Z, np.int32); self.x8 = np.full(self.N, self.Z, np.int32)
        sc = self.scalls + [[] for _ in range(tot - nS)]
        for ctx, arr, off in ((7, self.x7, self.o7), (8, self.x8, self.o8)):
            for j, (k, lb) in enumerate(rows[ctx]):
                es = I.get((ctx, tuple(k[1])), [])
                if not es:
                    continue
                g = np.array(es, np.int64) * NT + GA.cnt_idx(tuple(k[2]))
                arr[g] = off + j
                slb[off + j] = lb
                sc[off + j] = sorted(calls.get(k, []))
        self.slb, self.sF, self.scalls = slb, sF, sc
        self.lvl = slb.copy()
        self.ctx_ord = {}
        for ctx, arr, off, end in ((7, self.x7, self.o7, self.o8), (8, self.x8, self.o8, self.Z)):
            m = np.flatnonzero(arr != self.Z).astype(np.int64)
            o = m[np.argsort(arr[m], kind='stable')]
            st = np.searchsorted(arr[o], np.arange(off, end + 1))
            self.ctx_ord[ctx] = (o, st, off)
        self.ctx_loaded = True
        if verbose:
            L.log(f'ctx: {len(rows[7])} ctx-7 and {len(rows[8])} ctx-8 keys with lb > 0; '
                  f'{int((self.x7 != self.Z).sum())} / {int((self.x8 != self.Z).sum())} transitions; '
                  f'{time.time() - t0:.0f}s rss {C.rss_mb():.0f}')

    def kind_of(self, i):
        return '5' if i < self.o7 else 'c7' if i < self.o8 else 'c8' if i < self.Z else 'zero'

    def share_edges_all(self, i):
        if i < self.nS:
            return self.sord[self.sstart[i]:self.sstart[i + 1]].astype(np.int64)
        ctx = 7 if i < self.o8 else 8
        o, st, off = self.ctx_ord[ctx]
        return o[st[i - off]:st[i - off + 1]]

    def share_edges(self, i):
        es = self.share_edges_all(i)
        return es[self.cnt[es] == 0]

    def S(self, es):
        return np.maximum(np.maximum(self.lvl[self.k5[es]], self.lvl[self.x7[es]]), self.lvl[self.x8[es]])

    def w(self, es):
        if not getattr(self, 'ctx_loaded', False):
            return E.World.w(self, es)
        return self.Q * (120 * self.s[es] + self.S(es)) - self.P

    def other_level(self, i, es):
        """max level at es of the two sources other than id i's."""
        a = self.lvl[self.k5[es]] if i >= self.nS else np.zeros(len(es), np.int64)
        b = self.lvl[self.x7[es]] if not (self.o7 <= i < self.o8) else np.zeros(len(es), np.int64)
        c = self.lvl[self.x8[es]] if not (self.o8 <= i < self.Z) else np.zeros(len(es), np.int64)
        return np.maximum(np.maximum(a, b), c)

    # ---- free certificates of the 233 chain
    def add_free233(self, verbose):
        t0 = time.time()
        plain, h8, share, seeds = free233()
        self.free233 = dict(plain=0, derived=0, h8=0, share=0)
        for k in plain:
            j = self.kid.get(k)
            if j is not None and not self.kfree[j]:
                self.kfree[j] = True; self.kcost[j] = 0.0; self.kbasis[j] = 'reuse233'
                self.free233['plain'] += 1
        self.seeds233 = seeds
        self.sF5main = self.sF.copy()
        for k, lv in share.items():
            i = self.k5id.get(k)
            if i is not None and lv > self.sF[i]:
                self.sF[i] = lv; self.free233['share'] += 1
        self.slb = np.maximum(self.slb, self.sF); self.lvl = np.maximum(self.lvl, self.sF)
        # the 262 H8 cuts: one exclusion per transition whose H8 window is the key (steps233.h8_key)
        idx = collections.defaultdict(list)
        for e, (_, _, _, ds) in enumerate(self.Pr.ext):
            idx[C.canon(tuple(reversed(ds)))].append(e)
        ks, gs = [], []
        for dsr, syr in h8:
            for e in idx.get(dsr, []):
                ks.append(('H', dsr, syr, e)); gs.append(e * NT + GA.cnt_idx(tuple(reversed(syr))))
        if gs:
            self.kg = np.concatenate([self.kg, np.array(gs, np.int32)])
            self.kptr = np.concatenate([self.kptr, self.kptr[-1] + np.arange(1, len(gs) + 1)])
            for k in ks:
                self.kid[k] = len(self.keys); self.keys.append(k)
            self.nK = len(self.keys)
            n = len(gs)
            self.khints = np.concatenate([self.khints, np.zeros(n)]); self.kcore = np.concatenate([self.kcore, np.zeros(n)])
            self.kbasis += ['reuse233_H8'] * n
            self.kfree = np.concatenate([self.kfree, np.ones(n, bool)])
            self.kcost = np.concatenate([self.kcost, np.zeros(n)])
            self.chosen = np.concatenate([self.chosen, np.ones(n, bool)])
            self.recount()
            self.free233['h8'] = n
        if verbose:
            L.log(f'free from 233: {self.free233}; {time.time() - t0:.0f}s')

    def mark_derivable(self, js):
        """Mark the pool keys js that a 233 seed implies (L1/L2) as free."""
        ks = [self.keys[j] for j in js if len(self.keys[j]) == 2 and not self.kfree[j]]
        d, n = derivable_from_seeds(ks, self.seeds233)
        for k, (sd, m) in d.items():
            j = self.kid[k]
            self.kfree[j] = True; self.kcost[j] = 0.0; self.kbasis[j] = 'derive233_' + m
        self.free233['derived'] += len(d)
        return len(d), n

    # ---- costs
    def calf(self, kind, h):
        """Calibration factor (measured replay / model, by log10 bin of the model hints) or 1."""
        cb = getattr(self, 'cbins', {}).get(kind)
        if not cb:
            return 1.0
        return cb[min(8, max(3, int(math.floor(math.log10(max(h, 1.0))))))]

    def ctx_factor(self, kind, h=1e6):
        return self.calf(kind, h)

    def share_cost(self, i, lv):
        if lv <= self.sF[i]:
            return 0.0, 'lean_floor' if i < self.nS and lv <= L.share_floor_level(self, i) else 'free233'
        lf = getattr(self, 'levelfit', None)
        if lf:                                    # measured fit: h = A s^b (lv / T)^c, cheapest call T >= lv
            f = lf[self.kind_of(i)]
            cs = [(T, s_) for T, s_ in self.scalls[i] if T >= lv and s_ is not None]
            if cs:
                return max(8111.0, min(f['A'] * max(s_, 0.01) ** f['b'] * max(lv / T, 0.4) ** f['c']
                                       for T, s_ in cs)), 'fit'
        if i < self.nS:
            h, b = E.World.share_cost(self, i, lv)
            return h * self.ctx_factor('5', h), b
        cs = [s for T, s in self.scalls[i] if T >= lv]
        if not cs:
            h = L.share_hints(1.0, self.cal)
            return h * self.ctx_factor(self.kind_of(i), h), 'noseconds'
        h = L.share_hints(min(cs), self.cal)
        return h * self.ctx_factor(self.kind_of(i), h), 'model'

    def share_obj(self, i, lv):
        h, b = self.share_cost(i, lv)
        return 0.0 if b in ('lean_floor', 'free233') else h + OVH_CERT

    # ---- dual reverse-delete with three sources
    def critical(self):
        Q, P = self.Q, self.P
        red0 = Q * 120 * self.s - P + self.pi[self.u] - self.pi[self.v]
        crit = red0 < 0
        need = np.where(crit, (-red0 + Q - 1) // Q, 0)
        return crit, need

    def dual(self):
        crit, need = self.critical()
        shcov = crit & (self.S(np.arange(self.N)) >= need)
        items = [(self.kcost[j], 0, int(j)) for j in np.flatnonzero(self.chosen & ~self.kfree)]
        items += [(self.share_obj(i, self.lvl[i]), 1, int(i)) for i in np.flatnonzero(self.lvl > self.sF)]
        items.sort(key=lambda t: -t[0])
        dk = ds = 0
        for c, kind, j in items:
            if kind == 0:
                gs = self.hits(j)
                gc = gs[crit[gs]]
                if len(gc) and not np.all((self.cnt[gc] >= 2) | shcov[gc]):
                    continue
                self.cnt[gs] -= 1; self.chosen[j] = False; dk += 1
            else:
                es = self.share_edges_all(j)
                ec = es[crit[es]]
                oth = self.other_level(j, ec)
                unc = (self.cnt[ec] == 0) & (oth < need[ec])
                nl = max(int(need[ec][unc].max()) if unc.any() else 0, int(self.sF[j]))
                if nl < self.lvl[j]:
                    self.lvl[j] = nl; ds += 1
                    shcov[ec] = need[ec] <= np.maximum(oth, nl)
        return dk, ds, int(crit.sum())

    # ---- summary / io
    def rows(self):
        """Needed certificates: plain (paid and free) and share ids above their free level."""
        plain = []
        for j in np.flatnonzero(self.chosen):
            k = self.keys[j]
            if len(k) != 2:
                continue
            plain.append(dict(kind='plain', key=[list(k[0]), list(k[1])], centres=len(k[1]),
                              basis=self.kbasis[j], free=bool(self.kfree[j]), est_hints=round(float(self.khints[j]))))
        share = []
        for i in np.flatnonzero(self.lvl > 0):
            lv = int(self.lvl[i]); h, b = self.share_cost(i, lv)
            kd = self.kind_of(i)
            cs = [(T, s) for T, s in self.scalls[i] if T >= lv]
            src = min(cs, key=lambda x: (x[1] if x[1] is not None else 1e9)) if cs else None
            if kd == '5':
                key = [list(self.k5keys[i][0]), list(self.k5keys[i][1])]
            else:
                ctx, c, t = self.xkeys[i]
                key = [list(c), list(t)]
            share.append(dict(kind=kd, key=key, level=lv, proved=int(self.slb[i]),
                              source=dict(T=src[0], seconds=src[1]) if src else None,
                              basis=b, free=b in ('lean_floor', 'free233'), est_hints=round(h)))
        return plain, share

    def summary(self):
        plain, share = self.rows()
        out = dict(P=self.P, Q=self.Q, B=self.B, lam=self.P / self.Q, lam_alpha=self.P / self.Q / 120,
                   Rmax=self.Rmax, range=int(-self.pi.min()), bound=bound231(self.P, self.Q, self.B),
                   slack=slack_of(self.P, self.Q, self.B), target=TARGET)
        pp = [r for r in plain if not r['free']]
        out['plain'] = dict(keys=len(plain), free=len(plain) - len(pp), paid=len(pp),
                            hints=sum(r['est_hints'] for r in pp),
                            free_by=dict(collections.Counter(r['basis'].split('_')[0] for r in plain if r['free'])),
                            paid_by_centres=dict(collections.Counter(str(r['centres']) for r in pp)))
        for kd in ('5', 'c7', 'c8'):
            rs = [r for r in share if r['kind'] == kd]
            pd = [r for r in rs if not r['free']]
            out['share' + kd] = dict(used=len(rs), free=len(rs) - len(pd), paid=len(pd),
                                     hints=sum(r['est_hints'] for r in pd),
                                     below_proved=sum(1 for r in pd if r['level'] < r['proved']))
        h = out['plain']['hints'] + sum(out['share' + k]['hints'] for k in ('5', 'c7', 'c8'))
        n = out['plain']['paid'] + sum(out['share' + k]['paid'] for k in ('5', 'c7', 'c8'))
        out['paid_certificates'] = n
        out['hints'] = h
        out['objective'] = h + OVH_CERT * n
        return out


