"""Certificate plan for a Lean-checked m <= 231 (stage B of the 231 goal): which certificates a
share-weighted k6 chain with ONE potential needs at lambda_t = P/Q, how many of each kind, and what
they cost.

The chain is the 233 chain (milestone 33) with a wider share field: the step test of the Lean k6
automaton becomes

    P + pot(next) <= Q (120 s + S(e)) + pot(current),    S(e) = max(L5(k5), L7(k7), L8(k8))

on every transition e not excluded by a plain key, where (ds = the step's 8 directions, t = its 6
counts t0..t5 of the vertices n+2..n+7)

    k5 = lkey(ds[2:8], t[1:6])            5-window, both orientations (as share6 of the 233 chain)
    k7 = (canon(ds[1:8]), t)              ctx 7, oriented (share7.py)
    k8 = (canon(ds[0:8]), t)              ctx 8, oriented, count of vertex n+1 free (1..21)

and each level is backed by a certificate: L5 by `RefutedShare (winOf ds5) (boundsOf t5) 12 (L-1)` or
a Lean floor of main, L7/L8 by the same statement on the 7/8-direction window with the share
totalizer over the TRAILING 5 centres only (share7.SubShareEncoding).  The endpoint arithmetic is
milestone 28's (*):  (P + 4200 Q) m <= 1099800 Q + 7 P + 2^B - 1,  so m <= 231 iff
225 P - 125400 Q >= 2^B  (B = potential bits, R = range of the potential <= 2^B - 1).

Method: milestone 31's engine (eng233.World: full product, 6,158,592 transitions, every known plain key,
warm Bellman-Ford with undo, dual reverse-delete, exact drops), extended here by
  * the two context sources (one share id space: 5-window keys, then ctx-7 keys, then ctx-8 keys, then
    a zero sentinel; per transition the three ids; weight uses the max of the three levels);
  * free certificates of the unconditional 233 (milestone 33): its 6,794 plain keys (1,383 of them the
    235-237 replays), the keys L1/L2-derivable from its 2,637 widened seeds, its 262 H8 cuts and its
    490 share thresholds (free up to the level 233 proved), besides main's floors 16/17;
  * the 231 arithmetic (bits B = floor(log2(225 P - 125400 Q))).
Per transition the needed level T(e) = ceil(-(Q 120 s - P + pi(u) - pi(v)) / Q) may come from any of
the three sources: the dual pass visits share ids by decreasing cost and lowers each to what the
transitions it alone covers need (taking the other two sources' CURRENT levels into account), so one
ctx record covers many transitions and the level kept per id is the max over the transitions that
still depend on it.  The exact pass then tries each item (plain key drop / share id lowering, binary
search on the level) against a warm Bellman-Ford, keeping the change iff the range stays <= 2^B - 1.

Level semantics: a record "UNSAT at T" proves share >= T, hence every level <= T.  A level kept below
the proved one is costed on the solve time of the cheapest UNSAT call at a level >= it (an upper
bound); the certificate itself is generated by a new solve at the kept level (cap = level - 1), as the
233 production did (milestone 31 step 7).  Nothing assumes that a never-tried level is UNSAT.

usage:
  nice -n 10 python3 certplan231.py scan  [--qmax 32] [--out data/certplan231_scan.json]
  nice -n 10 python3 certplan231.py plan  P/Q [--bits B] [--exact-s S] [--tag TAG]
  python3 certplan231.py calib233                      # model vs measured on the 233 certificates
  nice -n 10 python3 certplan231.py measure TAG [--n ...] [--jobs 3] [--tl S]
  python3 certplan231.py report TAG
"""
