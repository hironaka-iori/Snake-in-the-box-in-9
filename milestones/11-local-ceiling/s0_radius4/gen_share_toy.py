"""Exit test of stage 2 of the s0 route (s0_lean_design.md §5): a toy share certificate.

Writes the Lean modules of work/final_lean/LocalWindowShareToy/ (and the top module
LocalWindowShareToy.lean): a 16-clause CNF that uses every share clause family
(`emptyE`, `totUp`, `totDown`, `shareCl`, `shareCap`) next to window clauses, its
packed meaning trees and tags for `Tags.checkAllS`, and an LRAT refutation replayed by
`LratFast2` (through gen_lean_lrat.py --fast --split).

The window is the 4-cycle 0, 1, 3, 2, so the CNF is refuted by its window units and
the cut clause alone, and `RefutedShare` holds for every cap.  The point of the test is
the pipeline: the share clauses are checked by the kernel against their meanings, the
soundness theorem `soundS` composes with the LRAT replay, and the packed decoders
`mtB`, `mtB64` and `tagsOfS` are exercised.  A real share window needs the static-cap
encoder of §4.1 and new checker variants with a larger literal offset.

  python3 gen_share_toy.py --work DIR      (DIR: scratch directory for the CNF and LRAT)
"""
import argparse, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
LEAN = os.path.join(ROOT, 'work', 'final_lean')
SCRIPTS = os.path.join(ROOT, 'milestones', '10-window-aggregate', 'scripts')

WINDOW = [0, 1, 3, 2]
BOUNDS = [(0, 21), (0, 21)]
MRES, CAP = 12, 0
PRIM = [0, 1, 3, 2, 5, 4, 7, 6, 13, 12, 21, 37, 69, 133, 261]   # primaries, variables 1..15
X = {v: i + 1 for i, v in enumerate(PRIM)}
Q = 5                                                           # share neighbour 1 ^ 2^2
NBRS = [Q ^ (1 << k) for k in range(9)]

# share variables: ('sq', q, a, b), ('t', i, lo, hi, c), ('u', q, t)
SV = {16: ('sq', Q, 0, 1), 17: ('sq', Q, 0, 3),
      18: ('t', 0, 0, 2, 1), 19: ('t', 0, 0, 2, 2),
      20: ('t', 1, 0, 9, 2), 21: ('t', 1, 0, 8, 2), 22: ('t', 1, 0, 8, 1),
      23: ('u', Q, 1), 24: ('t', 2, 0, 1, 1)}
NV = 24

CLAUSES = [   # (tag, DIMACS clause)
    (('old', 'window'), [X[0]]), (('old', 'window'), [X[1]]),
    (('old', 'window'), [X[3]]), (('old', 'window'), [X[2]]),
    (('old', 'cut'), [-X[0], -X[1], -X[3], -X[2]]),
    (('emptyE',), [X[5], X[4], X[7], X[6], 16]),
    (('emptyE',), [X[5], X[4], X[13], X[12], 17]),
    (('totUp', 0), [18, -16]), (('totUp', 0), [18, -17]), (('totUp', 0), [19, -16, -17]),
    (('totDown', 1), [-20, 21, X[261]]), (('totDown', 1), [-20, 22]),
    (('shareCl', 0, 1), [23, -18, 20]), (('shareCl', 0, 1), [23, -19]),
    (('totUp', 2), [24, -23]),
    (('shareCap', 2), [-24]),
]
OLD_KIND = {'window': 0, 'cut': 6}


def code(l):
    return 2 * l if l > 0 else 2 * (-l) + 1


def leaves(nv, r, s):
    """Leaf order of `mtB`/`mtB64` (node (r, s) is a leaf when r + s > nv)."""
    if r + s <= nv:
        return leaves(nv, r, 2 * s) + leaves(nv, r + s, 2 * s)
    return [r]


def leaf48(x):
    return 1 + 4 * PRIM[x - 1] if 1 <= x <= len(PRIM) else 0


def leaf64(x):
    m = SV.get(x)
    if m is None:
        return 0
    if m[0] == 'sq':
        return 1 + 4 * (m[1] + (m[2] << 16) + (m[3] << 24))
    if m[0] == 't':
        _, i, lo, hi, c = m
        assert i < 1 << 10 and lo < 1 << 16 and hi < 1 << 16 and c < 1 << 20
        return 2 + 4 * (i + (lo << 10) + (hi << 26) + (c << 42))
    return 3 + 4 * (m[1] + (m[2] << 16))


def stream(ws, bits):
    return sum(w << (bits * k) for k, w in enumerate(ws))


def tag48(t):
    k, c, i, j = 0, 0, 0, 0
    if t[0] == 'old':
        k = OLD_KIND[t[1]]
    elif t[0] == 'emptyE':
        k = 12
    elif t[0] in ('totUp', 'totDown', 'shareCap'):
        k, c = {'totUp': 13, 'totDown': 14, 'shareCap': 16}[t[0]], t[1]
    elif t[0] == 'shareCl':
        k, i, j = 15, t[1], t[2]
    return k + (c << 5) + (i << 13) + (j << 29)


HEADER = 'set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n'
NS = 'Snake9.LocalWindow.ShareToy'


def write(path, txt):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(txt)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--work', required=True)
    a = ap.parse_args()
    os.makedirs(a.work, exist_ok=True)
    raw = [[code(l) for l in cl] for _, cl in CLAUSES]
    rawtxt = ',\n  '.join('[%s]' % ', '.join(map(str, c)) for c in raw)
    write(os.path.join(LEAN, 'LocalWindowShareToy', 'Cnf.lean'), '\n'.join([
        'import LocalWindowShareModel', '',
        '/-! Toy share CNF (generated by `milestones/11-local-ceiling/s0_radius4/gen_share_toy.py`):',
        'the window units and the cut of the 4-cycle `0, 1, 3, 2`, and one clause or more of',
        'every share family for the neighbour `5` of the centre `1`. -/', '',
        HEADER, 'namespace ' + NS, '', 'open Snake9.LocalWindow', '',
        'def window : List Nat := %s' % WINDOW,
        'def bounds : List (Nat × Nat) := [%s]' % ', '.join('(%d, %d)' % b for b in BOUNDS),
        'def resolution : Nat := %d' % MRES,
        'def cap : Nat := %d' % CAP, '',
        '/-- Literals coded by `decodeLit`. -/',
        'def raw : List (List Nat) := [\n  %s]' % rawtxt, '',
        'def cnf : List (List Int) := raw.map (·.map decodeLit)', '',
        'end ' + NS, '']))
    mstream = stream([leaf48(x) for x in leaves(NV, 0, 1)], 48)
    xstream = stream([leaf64(x) for x in leaves(NV, 0, 1)], 64)
    tstream = stream([tag48(t) for t, _ in CLAUSES], 48)
    totlits = [[code(16), code(17)], [code(X[v]) for v in NBRS], [code(23)]]
    tots = ('[⟨natsOf %d (nat_lit 0x%x), .emp %d⟩,\n   ⟨natsOf %d (nat_lit 0x%x), .nb %d⟩,\n'
            '   ⟨natsOf %d (nat_lit 0x%x), .cap [[(2, 1)], []]⟩]') % (
        len(totlits[0]), stream(totlits[0], 24), Q, len(totlits[1]), stream(totlits[1], 24), Q,
        len(totlits[2]), stream(totlits[2], 24))
    write(os.path.join(LEAN, 'LocalWindowShareToy', 'Sat.lean'), '\n'.join([
        'import LocalWindowTagsShare', 'import LocalWindowTagsPacked', 'import LocalWindowTagsSharePacked',
        'import LocalWindowShareToy.Cnf', '',
        '/-! Every clause of the toy share CNF follows from the share axioms (generated by',
        '`milestones/11-local-ceiling/s0_radius4/gen_share_toy.py`).  `meaning` (window',
        'variables, `mtB`), `smeaning` (share variables, `mtB64`) and `tags` (`tagsOfS`) are',
        'packed literals decoded in the kernel; `check` runs `checkAllS` once. -/', '',
        HEADER, 'namespace ' + NS, '', 'open Snake9.LocalWindow Snake9.LocalWindow.Tags', '',
        'noncomputable def meaning : MT := (mtB %d 64 0 1 (nat_lit 0x%x)).1' % (NV, mstream), '',
        'noncomputable def smeaning : MS := (mtB64 %d 64 0 1 (nat_lit 0x%x)).1' % (NV, xstream), '',
        'def ctrs : List Ctr := []', '',
        'noncomputable def tots : List Tot :=\n  ' + tots, '',
        'noncomputable def tags : List TagS := tagsOfS %d (nat_lit 0x%x)' % (len(CLAUSES), tstream), '',
        'theorem check : checkAllS meaning smeaning resolution ctrs tots window bounds cap tags raw = true := by',
        '  decide +kernel', '',
        'theorem sat : ∀ S E : Nat → Bool,',
        '    AxiomsS S E window (centresOf window bounds) resolution cap → ∃ τ, cnfTrue τ cnf = true :=',
        '  fun S E h => ⟨tauS S E meaning smeaning resolution ctrs tots,',
        '    soundS meaning smeaning resolution ctrs tots window bounds cap tags raw check S E h⟩', '',
        'end ' + NS, '']))
    # DIMACS, LRAT (one lemma: the empty clause from the four units and the cut), core meta
    with open(os.path.join(a.work, 'share_toy.cnf'), 'w') as f:
        f.write('p cnf %d %d\n' % (NV, len(CLAUSES)))
        for _, cl in CLAUSES:
            f.write(' '.join(map(str, cl)) + ' 0\n')
    n = len(CLAUSES)
    with open(os.path.join(a.work, 'share_toy.lrat'), 'w') as f:
        f.write('%d 0 1 2 3 4 5 0\n' % (n + 1))
    data = os.path.join(a.work, 'meta')
    os.makedirs(data, exist_ok=True)
    json.dump({'module': 'ShareToy', 'core_ids': list(range(1, n + 1))},
              open(os.path.join(data, 'share_toy.json'), 'w'))
    out = os.path.join(a.work, 'lean')
    subprocess.run([sys.executable, os.path.join(SCRIPTS, 'gen_lean_lrat.py'), '--work', a.work,
                    '--data', data, '--out', out, '--fast', '--split', '--check', 'share_toy'], check=True)
    sub = os.path.join(out, 'LocalWindowUnsat', 'ShareToy')

    def fix(txt):
        txt = txt.replace('import LocalWindowCnf.ShareToy', 'import LocalWindowShareToy.Cnf')
        txt = txt.replace('import LocalWindowUnsat.ShareToy.', 'import LocalWindowShareToy.')
        return txt.replace('Snake9.LocalWindow.ShareToy', NS)
    for fn in sorted(os.listdir(sub)):
        write(os.path.join(LEAN, 'LocalWindowShareToy', fn), fix(open(os.path.join(sub, fn)).read()))
    unsat = fix(open(os.path.join(out, 'LocalWindowUnsat', 'ShareToy.lean')).read())
    unsat = unsat.replace('/-! Kernel-checked', 'import LocalWindowShareToy.Sat\n\n/-! Kernel-checked', 1)
    unsat = unsat.replace('\nend ' + NS, '\n'.join([
        '',
        '/-- The toy share certificate: `checkAllS` (`Sat.check`) and the LRAT replay (`unsat`)',
        'give `RefutedShare` through `soundS` and `refutedShare_of_sat`. -/',
        'theorem refuted : RefutedShare window bounds resolution cap :=',
        '  Snake9.LocalWindow.Tags.refutedShare_of_sat sat unsat', '',
        'end ' + NS]))
    write(os.path.join(LEAN, 'LocalWindowShareToy.lean'), unsat)


if __name__ == '__main__':
    main()
