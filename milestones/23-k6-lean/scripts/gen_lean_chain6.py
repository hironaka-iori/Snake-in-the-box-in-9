"""Emit the Lean chain from a six-centre automaton (gen_lean_automaton6.py) to its bound.

Reads the summary `milestones/23-k6-lean/data/auto6_<T>.json` written by
`gen_lean_automaton6.py --tag T` and writes, in work/spectral/stronger/:

  DirectionWindowBridge6<T>.lean   core Lean: the kernel checks `keysOK6 dirKeys6<T>` and
                                   `Cover6 tables6<T> dirKeys6<T>` (`cover6_rows`, one
                                   declaration per nonzero exclusion row), and the five window
                                   premises `Windows6` from `AllRefuted6<T>`
  AggregateDirection6<T>.lean      mathlib side: `upper_<N>_of_refuted6<T>`,
                                   `AllRefuted6<T> → ∀ snake, m ≤ N`

The arithmetic is the generic `upper_of_refuted6` (AggregateDirection6Conditional):
(P + 35 Q) m + 6 Q ≤ 9171 Q + 7 P + (2^B - 1), i.e. C = (2^B - 1) + 7 P - 6 Q as in the
five-centre chain, which must give m ≤ N.  The unconditional module (discharging
`AllRefuted6<T>` by the LRAT replays of the keys, as `LocalWindowDirSatR4b`/`UpperBound237`
do for the five-centre set) is not generated: it needs the replay modules of the keys.

  python gen_lean_chain6.py --tag T [--check]
"""
import argparse, json, os, sys


def lst(c):
    return '[' + ', '.join(map(str, c)) + ']'

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
STRONGER = os.path.join(ROOT, 'work', 'spectral', 'stronger')
DATA = os.path.join(HERE, '..', 'data')
ME = 'milestones/23-k6-lean/scripts/gen_lean_chain6.py'


def bridge(T, s):
    rows = [(tuple(c), s0) for c, s0 in s['rows']]
    return f'''/-
Generated by {ME}.
The window premises of the six-centre automaton `tables6{T}` from the {s["keys"]}
certificate statements `AllRefuted6{T}` (core Lean; generic argument in
`DirectionWindowBridge6`).
-/
import DirectionWindowBridge6
import WindowAutomaton6{T}Data
import LocalWindowDirKeys6{T}

set_option Elab.async false

namespace Snake9.DirectionWindow6
open Snake9 Snake9.LocalWindow Snake9.WindowAutomaton

theorem keysOK6{T} : keysOK6 dirKeys6{T} = true := by decide +kernel

''' + ''.join(f'''set_option maxRecDepth 100000 in
theorem zero6{T}_{n} : allRGS {n} 0 (zeroOutside6 tables6{T} rows6{T}) = true := by decide +kernel

''' for n in range(3, 8)) + ''.join(f'''set_option maxRecDepth 100000 in
theorem row6{T}_{k} : rowOK6 tables6{T} dirKeys6{T} {lst(c)} {s0} = true := by decide +kernel

''' for k, (c, s0) in enumerate(rows)) + f'''theorem rows6{T}_ok : ∀ r ∈ rows6{T}, rowOK6 tables6{T} dirKeys6{T} r.1 r.2 = true := by
  intro r hr
  simp only [rows6{T}, List.mem_cons, List.not_mem_nil, or_false] at hr
  rcases hr with {' | '.join(['rfl'] * len(rows))}
{chr(10).join(f'  · exact row6{T}_{k}' for k in range(len(rows)))}

/-- Every set exclusion bit of a canonical shape of 3 to 7 directions is one of the keys
(the nonzero rows are listed, each is checked in a declaration of its own). -/
theorem cover6{T} : Cover6 tables6{T} dirKeys6{T} :=
  cover6_rows rows6{T} zero6{T}_3 zero6{T}_4 zero6{T}_5 zero6{T}_6 zero6{T}_7 rows6{T}_ok

theorem windows6{T} (h : AllRefuted6{T}) {{m : Nat}} (p : Snake m) :
    Windows6 tables6{T} (pathDir p) (coreAlpha p) m :=
  direction_windows_core6 h keysOK6{T} cover6{T} p

end Snake9.DirectionWindow6

#print axioms Snake9.DirectionWindow6.cover6{T}
#print axioms Snake9.DirectionWindow6.windows6{T}
'''


def aggregate(T, s):
    P, Q, B, N = s['P'], s['Q'], s['bits'], s['bound']
    lhs = f'({P} + 35 * {Q}) * m + 6 * {Q} ≤ 9171 * {Q} + 7 * {P} + {2 ** B - 1}'
    what = ('a toy instance (zero potential, lambda = 1; the keys are not certificates)' if s['toy'] else
            f'lambda = {P}/{Q}, {B}-bit potential, {s["keys"]} window keys'
            + (' (PROVISIONAL key set: solver answers)' if s['provisional'] else ''))
    return f'''import AggregateDirection6Conditional
import WindowAutomaton6{T}Sequence
import DirectionWindowBridge6{T}

/-!
# The bound {N} from the six-centre automaton `{T}`

Generated by `{ME}`: {what}.
`upper_of_refuted6` gives `{lhs}`, so `m ≤ {N}`.  The only hypothesis is `AllRefuted6{T}`.
-/

namespace Snake9
open WindowAutomaton

theorem upper_{N}_of_refuted6{T} (h : LocalWindow.AllRefuted6{T}) {{m : Nat}} (p : Snake m) :
    m ≤ {N} := by
  have := upper_of_refuted6 tables6{T} LocalWindow.dirKeys6{T} h DirectionWindow6.keysOK6{T}
    DirectionWindow6.cover6{T} stepOK6{T} p
  change {lhs} at this
  omega

end Snake9

#print axioms Snake9.upper_{N}_of_refuted6{T}
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tag', required=True)
    ap.add_argument('--summary')
    ap.add_argument('--out-stronger', default=STRONGER)
    ap.add_argument('--check', action='store_true', help='fail if a module would change')
    a = ap.parse_args()
    s = json.load(open(a.summary or os.path.join(DATA, f'auto6_{a.tag}.json')))
    T = s['tag']
    P, Q, B, N = s['P'], s['Q'], s['bits'], s['bound']
    assert (P + 35 * Q) * (N + 1) + 6 * Q > 9171 * Q + 7 * P + 2 ** B - 1, 'bound does not follow'
    files = {f'DirectionWindowBridge6{T}.lean': bridge(T, s), f'AggregateDirection6{T}.lean': aggregate(T, s)}
    changed = False
    for name, text in files.items():
        p = os.path.join(a.out_stronger, name)
        same = os.path.exists(p) and open(p).read() == text
        changed |= not same
        if not same and not a.check:
            open(p, 'w').write(text)
        print(name, 'unchanged' if same else ('DIFFERS' if a.check else 'written'))
    if a.check and changed:
        sys.exit(1)


if __name__ == '__main__':
    main()
