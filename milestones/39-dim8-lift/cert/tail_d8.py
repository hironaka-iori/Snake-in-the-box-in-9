#!/usr/bin/env python3
"""Tail worker: certificates of the TOO_BIG cubes on ordinary (16 GB) machines by recursive vertex splitting.

    tail_d8.py list --work DIR [--ref-prefix refs/heads/xfer/d8]           TOO_BIG cubes of the published manifests
    tail_d8.py run  --stack DIR --work DIR --index I[,J|-K] --workers W [--mem-gb 12] [--procs 3] [--publish]
                    [--name tI] [--only A,A,...] [--max-depth 12] [--hours H]

Items: every module with a TOO_BIG record and no OK or SAT? record in any manifest under --ref-prefix (each ref
fetched by name into WORK/idx, a private git directory), sharded as prod_d8.py (sha1(module) % W in the
indices), smallest known pred_gb first. --only A,... takes the listed cubes instead (tests).
Per cube (Unsat (cubeCnfQ 13 L A k) by Dim8Lift.Split.unsat_of_leaves, as make_split.py):
  1. leaves       start from the two depth-1 paths. A leaf path p is generated by make_cert.py (UNITS=p,
                  LEAF=<bits of p>, SOLVE_LIMIT as prod_d8.py). If the solve hits the cap, or the predicted
                  peak pred_gb(hints, vars) of its compacted proof exceeds --mem-gb, the leaf is not built: it is
                  replaced by its two children p+[v], p-[v] (v = the next vertex of split.py's order, so every
                  node of one depth branches on the same variable). Otherwise build_cert.sh builds it.
                  At most --procs leaves at once under prod_d8.py's memory reservation.
  2. top          the tree of the built leaves (complete by construction), the top module CubeQ<A>.lean,
                  then prod_d8.check_public on its public .olean (statement `Unsat (cubeCnfQ 13 L A k)`,
                  standard axioms only).
  3. record       an OK line in WORK/manifest.jsonl (prod_d8.py's format plus route=tail, leaves, depth),
                  the public .olean in WORK/olean; --publish pushes both to <ref-prefix>/<name> (default
                  t<first index>) with prod_d8.publish, so assemble_d8.py collects them like any worker's.
A SAT leaf records SAT? (with its path) and stops the worker. Resumable: WORK/jobs/<module>/state.json holds
the leaf frontier; built leaves and generated-but-unbuilt leaves are reused. A cube whose leaves reach
--max-depth without fitting is recorded FAILED (retried by the next run).
Disk: a built leaf keeps its build directory (~0.5 GB) until the cube's top module is checked.
"""
import argparse, hashlib, json, os, shutil, socket, subprocess, sys, threading, time
from concurrent.futures import ThreadPoolExecutor, FIRST_COMPLETED, wait
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import prod_d8 as P
LEAN = P.LEAN


def vertex_order(A, n=8, k=6):   # scripts/split.py's branching order (DIMACS variable = vertex + 1)
    V, K = 1 << n, 1 << k
    adeg = lambda x: sum(1 for i in range(k) if x ^ (1 << i) in A)
    ends = [u for u in range(K, V) if any((u ^ (1 << i)) in A and adeg(u ^ (1 << i)) <= 1 for i in range(k, n))]
    near = [u for u in range(K, V) if u not in ends and any((u ^ (1 << i)) < K for i in range(k, n))]
    rest = [u for u in range(K, V) if u not in ends and u not in near]
    return [u + 1 for u in ends + near + rest]


def published(a):
    """module -> its records in every manifest under --ref-prefix"""
    g = os.path.join(a.work, 'idx')
    if not os.path.exists(os.path.join(g, '.git')):
        os.makedirs(g, exist_ok=True); P.sh(['git', 'init', '-q'], cwd=g)
        P.sh(['git', 'remote', 'add', 'origin', P.sh(['git', 'remote', 'get-url', 'origin'], cwd=P.ROOT).stdout.strip()], cwd=g)
    r = P.sh(['git', 'ls-remote', 'origin', a.ref_prefix + '/*'], cwd=g); assert r.returncode == 0, r.stderr
    refs = [l.split()[1] for l in r.stdout.split('\n') if l.strip()]
    for i in range(0, len(refs), 50):   # by name, into private refs of WORK/idx
        r = P.sh(['git', 'fetch', '-q', 'origin'] + ['+%s:refs/d8/%s' % (x, x.rsplit('/', 1)[1]) for x in refs[i:i + 50]], cwd=g)
        assert r.returncode == 0, r.stderr
    recs = {}
    for x in refs:
        m = P.sh(['git', 'show', 'refs/d8/%s:manifest.jsonl' % x.rsplit('/', 1)[1]], cwd=g).stdout
        for l in m.split('\n'):
            if l.strip():
                rec = json.loads(l); rec['ref'] = x; recs.setdefault(rec['module'], []).append(rec)
    return recs


def tail_items(a):
    recs = published(a); out = []
    for m, rs in recs.items():
        st = {r['status'] for r in rs}
        if 'TOO_BIG' in st and not st & {'OK', 'SAT?'}:
            pg = min([r['pred_gb'] for r in rs if r.get('pred_gb')] or [1e9])
            out.append((pg, rs[0]['k'], rs[0]['A']))
    return sorted(out)


def cmd_list(a):
    a.work = os.path.abspath(a.work); os.makedirs(a.work, exist_ok=True)
    its = tail_items(a)
    for pg, k, h in its: print(k, h, pg if pg < 1e9 else '?')
    print('%d TOO_BIG cubes without a certificate' % len(its), file=sys.stderr)


def key(p): return ','.join(map(str, p))
def bits(p): return 'x' + ''.join('1' if x > 0 else '0' for x in p)


def leaf_job(a, h, k, cd, p, held):
    """generate (and if it fits, build) leaf p; returns (status, info). held: this thread's reservation (GB)"""
    m = 'Q' + h.upper() + 'L' + bits(p); d = os.path.join(cd, 'leaves', m); gj = os.path.join(d, 'gen.json')
    olean = os.path.join(d, 'build', 'Cube' + m + '.olean')
    if os.path.exists(olean) and os.path.exists(gj): return 'done', json.load(open(gj))
    P.reserve(held[0], P.GEN_GB); held[0] = P.GEN_GB
    if not (os.path.exists(gj) and os.path.exists(os.path.join(d, 'gen', m + '.modules'))):
        shutil.rmtree(d, ignore_errors=True); os.makedirs(d)
        lim = max(300.0, (a.mem_gb - 3.1) / 0.55 * 1e6 / 28000)
        env = {x: y for x, y in os.environ.items() if x != 'MEM_GB'}   # no portfolio: a big leaf is split instead
        r = P.sh([sys.executable, os.path.join(HERE, 'make_cert.py'), str(a.L), h, str(k), d], cwd=HERE,
                 env=dict(env, UNITS=','.join(map(str, p)), LEAF=bits(p), SOLVE_LIMIT=str(round(lim))))
        if r.returncode == 10: return 'SAT', {}
        if r.returncode == 11: shutil.rmtree(d, ignore_errors=True); return 'split', {'solve_limit': round(lim)}
        if r.returncode != 0: return 'failed', {'log': (r.stdout + r.stderr)[-1500:]}
        g = json.loads(r.stdout.strip().splitlines()[-1])
        info = dict(hints=g['replay']['hints'], vars=g['core']['vars'], solve_s=g['solve_s'], gen_s=g['gen_s'])
        info['pred_gb'] = round(P.pred_gb(info['hints'], info['vars']), 1)
        if info['pred_gb'] > a.mem_gb: shutil.rmtree(d, ignore_errors=True); return 'split', info
        json.dump(info, open(gj, 'w'))
    info = json.load(open(gj))
    P.reserve(held[0], info['pred_gb']); held[0] = info['pred_gb']
    t = time.time()
    r = P.sh(['bash', os.path.join(HERE, 'build_cert.sh'), d, m], env=dict(os.environ, STACK=os.path.join(a.stack, 'build'), JOBS='1'))
    rss = [int(x.split()[0]) for x in r.stdout.split(' s ')[1:] if x.split()[0].isdigit()]
    info.update(build_s=round(time.time() - t, 1), peak_mb=max(rss) if rss else None)
    if 'CERT BUILT' not in r.stdout or not os.path.exists(olean): return 'failed', {'log': r.stdout[-1500:]}
    shutil.rmtree(os.path.join(d, 'gen'), ignore_errors=True); shutil.rmtree(os.path.join(d, 'work'), ignore_errors=True)
    json.dump(info, open(gj, 'w'))
    return 'done', info


def run_leaf(a, h, k, cd, p):
    held = [0.0]
    try:
        return leaf_job(a, h, k, cd, p, held)
    except Exception as e:   # noqa: a crashed leaf fails the cube, not the worker
        return 'failed', {'log': repr(e)[-1500:]}
    finally:
        with P.BLOCK:
            P.BUDGET['used'] -= held[0]; P.BLOCK.notify_all()


def tree_of(leaves):   # make_split.py's tree builder (positive branch first, as ST.leaves)
    def build(prefix, paths):
        if paths == [prefix]: return 'ST.leaf', [prefix]
        nxt = {q[len(prefix)] for q in paths}
        v = abs(next(iter(nxt))); assert nxt == {v, -v} and v > 0, (prefix, nxt)
        tp, lp = build(prefix + (v,), [q for q in paths if q[len(prefix)] == v])
        tn, ln = build(prefix + (-v,), [q for q in paths if q[len(prefix)] == -v])
        return 'ST.node %d (%s) (%s)' % (v, tp, tn), lp + ln
    return build((), sorted(leaves))


def tail_cube(a, k, h, stop):
    mod = 'Q' + h.upper(); cd = os.path.join(a.work, 'jobs', 'Cube' + mod); os.makedirs(cd, exist_ok=True)
    t0 = time.time(); rec = dict(module='Cube' + mod, A=h, k=k, L=a.L, host=socket.gethostname(), commit=a.commit,
                                 route='tail', mem_gb=a.mem_gb)
    sf = os.path.join(cd, 'state.json'); order = vertex_order(set(u for u in range(64) if int(h, 16) >> u & 1))
    st = json.load(open(sf)) if os.path.exists(sf) else {key([order[0]]): 'todo', key([-order[0]]): 'todo'}
    infos = {}
    save = lambda: json.dump(st, open(sf + '.tmp', 'w')) or os.replace(sf + '.tmp', sf)
    save()
    with ThreadPoolExecutor(a.procs) as ex:
        fut = {}
        while True:
            for s_, v_ in list(st.items()):
                if v_ == 'todo' and s_ not in fut.values() and not stop():
                    fut[ex.submit(run_leaf, a, h, k, cd, [int(x) for x in s_.split(',')])] = s_
            if not fut: break
            dn, _ = wait(list(fut), return_when=FIRST_COMPLETED)
            for f in dn:
                s_ = fut.pop(f); p = [int(x) for x in s_.split(',')]; res, info = f.result()
                if res == 'done': st[s_] = 'done'; infos[s_] = info
                elif res == 'split':
                    if len(p) >= a.max_depth:
                        st[s_] = 'failed'; rec.update(status='FAILED', log='leaf %s still too big at depth %d' % (s_, len(p)))
                    else:
                        v = order[len(p)]; st[s_] = 'split'; st[key(p + [v])] = 'todo'; st[key(p + [-v])] = 'todo'
                elif res == 'SAT':
                    st[s_] = 'SAT'; rec.update(status='SAT?', leaf=p)
                else:
                    st[s_] = 'todo'; rec.update(status='FAILED', leaf=p, log=info.get('log'))
                save()
            if rec.get('status'):   # stop scheduling; let running leaves finish
                for f in list(fut): f.result()
                break
    if rec.get('status'):
        if rec['status'] == 'FAILED':   # the failed leaf is retried on the next run
            for s_, v_ in st.items():
                if v_ == 'failed': st[s_] = 'todo'
            save()
        return rec
    if stop() or any(v_ == 'todo' for v_ in st.values()): return None   # stopped: resume next run
    leaves = [tuple(int(x) for x in s_.split(',')) for s_, v_ in st.items() if v_ == 'done']
    for s_ in st:
        if st[s_] == 'done' and s_ not in infos:
            infos[s_] = json.load(open(os.path.join(cd, 'leaves', mod + 'L' + bits([int(x) for x in s_.split(',')]), 'gen.json')))
    tree, order_ = tree_of(leaves)
    names = [mod + 'L' + bits(p) for p in order_]
    top = os.path.join(cd, 'top'); os.makedirs(top, exist_ok=True)
    ls = '[%s]' % ', '.join('[%s]' % ', '.join('(%d : Int)' % x for x in p) for p in order_)
    cert = '⟨%s, trivial⟩' % ', '.join('Snake9.CubeProv.%s.unsat' % n for n in names)
    src = ('module\n\npublic import CubeCnf\nimport Split\n%s\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n'
           'namespace Snake9.CubeProv.%s\nopen Dim8Lift.Split\n'
           'def T : ST := %s\n'
           '/-- the split certificate: %d leaves of the vertex-literal split tree -/\n'
           'public theorem unsat : Snake9.LocalWindow.Unsat (Dim8Lift.Cube.cubeCnfQ 13 %d 0x%s %d) :=\n'
           '  unsat_of_leaves _ T (by decide) %s (by decide)\n    %s\nend Snake9.CubeProv.%s\n'
           '#print axioms Snake9.CubeProv.%s.unsat\n'
           % (''.join('import Cube%s\n' % n for n in names), mod, tree, len(names), a.L, h, k, ls, cert, mod, mod))
    open(os.path.join(top, 'Cube' + mod + '.lean'), 'w').write(src)
    lp = ':'.join([os.path.join(cd, 'leaves', n, 'build') for n in names] + [os.path.join(a.stack, 'build')])
    r = P.sh([LEAN, '--root=.', '-o', os.path.join(top, 'Cube' + mod + '.olean'), 'Cube' + mod + '.lean'], cwd=top,
             env=dict(os.environ, LEAN_PATH=lp))
    olean = os.path.join(top, 'Cube' + mod + '.olean')
    lv = [infos[key(p)] for p in order_]
    rec.update(leaves=len(names), depth=max(len(p) for p in order_), hints=sum(x['hints'] for x in lv),
               peak_mb=max([x.get('peak_mb') or 0 for x in lv]), max_leaf_hints=max(x['hints'] for x in lv),
               splits=sum(1 for v_ in st.values() if v_ == 'split'))
    if r.returncode != 0 or not os.path.exists(olean):
        rec.update(status='BUILD_FAILED', log=(r.stdout + r.stderr)[-1500:]); return rec
    ok, out = P.check_public(a.stack, olean, 'Cube' + mod, cd)
    if not ok:
        rec.update(status='CHECK_FAILED', log=out[-1500:]); return rec
    dst = os.path.join(a.work, 'olean', 'Cube' + mod + '.olean'); os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(olean, dst)
    rec.update(status='OK', sha256=hashlib.sha256(open(dst, 'rb').read()).hexdigest(), total_s=round(time.time() - t0, 1))
    shutil.rmtree(cd, ignore_errors=True)
    return rec


def ensure_stack(a):
    """the stack must have the split-route Split.lean (unsat_of_leaves, ea5ecf379); stacks built earlier do not"""
    sp = os.path.join(a.stack, 'Split.lean')
    if os.path.exists(sp) and 'unsat_of_leaves' not in open(sp).read():
        for f in os.listdir(os.path.join(a.stack, 'build')):
            if f.split('.')[0] == 'Split': os.remove(os.path.join(a.stack, 'build', f))
    if not os.path.exists(os.path.join(a.stack, 'build', 'Split.olean')) or not os.path.exists(os.path.join(a.stack, 'build', 'Final.olean')):
        r = P.sh([sys.executable, os.path.join(HERE, 'prod_d8.py'), 'setup', '--stack', a.stack]); assert r.returncode == 0, r.stdout[-2000:] + r.stderr[-2000:]
    assert 'unsat_of_leaves' in open(sp).read()


def cmd_run(a):
    a.work = os.path.abspath(a.work); a.stack = os.path.abspath(a.stack); os.makedirs(a.work, exist_ok=True)
    a.indices = set()
    for part in a.index.split(','):
        lo, _, hi = part.partition('-'); a.indices.update(range(int(lo), int(hi or lo) + 1))
    assert a.indices and max(a.indices) < a.workers, 'indices must be < --workers'
    a.name = a.name or 't%d' % min(a.indices)
    a.commit = P.sh(['git', 'rev-parse', 'HEAD'], cwd=P.ROOT).stdout.strip()
    ensure_stack(a)
    man = os.path.join(a.work, 'manifest.jsonl')
    done = {r['module'] for r in map(json.loads, open(man)) if r['status'] in ('OK', 'SAT?')} if os.path.exists(man) else set()
    if a.only:
        ks = {h: k for k, h in P.items(a.L)}; its = [(0, ks[h], h) for h in a.only.split(',')]
    else:
        its = [x for x in tail_items(a) if int(hashlib.sha1(P.modname(x[2]).encode()).hexdigest(), 16) % a.workers in a.indices]
    its = [x for x in its if P.modname(x[2]) not in done]
    print('tail worker %s (indices %s of %d): %d cubes to do, %d done' % (a.name, a.index, a.workers, len(its), len(done)), flush=True)
    P.BUDGET['cap'] = a.mem_gb; end = time.time() + a.hours * 3600
    stop = lambda: os.path.exists(os.path.join(a.work, 'STOP')) or time.time() > end
    for pg, k, h in its:
        if stop(): break
        print('cube', h, 'k', k, 'pred_gb', pg if pg < 1e9 else '?', time.ctime(), flush=True)
        rec = tail_cube(a, k, h, stop)
        if rec is None: break
        open(man, 'a').write(json.dumps(rec) + '\n'); print(json.dumps(rec), flush=True)
        if a.publish: P.publish(a)
        if rec['status'] == 'SAT?':
            open(os.path.join(a.work, 'STOP'), 'w').write('SAT? ' + rec['module']); break
    print('tail worker finished', flush=True)


