"""Emit the Lean chain of a share-weighted six-centre automaton with context shares
(gen_lean_automaton6sc.py) to its bound.  Copy-and-extend of
milestones/33-233-lean/scripts/gen_lean_chain6s.py (not modified).

Reads the summary `milestones/35-231-lean/data/auto6sc_<T>.json` and writes (core Lean unless noted):

  DirectionWindowBridge6SC<T>R<g>.lean   k6 part g: keysOK6 of its key chunks and `rowOK6` of the
                                         exclusion rows whose chunk is in the part (one declaration each)
  DirectionWindowBridge6SC<T>S.lean      H8 (keysOKH8, CoverH8) and the 5-window ShareCover
                                         (`shareCover_chunks`, DirectionWindowBridge6SCChunks: one declaration
                                         per share shape and first count, against that row's key chunk)
  DirectionWindowBridge6SC<T>C.lean      the two CtxCover (ctx 7 on 7 directions, ctx 8 on 8):
                                         one `allRGS` zero check each, one declaration per shape and first
                                         count against that row's key chunk, `ctxCover_chunks`
  DirectionWindowBridge6SC<T>.lean       keysOK6, Cover6 (cover6_chunks), `windows6SC<T>`
  AggregateDirection6SC<T>.lean          mathlib: `upper_<N>_of_refuted6SC<T>` :
      AllRefuted6S<T> → AllRefutedShare6S<T> → AllRefutedCtx6SC<T> → Floors233 → ∀ snake, m ≤ N
  Audit6SC<T>.lean                       `#check` of that theorem and `#print axioms` of it and of the
                                         kernel checks (build it without -o, or with build231.py)

The arithmetic is `upper_of_refuted6SC` (AggregateDirection6SCConditional):
(P + 4200 Q) m ≤ 1099800 Q + 7 P + (2^B - 1).

  python gen_lean_chain6sc.py --tag T --out-stronger DIR [--summary FILE] [--rows-per-part 40] [--ctx-shapes-per-part 0] [--check]
"""
import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
DATA = os.path.join(HERE, '..', 'data')
ME = 'milestones/35-231-lean/scripts/gen_lean_chain6sc.py'
OPEN = 'open Snake9 Snake9.LocalWindow Snake9.WindowAutomaton Snake9.DirectionWindow6 Snake9.DirectionWindow7 Snake9.DirectionWindow6S'


def lst(c):
    return '[' + ', '.join(map(str, c)) + ']'


def head(T, what, imports):
    return f'''/-
Generated by {ME}.
{what}
-/
''' + ''.join(f'import {m}\n' for m in imports) + f'''
set_option Elab.async false
set_option maxHeartbeats 0

namespace Snake9.DirectionWindow6SC
{OPEN}

'''


BASE = lambda T: ['DirectionWindowBridge6SC', f'WindowAutomaton6SC{T}Data', f'LocalWindowDirKeys6SC{T}']   # noqa: E731


def k6_parts(T, s, rpp):
    """Parts of whole key chunks, about `rpp` exclusion rows each."""
    rows = s['rows']
    nch = s['k_chunks']
    byc = {}
    for k, (c, s0, ci) in enumerate(rows):
        byc.setdefault(ci, []).append(k)
    parts, cur, n = [], [], 0
    for ci in range(nch):
        if cur and n + len(byc.get(ci, [])) > rpp:
            parts.append(cur); cur, n = [], 0
        cur.append(ci); n += len(byc.get(ci, []))
    if cur:
        parts.append(cur)
    mods = {}
    for g, cis in enumerate(parts):
        body = ''.join(f'''theorem keysOK6S{T}_{ci} : keysOK6 (dirChunks6S{T}.getD {ci} []) = true := by decide +kernel

''' for ci in cis) + ''.join(f'''set_option maxRecDepth 100000 in
theorem row6S{T}_{k} : rowOK6 tables6SC{T}.s.k6 (dirChunks6S{T}.getD {rows[k][2]} []) {lst(rows[k][0])} {rows[k][1]} = true := by
  decide +kernel

''' for ci in cis for k in byc.get(ci, []))
        mods[f'DirectionWindowBridge6SC{T}R{g}'] = head(
            T, f'k6 cover part {g} of `tables6SC{T}`: key chunks {cis[0]} .. {cis[-1]} and their exclusion rows.',
            BASE(T)) + body + 'end Snake9.DirectionWindow6SC\n'
    return mods


def rows_t0(T, name, k, c, stmt_of, idx):
    """Six row declarations (one per first count) and the shape lemma `∀ t0, ∃ i, ...`."""
    out = ''.join(f'''set_option maxRecDepth 100000 in
theorem {name}_{k}_{t0} : {stmt_of(idx[t0 - 1], t0)} = true := by
  decide +kernel

''' for t0 in range(1, 7))
    return out + f'''theorem {name}_{k} : ∀ t0, 1 ≤ t0 → t0 ≤ 6 → ∃ i, {stmt_of('i', 't0')} = true := by
  intro t0 h1 h6
  have : t0 = 1 ∨ t0 = 2 ∨ t0 = 3 ∨ t0 = 4 ∨ t0 = 5 ∨ t0 = 6 := by omega
  rcases this with rfl | rfl | rfl | rfl | rfl | rfl
''' + ''.join(f'  · exact ⟨{idx[t0 - 1]}, {name}_{k}_{t0}⟩\n' for t0 in range(1, 7)) + '\n'


def share_mod(T, s):
    shapes = s['share_shapes']
    stmt = lambda c: (lambda i, t0: f'shareRowOK tables6SC{T}.s (shareChunks6S{T}.getD {i} []) {lst(c)} {t0}')  # noqa: E731
    gen = lambda c: f'(fun c : List Nat => ∀ t0, 1 ≤ t0 → t0 ≤ 6 → ∃ i, shareRowOK tables6SC{T}.s (shareChunks6S{T}.getD i []) c t0 = true)'  # noqa: E731
    return head(T, f'H8 cover and 5-window share cover of `tables6SC{T}`.', BASE(T) + ['DirectionWindowBridge6SCChunks']) + f'''theorem keysOKH8_6S{T} : keysOKH8 h8Keys6S{T} = true := by decide +kernel

set_option maxRecDepth 100000 in
theorem coverH8_6S{T} : CoverH8 tables6SC{T}.s h8Keys6S{T} := coverH8_of (by decide +kernel)

set_option maxRecDepth 100000 in
theorem zeroS6S{T} : allRGS 6 0 (zeroOutsideS tables6SC{T}.s sshapes6SC{T}) = true := by decide +kernel

''' + ''.join(rows_t0(T, f'srow6S{T}', k, c, stmt(c), s['share_chunk_index'][k]) for k, c in enumerate(shapes)) + f'''set_option maxRecDepth 100000 in
theorem srows6S{T}_lit : AllP {gen(None)}
    [{', '.join(lst(c) for c in shapes)}] :=
  {f"⟨{', '.join(f'srow6S{T}_{k}' for k in range(len(shapes)))}, trivial⟩" if shapes else 'trivial'}

/-- Every 5-window share field is backed by a share key (its row's chunk) or a floor theorem. -/
theorem shareCover6S{T} : ShareCover tables6SC{T}.s shareKeys6S{T} :=
  shareCover_chunks sshapes6SC{T} zeroS6S{T} (by
    unfold sshapes6SC{T}
    exact AllP.mem srows6S{T}_lit)

end Snake9.DirectionWindow6SC
'''


def ctx_mod(T, s, shapes_per_part=0):
    """The ctx covers.  With `shapes_per_part` > 0 the row declarations go to part modules
    `DirectionWindowBridge6SC<T>C<n>_<g>` (that many shapes each; they build in parallel) and the
    module `…C` keeps the zero checks and the two covers; with 0, everything is in `…C`."""
    parts = {}
    out = None
    imps = []
    body = ''
    for n in (7, 8):
        shapes = s[f'ctx{n}_shapes']
        rf = f'rowf{n} tables6SC{T}'
        stmt = lambda c: (lambda i, t0: f'ctxRowOK tables6SC{T}.cbits ({rf} {lst(c)}) (ctx{n}Chunks6SC{T}.getD {i} []) {lst(c)} {t0}')  # noqa: E731
        rows = [rows_t0(T, f'ctxRow{n}_6SC{T}', k, c, stmt(c), s[f'ctx{n}_chunk_index'][k]) for k, c in enumerate(shapes)]
        if shapes_per_part > 0:
            for g in range(0, len(rows), shapes_per_part):
                m = f'DirectionWindowBridge6SC{T}C{n}_{g // shapes_per_part}'
                parts[m] = head(T, f'ctx {n} row declarations {g} .. {min(len(rows), g + shapes_per_part) - 1} of `tables6SC{T}`.',
                                BASE(T)) + ''.join(rows[g:g + shapes_per_part]) + 'end Snake9.DirectionWindow6SC\n'
                imps.append(m)
            rows = []
        body += f'''set_option maxRecDepth 100000 in
theorem ctxZero{n}_6SC{T} : allRGS {n} 0 (zeroOutsideC ({rf}) ctx{n}Shapes6SC{T}) = true := by decide +kernel

''' + ''.join(rows) + f'''set_option maxRecDepth 100000 in
theorem ctxRows{n}_6SC{T}_lit : AllP (fun c : List Nat => ∀ t0, 1 ≤ t0 → t0 ≤ 6 → ∃ i, ctxRowOK tables6SC{T}.cbits ({rf} c) (ctx{n}Chunks6SC{T}.getD i []) c t0 = true)
    [{', '.join(lst(c) for c in shapes)}] :=
  {f"⟨{', '.join(f'ctxRow{n}_6SC{T}_{k}' for k in range(len(shapes)))}, trivial⟩" if shapes else 'trivial'}

theorem ctxCover{n}_6SC{T} : CtxCover {n} tables6SC{T}.cbits ({rf}) ctx{n}Keys6SC{T} :=
  ctxCover_chunks ctx{n}Shapes6SC{T} ctxZero{n}_6SC{T} (by
    unfold ctx{n}Shapes6SC{T}
    exact AllP.mem ctxRows{n}_6SC{T}_lit)

'''
    out = head(T, f'The ctx 7 and ctx 8 covers of `tables6SC{T}`.', BASE(T) + ['DirectionWindowBridge6SCChunks'] + imps) + body
    parts[f'DirectionWindowBridge6SC{T}C'] = out + 'end Snake9.DirectionWindow6SC\n'
    return parts


def bridge(T, s, nparts):
    rows = s['rows']
    nch = s['k_chunks']
    imports = BASE(T) + [f'DirectionWindowBridge6SC{T}R{g}' for g in range(nparts)] + \
        [f'DirectionWindowBridge6SC{T}S', f'DirectionWindowBridge6SC{T}C']
    return head(T, f'The window premises of `tables6SC{T}` from its certificate statements (core Lean; generic '
                   f'argument in `DirectionWindowBridge6S`/`DirectionWindowBridge6SC`).', imports) + f'''theorem keysOK6S{T} : keysOK6 dirKeys6S{T} = true :=
  keysOK6_flatten (fun i hi => by
    have : i < {nch} := by simpa [dirChunks6S{T}] using hi
    exact AllP.mem (P := fun i => keysOK6 (dirChunks6S{T}.getD i []) = true) (l := List.range {nch})
      ⟨{', '.join(f'keysOK6S{T}_{ci}' for ci in range(nch))}, trivial⟩ i (List.mem_range.2 this))

''' + ''.join(f'''set_option maxRecDepth 100000 in
theorem zero6S{T}_{n} : allRGS {n} 0 (zeroOutside6 tables6SC{T}.s.k6 rows6SC{T}) = true := by decide +kernel

''' for n in range(3, 8)) + f'''set_option maxRecDepth 100000 in
theorem rows6S{T}_lit : AllP (fun r : List Nat × Nat => ∃ i, rowOK6 tables6SC{T}.s.k6 (dirChunks6S{T}.getD i []) r.1 r.2 = true)
    [{', '.join(f'({lst(c)}, {s0})' for c, s0, ci in rows)}] :=
  ⟨{', '.join(f'⟨{ci}, row6S{T}_{k}⟩' for k, (c, s0, ci) in enumerate(rows))}, trivial⟩

theorem rows6S{T}_ok : ∀ r ∈ rows6SC{T}, ∃ i, rowOK6 tables6SC{T}.s.k6 (dirChunks6S{T}.getD i []) r.1 r.2 = true := by
  unfold rows6SC{T}
  exact AllP.mem rows6S{T}_lit

/-- Every set exclusion bit of a canonical shape of 3 to 7 directions is one of the plain keys. -/
theorem cover6S{T}k6 : Cover6 tables6SC{T}.s.k6 dirKeys6S{T} :=
  cover6_chunks dirChunks6S{T} rows6SC{T} zero6S{T}_3 zero6S{T}_4 zero6S{T}_5 zero6S{T}_6 zero6S{T}_7
    rows6S{T}_ok

theorem windows6SC{T} (h : AllRefuted6S{T}) {{m : Nat}} (p : Snake m) :
    Windows6S tables6SC{T}.s (pathDir p) (coreAlpha p) m :=
  direction_windows_core6S h.1 keysOK6S{T} cover6S{T}k6 h.2 keysOKH8_6S{T} coverH8_6S{T} p

end Snake9.DirectionWindow6SC

#print axioms Snake9.DirectionWindow6SC.cover6S{T}k6
#print axioms Snake9.DirectionWindow6SC.coverH8_6S{T}
#print axioms Snake9.DirectionWindow6SC.shareCover6S{T}
#print axioms Snake9.DirectionWindow6SC.ctxCover7_6SC{T}
#print axioms Snake9.DirectionWindow6SC.ctxCover8_6SC{T}
#print axioms Snake9.DirectionWindow6SC.windows6SC{T}
'''


def aggregate(T, s):
    P, Q, B, N = s['P'], s['Q'], s['bits'], s['bound']
    lhs = f'({P} + 4200 * {Q}) * m ≤ 1099800 * {Q} + 7 * {P} + (2 ^ {B} - 1)'
    what = (f'lambda = {P}/{Q}, {B}-bit potential (range {s["potential_range"]}), {s["plain_keys"]} plain keys, '
            f'{s["h8_keys"]} H8 keys, {s["share_keys"]} 5-window share keys, {s["share_on_floors"]} share fields on '
            f'main\'s floors, {s["ctx7_keys"]} ctx 7 and {s["ctx8_keys"]} ctx 8 keys; plan `{s["plan"]}`')
    D = 'DirectionWindow6SC'
    return f'''import AggregateDirection6SCConditional
import WindowAutomaton6SC{T}Sequence
import DirectionWindowBridge6SC{T}

/-!
# The bound {N} from the share-weighted six-centre automaton with context shares `{T}`

Generated by `{ME}`: {what}.
`upper_of_refuted6SC` gives `{lhs}`, so `m ≤ {N}`.  The hypotheses are the certificate statements
`AllRefuted6S{T}` (plain and H8 keys), `AllRefutedShare6S{T}` (5-window share thresholds),
`AllRefutedCtx6SC{T}` (ctx 7 and ctx 8 thresholds) and the floor theorems of origin/main (`Floors233`).
-/

namespace Snake9
open WindowAutomaton

theorem upper_{N}_of_refuted6SC{T} (h : LocalWindow.AllRefuted6S{T})
    (hs : LocalWindow.AllRefutedShare6S{T}) (hc : LocalWindow.AllRefutedCtx6SC{T})
    (hF : DirectionWindow6S.Floors233) {{m : Nat}} (p : Snake m) : m ≤ {N} := by
  have := upper_of_refuted6SC tables6SC{T} LocalWindow.dirKeys6S{T} LocalWindow.h8Keys6S{T}
    LocalWindow.shareKeys6S{T} LocalWindow.ctx7Keys6SC{T} LocalWindow.ctx8Keys6SC{T} h.1 h.2 hs hc.1 hc.2 hF
    {D}.keysOK6S{T} {D}.cover6S{T}k6 {D}.keysOKH8_6S{T} {D}.coverH8_6S{T}
    {D}.shareCover6S{T} {D}.ctxCover7_6SC{T} {D}.ctxCover8_6SC{T} stepOK6SC{T} p
  change {lhs} at this
  omega

end Snake9

#print axioms Snake9.upper_{N}_of_refuted6SC{T}
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tag', required=True)
    ap.add_argument('--summary')
    ap.add_argument('--out-stronger', required=True)
    ap.add_argument('--rows-per-part', type=int, default=40)
    ap.add_argument('--ctx-shapes-per-part', type=int, default=0,
                    help='split the ctx row declarations into part modules of this many shapes (0: one module)')
    ap.add_argument('--check', action='store_true', help='fail if a module would change')
    a = ap.parse_args()
    s = json.load(open(a.summary or os.path.join(DATA, f'auto6sc_{a.tag}.json')))
    T = s['tag']
    P, Q, B, N = s['P'], s['Q'], s['bits'], s['bound']
    R = 2 ** B - 1
    assert (P + 4200 * Q) * N <= 1099800 * Q + 7 * P + R < (P + 4200 * Q) * (N + 1), 'bound does not follow'
    parts = k6_parts(T, s, a.rows_per_part)
    files = {f'{m}.lean': t for m, t in parts.items()}
    files[f'DirectionWindowBridge6SC{T}S.lean'] = share_mod(T, s)
    for m, t in ctx_mod(T, s, a.ctx_shapes_per_part).items():
        files[f'{m}.lean'] = t
    files[f'DirectionWindowBridge6SC{T}.lean'] = bridge(T, s, len(parts))
    files[f'AggregateDirection6SC{T}.lean'] = aggregate(T, s)
    D = 'Snake9.DirectionWindow6SC'
    files[f'Audit6SC{T}.lean'] = f'''import AggregateDirection6SC{T}

/-! Axiom audit of the conditional chain `{T}` (generated by `{ME}`). -/

#check @Snake9.upper_{N}_of_refuted6SC{T}
''' + ''.join(f'#print axioms {x}\n' for x in [
        f'Snake9.upper_{N}_of_refuted6SC{T}', f'Snake9.WindowAutomaton.stepOK6SC{T}', f'{D}.windows6SC{T}',
        f'{D}.cover6S{T}k6', f'{D}.coverH8_6S{T}', f'{D}.shareCover6S{T}', f'{D}.ctxCover7_6SC{T}',
        f'{D}.ctxCover8_6SC{T}', 'Snake9.upper_of_refuted6SC', f'{D}.shareCover_chunks', f'{D}.ctxCover_chunks'])
    changed = False
    for name, text in files.items():
        p = os.path.join(a.out_stronger, name)
        same = os.path.exists(p) and open(p).read() == text
        changed |= not same
        if not same and not a.check:
            open(p, 'w').write(text)
        print(name, 'unchanged' if same else ('DIFFERS' if a.check else 'written'))
    if a.check and changed:
        sys.exit(1)


if __name__ == '__main__':
    main()
