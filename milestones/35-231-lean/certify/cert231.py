def keys(a):
    d = json.load(gzip.open(a.plan, 'rt'))
    c = collections.Counter()
    for r in d['plain']:
        c[('plain', 'free' if r['free'] else 'paid', r['basis'].split('_')[0])] += 1
    for r in d['share']:
        c[(r['kind'], 'free' if r['free'] else 'paid', r['basis'])] += 1
    it = items(a)
    out = {'counts': {' '.join(k): v for k, v in sorted(c.items())},
           'paid_by_kind': dict(collections.Counter(x[0] for x in it)),
           'paid_plan_est_hints': {kd: sum(x[3] for x in it if x[0] == kd) for kd in ('ctx', 'share', 'plain')},
           'share_already_in_233': sum(1 for x in it if x[0] == 'share' and built(a, 'LocalWindowUnsat', x[2]))}
    print(json.dumps(out, indent=1))


def status(a):
    it = items(a)
    r = collections.Counter()
    for kind, k, name, est in it:
        r[f'{kind}_keys'] += 1
        if load_meta(a, name) is not None:
            r[f'{kind}_cores'] += 1
        sd = subdirs(kind)
        r[f'{kind}_cnf_built'] += built(a, sd[0], name)
        r[f'{kind}_unsat_built'] += built(a, sd[1], name)
    if os.path.exists(seeds_path(a)):
        pl = C.load_plan(seeds_path(a))
        r['seeds'] = sum(1 for v in pl.values() if v[0] == 'self')
    r['disk_free_mb'] = C.disk_free_mb()
    print(json.dumps(dict(r), indent=1))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    ps = {c: sub.add_parser(c) for c in ('keys', 'cores', 'plan', 'cnf', 'replay', 'merge', 'build', 'publish', 'status')}
    for p in ps.values():
        p.add_argument('--plan', required=True)
        p.add_argument('--core', default=CORE)
        p.add_argument('--out', default=os.path.join(SCR, 'out'))
        p.add_argument('--build', default=None, help='scratch build directory (also searched for built .olean)')
        p.add_argument('--index', type=int, default=0)
        p.add_argument('--workers', type=int, default=1)
        p.add_argument('--min-disk-mb', type=int, default=1200)
        p.add_argument('names', nargs='*')
    ps['cores'].add_argument('--kinds', default='ctx,share,plain')
    ps['cores'].add_argument('--limit', type=int, default=0)
    ps['cores'].add_argument('--share-tl', type=float, default=3600)
    for c in ('cnf', 'replay'):
        ps[c].add_argument('--kinds', default='ctx,share,seed')
        ps[c].add_argument('--limit', type=int, default=0)
        ps[c].add_argument('--budget-hints', type=float, default=0)
    ps['replay'].add_argument('--big', type=float, default=5e6)
    ps['replay'].add_argument('--seed-jobs', default='1', help="parallel cadical runs per round, or 'auto'")
    ps['replay'].add_argument('--cores', type=int, default=4, help='for --seed-jobs auto')
    ps['merge'].add_argument('--remove-parts', action='store_true')
    ps['build'].add_argument('--merged', action='store_true', help='build the merged one-module certificates')
    ps['build'].add_argument('--jobs', type=int, default=1)
    ps['build'].add_argument('--rss-cap-gb', type=float, default=10.0)
    ps['build'].add_argument('--lean-bin', default=None)
    ps['build'].add_argument('--extra-src', action='append', default=[])
    ps['publish'].add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    a.plan = os.path.abspath(a.plan)
    assert 0 <= a.index < a.workers
    globals()[a.cmd](a)


if __name__ == '__main__':
    main()
