def core_ctx(k, work, certs, cad, tl):
    """ctxcert.core with the full-proof LRAT size recorded (`lrat`, as cert233's cores)."""
    ctx, dirs, t, cap = k
    name = X.name_of(ctx, dirs, t, cap)
    bounds = X.bounds_of(ctx, t)
    assert len(dirs) == ctx and len(bounds) + 1 == ctx and len(t) == 6
    meta = {'name': name, 'module': 'LocalWindowCnf.' + name, 'kind': 'ctxshare', 'ctx': ctx,
            'dirs': list(dirs), 'syms': list(t), 'bounds': [list(b) for b in bounds], 'k': len(bounds) - 5,
            'cap': cap, 'resolution': C.MRES, 'window': C.wincert.window_from_dirs(list(dirs)), 'radius': 4}
    enc = X.enc_of(meta)
    npre = len(enc.clauses)
    st, cuts, sec = share233.solve(enc, tl)
    if st != 'UNSAT':
        return {'name': name, 'result': st, 'solve_s': round(sec, 1)}
    gz = os.path.join(certs, name + '.cnf.gz')
    sha = C.write_cnf_gz(enc.nv, enc.clauses, gz)
    t1 = time.time()
    cnf = GC.extract_cnf(name, work, certs)
    nl, nh, desc, ids = GC.best_cadical_proof(cnf, os.path.join(work, name + '.full'), cad, [1],
                                              portfolio=[['--unsat']], rounds=1)
    os.remove(os.path.join(work, name + '.full.lrat'))
    for p in (gz, cnf):
        if os.path.exists(p):
            os.remove(p)
    ren, core_, tags, _ = C.share_compact(enc, ids)
    meta.update({'result': 'UNSAT', 'full_variables': enc.nv, 'full_clauses': len(enc.clauses), 'base_clauses': npre,
                 'full_sha256': sha, 'cycle_cuts': cuts, 'full_core_ids': ids, 'variables': len(ren),
                 'cnf_clauses': len(ids), 'core_ids': list(range(1, len(ids) + 1)),
                 'core_kinds': dict(collections.Counter(x[0] if x[0] != 'old' else 'old.' + x[1][0] for x in tags)),
                 'cnf_source': 'ctxcert.TaggedShareCtx(winOf dirs, bounds, cap, k) plus cycle_cuts (in order), SHA256 '
                               'full_sha256; the core is clauses full_core_ids of it, renumbered by cert233.share_compact',
                 'hash_source': ME,
                 'core_producer': f'cadical --lrat {desc} on the full ctx share CNF, trimmed ({nl} lemmas, {nh} hints)',
                 'lrat': {'lemmas': nl, 'hints': nh, 'estimated_from_full_proof': True},
                 'secs': {'solve': round(sec, 2), 'core': round(time.time() - t1, 2)}})
    return meta


def cores(a):
    os.makedirs(a.core, exist_ok=True)
    kinds = set(a.kinds.split(','))
    todo = sorted((x for x in items(a, kinds) if mine(a, x[2]) and (not a.names or x[2] in a.names)),
                  key=lambda x: (x[3], x[2]))
    work = os.path.join(SCR, f'core{a.index}')
    certs = os.path.join(work, 'certs')
    os.makedirs(certs, exist_ok=True)
    cad = C.cadical(work)
    n = 0
    for kind, k, name, est in todo:
        if load_meta(a, name) is not None:
            continue
        if kind == 'share' and built(a, 'LocalWindowUnsat', name):
            continue                                    # a 233 certificate (same key, same cap)
        if C.disk_free_mb() < a.min_disk_mb:
            print('stop: disk below %d MB' % a.min_disk_mb, flush=True)
            break
        t0 = time.time()
        try:
            meta = (core_ctx(k, work, certs, cad, a.share_tl) if kind == 'ctx' else
                    C.core_share(k, work, certs, cad, a.share_tl) if kind == 'share' else
                    C.core_plain(k, work, certs, cad))
        except Exception as e:     # noqa: BLE001  (logged; retried by the next run)
            rec(a, 'cores', {'name': name, 'kind': kind, 'error': repr(e)[:500], 's': round(time.time() - t0, 1)})
            for d in (work, certs):
                for fn in os.listdir(d):
                    if fn.startswith(name):
                        os.remove(os.path.join(d, fn))
            continue
        if meta.get('result', 'UNSAT') != 'UNSAT':
            rec(a, 'cores', {'name': name, 'kind': kind, 'result': meta['result'], 's': round(time.time() - t0, 1)})
            continue
        C.save_meta(a.core, name, meta)
        rec(a, 'cores', {'name': name, 'kind': kind, 'core': len(meta['core_ids']), 'variables': meta['variables'],
                         'est_hints': meta['lrat']['hints'], 'plan_est_hints': est, 's': round(time.time() - t0, 1)})
        n += 1
        if a.limit and n >= a.limit:
            break
    print(f'cores: {n} computed (worker {a.index}/{a.workers})', flush=True)


