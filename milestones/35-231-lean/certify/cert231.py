def publish(a):
    """Push the two generated sources of each name to refs/heads/xfer/231/<name> (one orphan commit,
    gzip -9 parts under 45 MiB, record.json), as xfer233.py did for 233.  The receiving machine
    rebuilds both modules, so a source made elsewhere needs no trust."""
    import xfer233 as XF
    kind_of = {name: kind for kind, k, name, est in items(a)}
    scr = os.path.join(SCR, 'publish')
    os.makedirs(scr, exist_ok=True)
    have = set() if a.dry_run else set(XF.ls_branches(XPFX))
    for n in a.names:
        kd = kind_of[n]
        paths = [src_path(a.out, kd, 0, n), src_path(a.out, kd, 1, n)]
        if n in have:
            print(json.dumps({'name': n, 'skip': 'branch exists'}))
            continue
        if not all(os.path.exists(p) for p in paths):
            print(json.dumps({'name': n, 'skip': 'sources missing'}))
            continue
        data = [open(p, 'rb').read() for p in paths]
        meta = {'name': n, 'kind': kd, 'plan': os.path.relpath(a.plan, ROOT),
                'files': [{'path': os.path.relpath(p, a.out), 'bytes': len(x),
                           'sha256': hashlib.sha256(x).hexdigest()} for p, x in zip(paths, data)]}
        if a.dry_run:
            print(json.dumps({'name': n, 'dry_run': True, **meta}))
            continue
        commit = XF.push_blobs(XPFX + n, data, meta, scr, f'xfer 231 sources {n}')
        print(json.dumps({'name': n, 'pushed': commit}))


