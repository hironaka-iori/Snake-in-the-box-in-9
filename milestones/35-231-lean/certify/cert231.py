def work_items(a, kinds):
    """(est, kind, key, name, meta, wide) of the certificates to generate, smallest first."""
    out = []
    pl = None
    for kind, k, name, est in items(a, ('ctx', 'share', 'plain')):
        if not mine(a, name) or (a.names and name not in a.names):
            continue
        wide = None
        if kind == 'plain':
            if 'seed' not in kinds:
                continue
            if pl is None:
                if not os.path.exists(seeds_path(a)):
                    raise SystemExit(f'no seed plan {seeds_path(a)}: run `plan` first')
                pl = C.load_plan(seeds_path(a))
            if pl[k][0] != 'self':
                continue                                   # derived from a seed by L1/L2: glue only
            wide = pl[k][1]
            kind = 'seed'
        elif kind not in kinds:
            continue
        m = load_meta(a, name)
        if m is None or m.get('result', 'UNSAT') != 'UNSAT':
            continue
        out.append((m['lrat']['hints'], kind, k, name, m, wide, est))
    out.sort(key=lambda x: (x[0], x[3]))
    return out


def src_path(out, kind, which, name):
    return os.path.join(out, subdirs(kind)[which], name + '.lean')


def cnf(a):
    work = os.path.join(SCR, 'cnf')
    certs = os.path.join(work, 'certs')
    jd = os.path.join(work, 'json')
    os.makedirs(certs, exist_ok=True)
    n = spent = 0
    for h, kind, k, name, m, wide, est in work_items(a, set(a.kinds.split(','))):
        if os.path.exists(src_path(a.out, kind, 0, name)) or built(a, subdirs(kind)[0], name):
            continue
        if C.disk_free_mb() < a.min_disk_mb:
            print('stop: disk below %d MB' % a.min_disk_mb, flush=True)
            break
        t0 = time.time()
        if kind == 'seed':
            meta = dict(m)
            if [tuple(x) for x in wide] != [tuple(x) for x in GC.dir_bounds(k[1])]:
                meta['lean_bounds'] = [list(x) for x in wide]
                meta['plan_bounds'] = [list(x) for x in wide]
            C.plain_json(meta, jd)
            gz = C.regen_plain(meta, certs)
            r = CP.emit(name, certs, jd, a.out, part_lits=C.PART_LITS, sat_v2=True)
            os.remove(gz)
            p = os.path.join(jd, name + '.json')
            if os.path.exists(p):
                os.remove(p)
        elif kind == 'share':
            r = C.emit_share(m, a.out)
        else:
            keep = C.share_regen
            try:
                r = X.emit_cnf(m, a.out)          # sets C.share_regen = X.regen; restored below
            finally:
                C.share_regen = keep
        rec(a, 'cnf', {'name': name, 'kind': kind, 'est_hints': h, 'plan_est_hints': est,
                       'src_bytes': os.path.getsize(src_path(a.out, kind, 0, name)),
                       'core': r.get('core'), 'parts': r.get('parts'), 's': round(time.time() - t0, 1)})
        n += 1
        spent += h
        if (a.limit and n >= a.limit) or (a.budget_hints and spent >= a.budget_hints):
            break


def replay(a):
    work = os.path.join(SCR, f'replay{a.index}')
    certs = os.path.join(work, 'certs')
    jd = os.path.join(work, 'json')
    tmp = os.path.join(work, 'out')
    os.makedirs(certs, exist_ok=True)
    cad = C.cadical(work)
    n = spent = 0
    for h, kind, k, name, m, wide, est in work_items(a, set(a.kinds.split(','))):
        if os.path.exists(src_path(a.out, kind, 1, name)) or built(a, subdirs(kind)[1], name):
            continue
        if C.disk_free_mb() < a.min_disk_mb:
            print('stop: disk below %d MB' % a.min_disk_mb, flush=True)
            break
        if kind == 'seed':
            meta = m
            gz = C.regen_plain(meta, certs)
        else:
            enc, ren, core, tags, used_c = (X.regen(m) if kind == 'ctx' else C.share_regen(m))
            rl = lambda x: (1 if x > 0 else -1) * ren[abs(x)]   # noqa: E731
            meta = dict(m)
            gz = os.path.join(certs, name + '.cnf.gz')
            C.write_cnf_gz(len(ren), [[rl(x) for x in c] for c in core], gz)
        C.plain_json(meta, jd)
        big = h >= a.big
        t0 = time.time()
        _, info = GC.core_lrat(name, meta['core_ids'], work, cad, list(range(1, (8 if big else 2) + 1)), certs,
                               rounds=5 if big else 1, jobs=C.seed_jobs(h, a))
        t1 = time.time()
        GC.extract_cnf(name, work, certs)
        dest = tmp if kind == 'ctx' else a.out
        cmd = [sys.executable, C.V3, '--work', work, '--data', jd, '--out', dest, '--seg', '60000',
               '--off', str(C.offset(meta['variables'])), '--warm', str(C.WARM), name]
        r = subprocess.run(['nice', '-n', '10', *cmd], capture_output=True, text=True)
        if r.returncode != 0:
            print(r.stderr[-3000:], file=sys.stderr)
            raise SystemExit(f'generation failed for {name}')
        if kind == 'ctx':                               # ctxcert.replay's rewrite of the import
            p = os.path.join(tmp, 'LocalWindowUnsat', name + '.lean')
            src = open(p).read()
            os.remove(p)
            assert src.count('import LocalWindowCnf.' + name) == 1
            src = src.replace('import LocalWindowCnf.' + name, 'import LocalWindowCtxCnf.' + name)
            os.makedirs(os.path.dirname(src_path(a.out, kind, 1, name)), exist_ok=True)
            open(src_path(a.out, kind, 1, name), 'w').write(src)
        rec(a, 'replay', {'case': name, 'kind': kind, 'variables': meta['variables'], 'core': len(meta['core_ids']),
                          'est_hints': h, 'plan_est_hints': est, 'core_lrat_hints': info['hints'],
                          'producer': info['producer'], 'lrat_s': round(t1 - t0, 1),
                          **json.loads(r.stdout.strip().splitlines()[-1])})
        for p in [os.path.join(work, name + ext) for ext in ('.lrat', '.lrat.json', '.core.cnf', '.cnf')] + \
                 [gz, os.path.join(jd, name + '.json')]:
            if os.path.exists(p):
                os.remove(p)
        n += 1
        spent += info['hints']
        if (a.limit and n >= a.limit) or (a.budget_hints and spent >= a.budget_hints):
            break


