"""Certificates of the 231 chain (milestone 35): production driver for the certificate premises of
`upper_231_of_refuted6SC<T>` (generated by milestones/35-231-lean/scripts/gen_lean_{automaton,chain}6sc.py),
from a certificate plan of milestones/28-combined-identities/certplan231.py.

Kinds of paid certificates (the plan's rows with `free = false`):

  ctx    ctx 7 / ctx 8 keys (plan kinds c7, c8): `RefutedCtx7 (dirs, t, level - 1)` /
         `RefutedCtx8 ...`.  Module pair `LocalWindowCtxCnf.C<ctx><dirs>A<t>K<cap>` (packed core +
         `TagsSW.soundSC`) and `LocalWindowCtxUnsat.C...` (checker v3 replay); the CNF is
         `ctxcert.TaggedShareCtx` (milestones/35-231-lean/scripts/ctxcert.py), the module text
         `cert233.emit_share` plus ctxcert's asserted rewrite.
  share  new 5-window share keys (plan kind 5, not on a floor, not a 233 key): `RefutedShare ... 12 K`,
         module pair `LocalWindowCnf.T...` / `LocalWindowUnsat.T...` exactly as in cert233.py
         (`core_share`, `emit_share`, checker v3).  A key whose replay .olean exists (233) is skipped.
  seed   new plain k6 keys (plan kind plain, not free): cores by `cert233.core_plain`, then a seed plan
         (`plan`, the families L1/L2 of cert233.plan over the new keys only), then module pairs
         `LocalWindowCnf.S...` (Sat v2) / `LocalWindowUnsat.S...` of the seeds, as in cert233.py.
         The plan's free plain keys (233 keys, 235-237 replays, L1/L2 from a 233 seed) need no
         certificate, only glue.

Steps (each resumable: an item whose output exists is skipped; every step but `plan` can be split
across machines with `--index I --workers W`: item belongs to worker I iff sha1(name) mod W = I):

  python3 cert231.py keys    --plan P                          counts by kind and status
  nice -n 10 python3 cert231.py cores  --plan P [--kinds ctx,share,plain] [--index I --workers W] [--limit N] [NAME ...]
  python3 cert231.py plan    --plan P                          seed plan of the new plain keys
  python3 cert231.py cnf     --plan P [--kinds ctx,share,seed] [--index I --workers W] [--limit N] [--budget-hints H] [NAME ...]
  nice -n 10 python3 cert231.py replay --plan P [--kinds ...] [...]
  python3 cert231.py merge   --plan P [--remove-parts] NAME ...   one module per certificate (AUDIT-SCALING.md)
  python3 cert231.py build   --plan P --build DIR [--jobs 2] [--merged] NAME ...    compile (build231.py)
  python3 cert231.py publish --plan P [--dry-run] NAME ...     push both sources to xfer/231/<name>
  python3 cert231.py status  --plan P

Records (milestones/35-231-lean/certify/data/, tag = the plan's basename): cores231_<tag>.jsonl
(per core: kind, core clauses, full-proof hints = est_hints, seconds), cnf231_<tag>.jsonl (source
bytes), replay231_<tag>.jsonl (est_hints, plan_est_hints, hints, lemmas, segments, lean_bytes, lrat
seconds, producer), and the build log of build231.py (seconds, CPU seconds, peak RSS, .olean bytes).
Core JSONs: --core (default milestones/35-231-lean/certify/cores, gzipped, one per key; plain and
share cores of milestone 33 in milestones/10-window-aggregate/data/lean_core_direction_6s are read too).
Work directory: $CERT231_SCR (default /home/user/cert231work).
"""
