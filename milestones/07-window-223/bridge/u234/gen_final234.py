"""Final modules of the 234 bridge.

usage: python3 -I gen_final234.py OUTDIR [--cond UpperBound235Cond.lean] [--uncond NAME]

* ShareRefs234.lean: the 34 share refutations `V<dirs>.ref`, one per shape of `shapesK6R3W`, and
  `SH234.shares_K6R3W`: every window `j` (1 ≤ j, j + 7 ≤ m) of every snake has share sum ≥ 21.
* UpperBound234Cond.lean: `S235.T235.upper_234_of_shapes` (234 from the 235 shape refutations
  `∀ e ∈ E, ShapeRefuted e.c e.L`) and `upper_234_of_remaining`, with exactly the hypotheses of
  `upper_235_of_remaining` read from UpperBound235Cond.lean.
* with --uncond NAME (a theorem `NAME : ∀ e ∈ S235.T235.E, ShapeRefuted e.c e.L` exported by the
  unconditional 235 bridge, module given by --uncond-module): UpperBound234.lean with
  `Snake9.upper_bound_234` and `Snake9.verified_interval_191_234`.
"""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'milestones', '10-window-aggregate', 'scripts'))


def shapes():
    src = open(os.path.join(REPO, 'work', 'spectral', 'stronger', 'WindowAutomatonK6R3WData.lean')).read()
    m = re.search(r'def shapesK6R3W : List \(List Nat\) := \[(.*)\]\n', src)
    return [list(map(int, x.split(','))) for x in re.findall(r'\[([0-9, ]+)\]', m.group(1))]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--cond', help='UpperBound235Cond.lean to read the remaining-shape hypotheses from')
    ap.add_argument('--uncond', help='name of the unconditional `∀ e ∈ E, ShapeRefuted e.c e.L`')
    ap.add_argument('--uncond-module', default='D235Refs')
    a = ap.parse_args()
    sh = shapes()
    assert len(sh) == 34
    P = ['V' + ''.join(map(str, s)) for s in sh]
    s = ''.join(f'import {p}Ref\n' for p in P)
    s += 'import AggregateDirectionK6R3WShare234\n'
    s += ('/-! The share premise of the 234 bound, unconditionally: each of the 34 six-centre shapes of\n'
          '`shapesK6R3W` has a kernel-checked share refutation (`V<dirs>.ref : ShareRef c 21`), and every\n'
          'window of a snake is normalised onto its canonical shape (`SH234.shareRef_window`).\n'
          'Generated by u234/gen_final234.py. -/\n')
    s += 'namespace SH234\nopen Snake9 Snake9.WindowAutomaton Snake9.ShareBonus\n\n'
    s += 'theorem refs : ∀ s ∈ shapesK6R3W, ShareRef s 21 := by\n'
    s += '  intro s hs\n  simp only [shapesK6R3W, List.mem_cons, List.not_mem_nil, or_false] at hs\n'
    s += '  rcases hs with ' + ' | '.join(['rfl'] * len(P)) + '\n'
    s += ''.join(f'  · exact {p}.ref\n' for p in P)
    s += ('\n/-- Every six-centre window `j` (`1 ≤ j`, `j + 7 ≤ m`) has share sum at least 21. -/\n'
          'theorem shares_K6R3W {m : Nat} (p : Snake m) :\n'
          '    ∀ j, 1 ≤ j → j + 7 ≤ m → 21 ≤ windowShareK6R3W p j := by\n'
          '  intro j _ hj\n'
          '  rw [windowShareK6R3W_eq]\n'
          '  exact shareRef_window (L := 7) (by decide) refs p j hj (window_shape_memK6R3W p j hj)\n\n'
          '#print axioms shares_K6R3W\nend SH234\n')
    open(os.path.join(a.out, 'ShareRefs234.lean'), 'w').write(s)
    # ---- conditional 234
    hyps, names = '', ''
    if a.cond:
        src = open(a.cond).read()
        sig = re.search(r'theorem upper_235_of_remaining (.*?)\n', src).group(1)
        hs = re.findall(r'\((h\d+) : (ShapeRefuted e\d+\.c e\d+\.L)\)', sig)
        hyps = ' '.join(f'({h} : {t})' for h, t in hs)
        names = ' '.join(h for h, _ in hs)
    s = 'import ShareRefs234\nimport D235Table\n' + ('import UpperBound235Cond\n' if a.cond else '')
    s += ('/-! # The 234 bound from the 235 window premises and the share bridge\n\n'
          '`upper_234_of_direction_windows_and_shares_allK6R3W` (AggregateDirectionK6R3WShare234, through\n'
          '`ShareBonus.upper_of_walk_and_shares` at LB 21: `4935 m ≤ 1159221`, 234.89) needs the K6R3W window\n'
          'premises `hw2 .. hw6`, given by `S235.T235.prem2 .. prem6` from the 235 shape refutations, and\n'
          'the share premise `SH234.shares_K6R3W` (unconditional). -/\n')
    s += 'namespace S235.T235\nopen S235\n\n'
    s += ('/-- 234 from the refutation of the 34 shapes of the 235 bridge. -/\n'
          'theorem upper_234_of_shapes (hE : ∀ e ∈ E, ShapeRefuted e.c e.L) {m : Nat} (p : Snake9.Snake m) :\n'
          '    m ≤ 234 :=\n'
          '  Snake9.upper_234_of_direction_windows_and_shares_allK6R3W p (prem2 hE p) (prem3 hE p) (prem4 hE p)\n'
          '    (prem5 hE p) (prem6 hE p) (SH234.shares_K6R3W p)\n\n')
    if a.cond:
        s += ('/-- The 234 bound, conditional only on the shapes the 235 bridge has not refuted yet (the\n'
              'hypotheses of `upper_235_of_remaining`). -/\n'
              f'theorem upper_234_of_remaining {hyps}\n    {{m : Nat}} (p : Snake9.Snake m) : m ≤ 234 :=\n'
              f'  upper_234_of_shapes (refutedE_of_remaining {names}) p\n\n')
    s += 'end S235.T235\n\n#print axioms S235.T235.upper_234_of_shapes\n'
    if a.cond:
        s += '#print axioms S235.T235.upper_234_of_remaining\n'
    open(os.path.join(a.out, 'UpperBound234Cond.lean'), 'w').write(s)
    if a.uncond:
        s = f'import ShareRefs234\nimport D235Table\nimport {a.uncond_module}\n'
        s += ('/-! # 191 ≤ a(9) ≤ 234\n\nThe 235 window premises (`S235.T235.prem2 .. prem6` from the unconditional\n'
              f'235 shape refutations `{a.uncond}`) and the share premise (`SH234.shares_K6R3W`) give at most 234\n'
              'edges for every snake in Q9 (`upper_234_of_direction_windows_and_shares_allK6R3W`). -/\n')
        s += ('namespace Snake9\nopen S235 S235.T235\n\n'
              '/-- **Unconditional bound**: every snake in the 9-cube has at most 234 edges. -/\n'
              'theorem upper_bound_234 {m : Nat} (p : Snake m) : m ≤ 234 :=\n'
              f'  upper_234_of_direction_windows_and_shares_allK6R3W p (prem2 {a.uncond} p) (prem3 {a.uncond} p)\n'
              f'    (prem4 {a.uncond} p) (prem5 {a.uncond} p) (prem6 {a.uncond} p) (SH234.shares_K6R3W p)\n\n')
        s += ('theorem upper_bound_234\' : ∀ m, Nonempty (Snake m) → m ≤ 234 :=\n'
              '  fun _ ⟨p⟩ => upper_bound_234 p\n\n'
              '/-- The verified interval: a 191-edge snake exists, and no snake has more than 234 edges. -/\n'
              'theorem verified_interval_191_234 :\n'
              '    Nonempty (Snake 191) ∧ ∀ m, Nonempty (Snake m) → m ≤ 234 :=\n'
              '  ⟨lower_bound, upper_bound_234\'⟩\n\nend Snake9\n\n'
              '#print axioms Snake9.upper_bound_234\n#print axioms Snake9.verified_interval_191_234\n')
        open(os.path.join(a.out, 'UpperBound234.lean'), 'w').write(s)


if __name__ == '__main__':
    main()
