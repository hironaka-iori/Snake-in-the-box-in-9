"""Write D235Table.lean (the 34 refuted shapes `E`, the kernel-decided coverage of the K6R3W window
table, and the 235 bound conditional on `∀ e ∈ E, ShapeRefuted e.c e.L`), D235Refs.lean (that
condition, from the per-shape `Q<dirs>Ref` modules) and UpperBound235.lean.

usage: python3 -I gen_table235.py OUTDIR [--setfile F] [--done DIRS ...]
Without --done every shape is taken as bridged (D235Refs imports all 34 `Q<dirs>Ref`).
"""
import argparse, json, os, sys
from itertools import product
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen235 import windows_of, DATA, atomic_write, code_of


def canon(ds):
    seen, out = [], []
    for d in ds:
        if d not in seen:
            seen.append(d)
        out.append(seen.index(d))
    return tuple(out)


def L(xs):
    return '[' + ', '.join(map(str, xs)) + ']'


def rsL(al):
    return '[' + ', '.join(f'({lo}, {hi})' for lo, hi in al) + ']'


HDR = '''/-!
# The 235 premise table: refuted shapes and kernel-decided coverage (generated by u235/gen_table235.py)

`E` lists the 34 direction shapes of the premise set `minimal_L7_k6_K5_r3_fix.json` with their
2635 count-range tuples (radius 3, `(6, 21)` = lumped symbol `≥ 6`), in the order of the
per-shape modules `Q<dirs>Ref`.  For every window size `n = 2..6`, `rgs<n>` says that every
canonical direction list of length `n + 1` is listed or has empty forward and reverse tables,
and `tab_<shape>` that every flagged symbol tuple of a listed shape is covered by a range tuple of
the shape read forwards or of its reversal read backwards.  `upper_235_of_shapes` is the 235
bound from `∀ e ∈ E, ShapeRefuted e.c e.L` alone.
-/
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--setfile', default='minimal_L7_k6_K5_r3_fix.json')
    ap.add_argument('--done', nargs='*', default=None,
                    help='bridged shapes (e.g. 0,1,2); writes UpperBound235Cond.lean with one hypothesis per other shape')
    a = ap.parse_args()
    Ex = json.load(open(os.path.join(DATA, a.setfile)))['exclusions']
    shapes = sorted({tuple(e['dirs']) for e in Ex}, key=lambda d: (len(d), d))
    for d in shapes:
        assert canon(d) == d
    listed = {}
    for d in shapes:
        for c in (d, canon(tuple(reversed(d)))):
            listed.setdefault(len(c) - 1, set()).add(c)
    s = 'import Win235Glue\n/-! The 34 refuted shapes of the 235 premise set and their range tuples (codes, `decR`). -/\n'
    s += 'namespace S235.T235\nopen Snake9 Snake9.WindowAutomaton S235\nset_option maxRecDepth 100000\n\n'
    for i, d in enumerate(shapes):
        ws = windows_of(d, 3, a.setfile)
        s += f'def e{i} : Entry := ⟨{L(d)}, [' + ', '.join(str(code_of(al)) for al in ws) + f'].map (decR {len(d) - 1})⟩\n'
    s += 'def E : List Entry := [' + ', '.join(f'e{i}' for i in range(len(shapes))) + ']\n\n'
    s += 'end S235.T235\n'
    data_mod = s
    files = {'D235Data': data_mod}
    tabmods = []
    s = ''
    names = {}
    for n in sorted(listed):
        lst = sorted(listed[n])
        for c in lst:
            cs = ''.join(map(str, c))
            nm = 'tab_' + cs
            names[c] = nm
            t = f'import D235Data\n/-! Coverage of the K6R3W table for the direction list {list(c)} ({n} centres). -/\n'
            t += 'namespace S235.T235\nopen Snake9 Snake9.WindowAutomaton S235\nset_option maxRecDepth 100000\n'
            k = {4: 1, 5: 1, 6: 2}.get(n, 0)
            if k == 0:
                t += f'theorem {nm} : TabOK E {n} {L(c)} :=\n  tabOK_of_allSyms (by decide +kernel : allSyms {n} (tabP E {L(c)}) = true)\n'
            else:
                pres = [list(x) for x in product(range(1, 7), repeat=k)]
                for pre in pres:
                    t += f'theorem pc_{cs}_{"".join(map(str, pre))} : pieceOK E {n} {L(c)} {L(pre)} = true := by decide +kernel\n'
                term = 'fun _ h => absurd h List.not_mem_nil'
                for pre in reversed(pres):
                    term = f'pieces_cons pc_{cs}_{"".join(map(str, pre))} ({term})'
                t += (f'theorem {nm} : TabOK E {n} {L(c)} :=\n  tabOK_of_pieces (k := {k}) (by decide) (by\n'
                      f'    show ∀ pre ∈ ({L(L(x) for x in pres)} : List (List Nat)), pieceOK E {n} {L(c)} pre = true\n'
                      f'    exact {term})\n')
            t += 'end S235.T235\n'
            files[f'D235Tab_{cs}'] = t
            tabmods.append(f'D235Tab_{cs}')
    s = ''.join(f'import {mm}\n' for mm in tabmods)
    s += 'import AggregateDirectionK6R3WConditional\n' + HDR
    s += 'namespace S235.T235\nopen Snake9 Snake9.WindowAutomaton S235\nset_option maxRecDepth 100000\n\n'
    for n in sorted(listed):
        lst = sorted(listed[n])
        s += f'def listed{n} : List (List Nat) := [' + ', '.join(L(c) for c in lst) + ']\n'
        s += f'theorem rgs{n} : rgsOK {n} listed{n} = true := by decide +kernel\n'
        term = 'fun _ h => absurd h List.not_mem_nil'
        for c in reversed(lst):
            term = f'tabOK_cons {names[c]} ({term})'
        s += f'theorem hS{n} : ∀ c ∈ listed{n}, TabOK E {n} c :=\n  {term}\n\n'
    # the premises in the exact form of the conditional theorem
    s += 'section\nvariable (hE : ∀ e ∈ E, ShapeRefuted e.c e.L) {m : Nat} (p : Snake m)\ninclude hE\n'
    for n in range(2, 7):
        ds = ', '.join('pathDir p j' if i == 0 else f'pathDir p (j+{i})' for i in range(n + 1))
        ss = ', '.join(f'sym (countSeq p (j+{i}))' for i in range(1, n + 1))
        s += (f'theorem prem{n} (j : Nat) (hj : j + {n + 1} ≤ m) :\n    wforbK6R3W [{ds}]\n      [{ss}] = false :=\n'
              f'  no_win (n := {n}) hE rgs{n} hS{n} p j (by omega)\n')
    s += 'end\n\n'
    s += ('/-- The 235 bound from the refutation of the 34 shapes. -/\n'
          'theorem upper_235_of_shapes (hE : ∀ e ∈ E, ShapeRefuted e.c e.L) {m : Nat} (p : Snake m) : m ≤ 235 :=\n'
          '  upper_235_of_direction_windowsK6R3W p (prem2 hE p) (prem3 hE p) (prem4 hE p) (prem5 hE p) (prem6 hE p)\n\n')
    s += 'end S235.T235\n'
    files['D235Table'] = s
    os.makedirs(a.out, exist_ok=True)
    for name, src in files.items():
        atomic_write(os.path.join(a.out, name + '.lean'), src)
    print('modules:', ' '.join(files))
    # ---- D235Refs and UpperBound235
    mods = ['Q' + ''.join(map(str, d)) for d in shapes]
    s = 'import D235Table\n' + ''.join(f'import {mm}Ref\n' for mm in mods)
    s += '/-! Every shape of the 235 premise set is refuted (one shared, kernel-checked proof per shape). -/\n'
    s += 'namespace S235.T235\nopen S235\n'
    term = 'fun _ h => absurd h List.not_mem_nil'
    for i in reversed(range(len(shapes))):
        term = f'entry_cons (e := e{i}) {mods[i]}.refuted ({term})'
    s += f'theorem refutedE : ∀ e ∈ E, ShapeRefuted e.c e.L :=\n  {term}\nend S235.T235\n'
    atomic_write(os.path.join(a.out, 'D235Refs.lean'), s)
    U = '''import D235Refs
/-!
# Every snake in the 9-cube has at most 235 edges

`upper_235_of_direction_windowsK6R3W` (AggregateDirectionK6R3WConditional) assumes that no window
of 2..6 consecutive internal vertices has a direction shape and lumped counts flagged in the
K6R3W automaton table (2635 certified exclusions, radius 3).  `S235.T235.prem2..prem6` discharge
these premises from the per-shape refutations `S235.T235.refutedE` (shape CNF checked once per
shape by G1, one shared FastRup proof with a kernel-checked target per window).
-/
namespace Snake9

/-- **Unconditional bound**: every snake in the 9-cube has at most 235 edges. -/
theorem upper_bound_235 {m : Nat} (p : Snake m) : m ≤ 235 :=
  S235.T235.upper_235_of_shapes S235.T235.refutedE p

theorem upper_bound_235' : ∀ m, Nonempty (Snake m) → m ≤ 235 :=
  fun _ ⟨p⟩ => upper_bound_235 p

/-- The verified interval: a 191-edge snake exists, and no snake has more than 235 edges. -/
theorem verified_interval_191_235 :
    Nonempty (Snake 191) ∧ ∀ m, Nonempty (Snake m) → m ≤ 235 :=
  ⟨lower_bound, upper_bound_235'⟩

end Snake9

#print axioms Snake9.upper_bound_235
#print axioms Snake9.verified_interval_191_235
'''
    atomic_write(os.path.join(a.out, 'UpperBound235.lean'), U)
    if a.done is not None:
        done = {tuple(int(x) for x in d.split(',')) for d in a.done}
        s = 'import D235Table\n' + ''.join(f'import {mods[i]}Ref\n' for i, d in enumerate(shapes) if d in done)
        rem = [i for i, d in enumerate(shapes) if d not in done]
        s += ('/-!\n# The 235 bound from the shapes not yet bridged\n\n'
              f'{len(shapes) - len(rem)} of the 34 shapes ({sum(len(windows_of(d, 3, a.setfile)) for d in shapes if d in done)} of the 2635 windows) are refuted\n'
              'by kernel-checked shape bridges; `upper_235_of_remaining` needs only the refutation of the\n'
              f'other {len(rem)} shapes (hypotheses `h<i>`, `S235.T235.e<i>` as in `D235Data`).\n-/\n')
        s += 'namespace S235.T235\nopen S235\n'
        hyps = ' '.join(f'(h{i} : ShapeRefuted e{i}.c e{i}.L)' for i in rem)
        term = 'fun _ h => absurd h List.not_mem_nil'
        for i in reversed(range(len(shapes))):
            pf = f'h{i}' if i in rem else f'{mods[i]}.refuted'
            term = f'entry_cons (e := e{i}) {pf} ({term})'
        s += (f'theorem refutedE_of_remaining {hyps} :\n    ∀ e ∈ E, ShapeRefuted e.c e.L :=\n  {term}\n\n'
              f'/-- The 235 bound, conditional only on the refutation of the remaining shapes. -/\n'
              f'theorem upper_235_of_remaining {hyps}\n    {{m : Nat}} (p : Snake9.Snake m) : m ≤ 235 :=\n'
              f'  upper_235_of_shapes (refutedE_of_remaining ' + ' '.join(f'h{i}' for i in rem) + ') p\n')
        s += 'end S235.T235\n\n#print axioms S235.T235.upper_235_of_remaining\n'
        atomic_write(os.path.join(a.out, 'UpperBound235Cond.lean'), s)
    print('shapes', len(shapes), 'listed', {n: len(v) for n, v in listed.items()})


if __name__ == '__main__':
    main()
