"""Generate the decoding tables (ball, interior vertices, counter blocks) for the two
(2,2,3) window CNFs, by re-running wincert.Encoding with a recording atmost()."""
import sys, json, hashlib
sys.path.insert(0, '/home/user/Snake-in-the-box-in-9/milestones/10-window-aggregate/scripts')
import wincert
from wincert import Encoding, window_from_dirs
G2 = sys.argv[1]; OUT = sys.argv[2]
class Rec(Encoding):
    def atmost(self, lits, k, kind):
        if not hasattr(self, 'blocks'): self.blocks = []
        base = self.nv + 1
        n0 = len(self.clauses)
        super().atmost(lits, k, kind)
        if k < len(lits) and k > 0:
            self.blocks.append((base, k, list(lits), kind))
            assert self.nv == base - 1 + len(lits) * k
CASES = {'Rep': ([0, 1, 2, 0], 'w223_rep'), 'Dis': ([0, 1, 2, 3], 'w223_dis')}
out = {}
for name, (dirs, tag) in CASES.items():
    enc = Rec(window_from_dirs(dirs), [2, 2, 3], 3)
    meta = json.load(open(f'{G2}/data/{tag}.meta.json'))
    assert enc.ball == meta['ball'] and enc.window == meta['window']
    # cnf clauses (without cycle cuts) must be a prefix of the stored cnf
    cl = [list(map(int, l.split()))[:-1] for l in open(f'{G2}/data/{tag}.cnf') if l[0] not in 'pc']
    assert cl[:len(enc.clauses)] == enc.clauses, name
    print(name, 'extra (cycle cut) clauses:', len(cl) - len(enc.clauses), meta['kinds'][len(enc.clauses):][:3])
    ends = [v for v in enc.ball if all(v ^ 1 << k in enc.B for k in range(9))]
    assert len(ends) == 95
    out[name] = dict(window=enc.window, blocks=[(b, k, l) for b, k, l, _ in enc.blocks],
                     kinds=[kd for *_, kd in enc.blocks], ball=enc.ball, ends=ends)
    print(name, [(b, k, len(l), kd) for b, k, l, kd in enc.blocks])
assert out['Rep']['ball'] == out['Dis']['ball']
def L(xs): return '[' + ', '.join(map(str, xs)) + ']'
def lit(l): return f'pos {l}' if l > 0 else f'neg {-l}'
o0 = out['Rep']
s = """import W223G1Defs
/-! Decoding tables for the two (2,2,3) window CNFs `W223Rep.F` / `W223Dis.F` (generated by
scripts/gendata.py from wincert.Encoding).  They are untrusted hints: every use is validated by
the kernel checker `W223G1.check`. -/
namespace W223G1
open WinCNF
"""
s += f'def ballL : List Nat := {L(o0["ball"])}\n'
s += f'def endsL : List Nat := {L(o0["ends"])}\n'
for name in CASES:
    o = out[name]
    pre = name.lower()
    for t, (b, k, l) in enumerate(o['blocks']):
        s += f'/-- {o["kinds"][t]} -/\n'
        s += f'def {pre}B{t} : Block := ⟨{b}, {k}, {len(l)}, [' + ', '.join(lit(x) for x in l) + ']⟩\n'
    s += f'def blocks{name} : List Block := [' + ', '.join(f'{pre}B{t}' for t in range(len(o['blocks']))) + ']\n'
    s += f'def tab{name} : Tables := ⟨{len(o0["ball"])}, {len(o0["ends"])}, ballL, endsL, {L(o["window"])}, blocks{name}⟩\n'
s += 'end W223G1\n'
open(OUT, 'w').write(s)
