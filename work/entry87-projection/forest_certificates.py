"""Compress fixed-forest refutations in small archives and replay their uncompressed contents."""
import argparse, gzip, json, re, subprocess
from hashlib import sha256
from pathlib import Path
from tempfile import TemporaryDirectory
from zipfile import ZipFile, ZIP_STORED
from forest_face import records, solve
from solve import save


def replay(z, name, receipt, checker, tmp):
    args=[str(checker)]
    for kind in ("cnf","core"):
        raw=gzip.decompress(z.read(name+"."+kind+".gz"))
        assert sha256(raw).hexdigest()==receipt[kind+"_sha256"]
        f=tmp/kind;f.write_bytes(raw);args.append(str(f))
    check=subprocess.run(args,capture_output=True,check=True)
    assert b"s VERIFIED" in check.stdout.splitlines()
    return int(re.search(rb"using (\d+) resolution steps",check.stdout).group(1))


def run(first,stop,checker):
    cases=records()
    with TemporaryDirectory() as tmp:
        for i in range(first,stop):
            tag=f"{i}-193"; base="forest-face-proof-"+tag; archive=Path("forest-refutation-"+tag+".zip")
            receipt=Path("forest-face-"+tag+"-checked.json")
            if not archive.exists():
                if not receipt.exists():solve(cases[i],i,1500000,checker)
                r=json.loads(receipt.read_text())
                assert r["status"]=="UNSAT" and not r["dynamic"]
                files=[Path(base+"."+kind+".gz") for kind in ("cnf","core")]
                with ZipFile(archive,"w",compression=ZIP_STORED) as z:
                    for f in files:z.write(f,f.name)
                r["archive_sha256"]=sha256(archive.read_bytes()).hexdigest()
                with ZipFile(archive) as z:r["replayed_steps"]=replay(z,base,r,checker,Path(tmp))
                save(receipt,r)
                # Each file here was just generated by this invocation and its
                # compact copy has already passed another independent replay.
                for suffix in (".cnf",".core",".drat",".cnf.gz",".core.gz"):
                    Path(base+suffix).unlink()
            else:
                r=json.loads(receipt.read_text())
                assert sha256(archive.read_bytes()).hexdigest()==r["archive_sha256"]
                with ZipFile(archive) as z:assert replay(z,base,r,checker,Path(tmp))==r["replayed_steps"]
            print("Archived",i,r["replayed_steps"],flush=True)


if __name__=="__main__":
    p=argparse.ArgumentParser();p.add_argument("first",type=int);p.add_argument("stop",type=int)
    p.add_argument("--checker",type=Path,default=Path("drat-check.exe"));a=p.parse_args()
    run(a.first,a.stop,a.checker.resolve())
