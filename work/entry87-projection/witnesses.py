"""Emit one explicit nonedge witness for each of the 528 colliding interval pairs.

The generated Lean file checks local interval IDs and projected distances by kernel
reduction. Each entire row gives the relation from one interval to all later ones.
"""
import re
from pathlib import Path
from solve import paths

HERE=Path(__file__).resolve().parent
CHOSEN=[0,2,4,6,10,12,14,16,18,20,22,24,28,30,32,34,36,42,44,46,48,50,56,58,
        60,68,70,72,74,76,80,82,84]


def main():
    source,q=paths()
    lean=(HERE/"Clique.lean").read_text()
    given=re.search(r"def source : List Nat :=\s*\[([^\]]+)\]",lean).group(1)
    assert [int(x) for x in given.split(",")]==source
    z=[x&19 for x in q]
    run=[0]
    for a,b in zip(z,z[1:]):
        run.append(run[-1]+(a==b))
    rows=[]
    for k,r in enumerate(CHOSEN):
        row=[]
        for s in CHOSEN[k+1:]:
            pair=next((i,j) for i in range(len(z)) if run[i]==r
                      for j in range(i+2,len(z)) if run[j]==s and (z[i]^z[j]).bit_count()<=1)
            row.append((s,*pair))
        rows.append(row)
    assert sum(map(len,rows))==528
    out=["-- Generated by witnesses.py from the pinned bank entry.",
         "import Clique","namespace Entry87","set_option maxRecDepth 10000","",
         "def bases : Array Nat := #["+ ",".join(map(str,z))+"]",
         "def ids : Array Nat := #["+ ",".join(map(str,run))+"]",
         "def good (r : Nat) (t : Nat × Nat × Nat) : Bool :=",
         "  let (s,i,j) := t","  decide (i < 193 ∧ j < 193 ∧ i+1<j) &&",
         "    (ids[i]! == r) && (ids[j]! == s) && decide (hamming (bases[i]!) (bases[j]!) ≤ 1)",
         "def checkedConflict (r s : Nat) := ∃ i j, i<193 ∧ j<193 ∧ i+1<j ∧",
         "  ids[i]! = r ∧ ids[j]! = s ∧ hamming (bases[i]!) (bases[j]!) ≤ 1","",
         "theorem rows_sound {r : Nat} {ts : List (Nat × Nat × Nat)}",
         "    (h : ts.all (good r) = true) : ∀ s ∈ ts.map Prod.fst, checkedConflict r s := by",
         "  intro s hs","  obtain ⟨⟨s',i,j⟩, ht, rfl⟩ := List.mem_map.mp hs",
         "  have v := List.all_eq_true.mp h _ ht",
         "  simp [good, Bool.and_eq_true] at v",
         "  exact ⟨i,j,v.1.1.1.1,v.1.1.1.2.1,v.1.1.1.2.2,v.1.1.2,v.1.2,v.2⟩",""]
    (HERE/"TraceData.lean").write_text("\n".join(out+["end Entry87",""]),encoding="utf-8")
    for k,(r,row) in enumerate(zip(CHOSEN,rows)):
        out=[f"-- Generated row {k}: all later members of the clique.","import TraceData",
             "namespace Entry87","set_option maxRecDepth 10000"]
        out.append(f"def row{k} : List (Nat × Nat × Nat) := [" + ",".join(f"({s},{i},{j})" for s,i,j in row) + "]")
        out.append(f"theorem row{k}_ok : row{k}.all (good {r}) = true := by decide")
        (HERE/f"TraceRow{k}.lean").write_text("\n".join(out+["end Entry87",""]),encoding="utf-8")
    out=[f"import TraceRow{k}" for k in range(len(rows))]+["namespace Entry87","set_option maxRecDepth 10000"]
    out.extend(["","theorem checked_clique : chosen.Pairwise checkedConflict := by","  unfold chosen"])
    for k,r in enumerate(CHOSEN):
        out.extend(["  apply List.Pairwise.cons",f"  · exact rows_sound (r := {r}) row{k}_ok"])
    out.extend(["  exact .nil","",
                "theorem no_interval_lift (word : Nat → Nat) (p : Bool)",
                "    (inParity : ∀ r ∈ chosen, word r ∈ supply p)",
                "    (nonedge : ∀ i j, i<193 → j<193 → i+1<j →",
                "      2 ≤ hamming (bases[i]!) (bases[j]!) + hamming (word (ids[i]!)) (word (ids[j]!))) : False := by",
                "  apply impossible p word checkedConflict checked_clique _ inParity",
                "  intro r s h same","  obtain ⟨i,j,hi,hj,hij,hr,hs,hd⟩ := h",
                "  have sep := nonedge i j hi hj hij","  have self (x : Nat) : hamming x x = 0 := by simp [hamming]",
                "  rw [hr,hs,same,self] at sep","  omega","",
                "#print axioms checked_clique","#print axioms no_interval_lift","end Entry87",""])
    (HERE/"Concrete.lean").write_text("\n".join(out),encoding="utf-8")


if __name__=="__main__":
    main()
