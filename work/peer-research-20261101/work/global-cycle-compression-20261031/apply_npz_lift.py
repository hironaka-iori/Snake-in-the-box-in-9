"""Apply the 7-edge history prohibition to the real upstream NPZ graph.
Requires the source graph regenerated by the upstream repository. No synthetic
array is accepted as if it were the five-million-edge model.
"""
from pathlib import Path
import argparse,json,hashlib,sys
H=Path(__file__).resolve().parent
if not __debug__:raise RuntimeError('verification requires Python without -O')

def transform(a,meta,analysis,np,verify_hashes=True):
 N=meta['states'];M=meta['edges']
 if verify_hashes:
  for key,digest in meta['arrays_sha256'].items():
   if hashlib.sha256(a[key].tobytes()).hexdigest()!=digest:raise ValueError('source array hash mismatch: '+key)
 if not all(len(x)==M for x in a.values()):raise ValueError('unaligned source arrays')
 C=analysis['cycle'];ids={int(e['edge']) for e in C};nodes=sorted({int(e['u']) for e in C}|{int(e['v']) for e in C})
 assert len(C)==4 and len(nodes)==4
 for i,e in enumerate(C):
  k=e['edge'];assert int(a['U'][k])==e['u'] and int(a['V'][k])==e['v'] and int(a['weight'][k])==e['weight']
  assert C[i]['v']==C[(i+1)%4]['u']
 extra={(v,r):N+j*6+r-1 for j,v in enumerate(nodes) for r in range(1,7)}
 added=[];us=[];vs=[]
 # Preserve base rows and projection IDs; a marked edge enters run length one.
 UU=a['U'].copy();VV=a['V'].copy()
 for e in C:VV[e['edge']]=extra[e['v'],1]
 for v in nodes:
  outgoing=np.flatnonzero(a['U']==v)
  for run in range(1,7):
   for raw in outgoing:
    row=int(raw)
    if row in ids:
     if run==6:continue
     target=extra[int(a['V'][row]),run+1]
    else:target=int(a['V'][row])
    added.append(row);us.append(extra[v,run]);vs.append(target)
 add=np.array(added,dtype=np.int64)
 out={key:np.concatenate([value,value[add]]) for key,value in a.items()}
 out['U']=np.concatenate([UU,np.array(us,dtype=UU.dtype)]);out['V']=np.concatenate([VV,np.array(vs,dtype=VV.dtype)])
 projection=np.concatenate([np.arange(M,dtype=np.int64),add])
 report={'status':'HISTORY_LIFT_BUILT_NOT_A_NEW_BOUND','source_states':N,'source_edges':M,'states':N+24,'edges':len(projection),'extra_states':24,'extra_edges':len(add),'max_consecutive_marked_edges':6,'source_model_arrays':meta['arrays_sha256'],'arrays_sha256':{k:hashlib.sha256(v.tobytes()).hexdigest() for k,v in out.items()},'projection_sha256':hashlib.sha256(projection.tobytes()).hexdigest(),'source_cycle_ids':sorted(ids),'full_model_mean_recomputed':False,'global_geometry_bridge':'inherited upstream obligation remains pending','new_global_bound':None}
 return out,projection,report

if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('source_graph',type=Path);ap.add_argument('output_graph',type=Path);args=ap.parse_args()
 try:import numpy as np
 except ImportError:
  sys.path.insert(0,str(H.parent/'pylibs'));import numpy as np
 meta=json.loads((H/'upstream_proved_model.json').read_text());analysis=json.loads((H/'upstream_proved_analysis.json').read_text())
 with np.load(args.source_graph,allow_pickle=False) as z:a={k:z[k] for k in meta['arrays_sha256']}
 out,projection,report=transform(a,meta,analysis,np)
 np.savez_compressed(args.output_graph,**out);np.save(args.output_graph.with_suffix('.projection.npy'),projection)
